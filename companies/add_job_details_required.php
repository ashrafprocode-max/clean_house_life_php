// ---------- 3. تنظيف مواعيد العمل والتحقق منها ----------
//
// ⭐ لماذا نُنظّفها؟ لأن TimeOfDay في فلاتر تُنتج صيغاً مختلفة
//    مثل "8:00" أو "08:00" أو "08:00:00" أو "8:00 AM"
//    وعمود MySQL من نوع TIME يحتاج "HH:MM:SS" بالضبط
//
// ⚠️ دالة مساعدة محلية تُنظّف الوقت وتتحقق منه
//    نضعها هنا لا في functions.php لأنها خاصة بهذا الملف
$cleanTime = function (string $raw): ?string {
    // إزالة المسافات الزائدة من الطرفين
    $t = trim($raw);

    // ⭐ إزالة صيغة 12 ساعة إن أرسلتها فلاتر (AM/PM)
    // نتحقق أولاً من وجود PM لأن معالجته مختلفة
    $isPM = stripos($t, 'PM') !== false;
    $isAM = stripos($t, 'AM') !== false;
    // حذف نص AM أو PM من القيمة
    $t = trim(str_ireplace(['AM', 'PM'], '', $t));

    // تقسيم الوقت لأجزاء عند النقطتين
    $parts = explode(':', $t);

    // يجب أن يحتوي ساعة ودقيقة على الأقل
    if (count($parts) < 2) return null;

    // قراءة الساعة والدقيقة كأرقام
    $h = (int) $parts[0];
    $m = (int) $parts[1];
    // الثواني إن وُجدت وإلا صفر
    $s = isset($parts[2]) ? (int) $parts[2] : 0;

    // ⭐ تحويل صيغة 12 ساعة لصيغة 24 ساعة
    // مساءً: نُضيف 12 لكل ساعة ما عدا 12 مساءً
    if ($isPM && $h < 12) $h += 12;
    // صباحاً: 12 صباحاً تعني الساعة صفر
    if ($isAM && $h === 12) $h = 0;

    // التحقق من نطاق الساعة والدقيقة والثانية
    if ($h < 0 || $h > 23) return null;
    if ($m < 0 || $m > 59) return null;
    if ($s < 0 || $s > 59) return null;

    // إرجاع الوقت بصيغة HH:MM:SS مع أصفار بادئة
    return sprintf('%02d:%02d:%02d', $h, $m, $s);
};

