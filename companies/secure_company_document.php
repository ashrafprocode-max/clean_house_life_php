<?php
// ============================================================
// ملف: companies/secure_company_document.php
// الغرض: بوّابة آمنة لعرض مستندات الشركة الحساسة
//        (السجل التجاري / البطاقة الضريبية)
//
// ⭐ لماذا نحتاج هذا الملف؟
//   مجلدا upload/commercial_registers و upload/tax_cards
//   محجوبان بـ .htaccess فلا يُفتح أي ملف برابط مباشر
//   وهذا الملف هو الطريق الوحيد لعرضها، وهو يتحقق من الصلاحية
//   أولاً ثم يقرأ الملف من القرص ويُرسله
//
// ⭐ لا نُمرّر اسم الملف في الرابط إطلاقاً
//   بل نُمرّر نوع المستند ومعرّف الشركة، ونقرأ اسم الملف
//   من قاعدة البيانات — فلا يمكن التخمين ولا الوصول لملف آخر
//
// ⭐ يخدم طرفين بمنطق تحقق مختلف لكل واحد:
//   1. الإدارة → بتوكن X-Admin-Token (ترى مستندات أي شركة)
//   2. صاحب الشركة → بـ company_user_id (يرى مستنداته فقط)
//
// ⚠️ لماذا ملف واحد لا ملفان؟
//   لأن منطق القراءة من القرص واحد، وتكراره في ملفين يعني
//   أن أي إصلاح أمني لاحق يجب تطبيقه مرتين — وهذه وصفة لثغرة
//
// الحقول المطلوبة: type, company_id
// أنواع المستندات: commercial_register / tax_card
// الطريقة: GET
// ============================================================

// تضمين ملف الاتصال بقاعدة البيانات والدوال المساعدة
include "../connect.php";

// ============================================================
// الخطوة 1: استقبال البيانات
// ============================================================
// نوع المستند المطلوب عرضه - إجباري
$type       = filterRequest("type");
// معرّف الشركة صاحبة المستند - إجباري
$company_id = filterRequest("company_id");

// ⭐ معرّف المستخدم صاحب الشركة (للمسار الثاني: صاحب الشركة)
// يُرسله التطبيق حين لا يوجد توكن إدارة
$user_id    = filterRequest("company_user_id");

// ============================================================
// الخطوة 2: التحقق من الحقول الإجبارية
// ============================================================
// إذا نقص أي حقل نوقف التنفيذ فوراً
if (empty($type) || empty($company_id)) {
    // رسالة توضح الحقول المطلوبة
    printFailure("الحقول المطلوبة: type, company_id");
    // إيقاف التنفيذ
    exit;
}

// تحويل معرّف الشركة لرقم صحيح لحماية جملة WHERE
$company_id = (int) $company_id;

// ============================================================
// الخطوة 3: خريطة أنواع المستندات
// تربط كل نوع بعموده في قاعدة البيانات ومجلده على القرص
//
// ⚠️ هذه الخريطة هي الحماية الأساسية: لا نقبل إلا هذين النوعين
//    فلا يمكن لأحد تمرير اسم عمود أو مسار عشوائي
// ============================================================
$documentMap = [
    // ملف السجل التجاري
    'commercial_register' => [
        'column' => 'company_commercial_register_pdf',
        'folder' => 'commercial_registers',
    ],
    // ملف البطاقة الضريبية
    'tax_card' => [
        'column' => 'company_tax_card_pdf',
        'folder' => 'tax_cards',
    ],
];

// إذا كان النوع غير معروف نرفض الطلب
if (!isset($documentMap[$type])) {
    // رسالة توضح الأنواع المسموحة
    printFailure("type يجب أن يكون أحد هذه القيم: " . implode(', ', array_keys($documentMap)));
    // إيقاف التنفيذ
    exit;
}

// قراءة اسم العمود والمجلد الخاصين بهذا النوع
$column = $documentMap[$type]['column'];
$folder = $documentMap[$type]['folder'];

// ============================================================
// الخطوة 4: ⭐ تحديد هوية الطالب — إدارة أم صاحب شركة؟
//
// نفحص وجود توكن الإدارة أولاً في الهيدر أو في بيانات الطلب
// فإن وُجد نتحقق منه ونمنح صلاحية كاملة
// وإن لم يوجد ننتقل لمسار صاحب الشركة
// ============================================================
// قراءة توكن الإدارة من الهيدر المخصص
$sentAdminToken = $_SERVER['HTTP_X_ADMIN_TOKEN'] ?? '';

// إن لم يوجد في الهيدر نبحث عنه في بيانات الطلب (لتسهيل Postman)
if ($sentAdminToken === '') {
    // قراءة التوكن من حقل admin_token
    $sentAdminToken = filterRequest("admin_token");
}

// ============================================================
// ⭐⭐ الخطوة 4-أ: قراءة الرابط الموقَّع قصير العمر
//
// ⚠️ لماذا نحتاجه؟
//   المتصفح يفتح رابط PDF مباشرة (launchUrl في فلاتر)
//   ولا يستطيع إضافة هيدر X-Admin-Token إطلاقاً
//   فبلا هذا المسار يرد الملف 401 دائماً على اللوحة
//
// ⭐ ولماذا لا نضع admin_token في الرابط؟
//   لأنه توكن دائم يُسرَّب في سجل المتصفح وسجل Apache
//   بينما هذا التوقيع ينتهي بعد 15 دقيقة ولا يفتح إلا هذا المستند
// ============================================================
// التوقيع القادم في الرابط
$sentSig     = filterRequest("sig");
// وقت انتهاء صلاحية التوقيع (طابع زمني Unix)
$sentExpires = filterRequest("exp");
// معرّف الموظف الذي طلب الرابط
$sentAdminId = filterRequest("aid");

// متغير يحمل نوع الطالب لتسجيله في السجل
$requesterType = null;
// متغير يحمل بيانات الموظف إن كان الطالب من الإدارة
$currentAdmin  = null;

// ---------- المسار الأول: الإدارة ----------
// نتحقق فقط إذا أُرسل توكن إدارة فعلاً
if ($sentAdminToken !== '') {
    // ⭐ checkAdminToken تتحقق من التوكن وتوقف التنفيذ عند الفشل
    // فلا نحتاج فحصاً إضافياً بعدها
    $currentAdmin  = checkAdminToken();
    // تسجيل أن الطالب من الإدارة
    $requesterType = 'admin';
}

// ---------- ⭐⭐ المسار الثالث: رابط موقَّع من اللوحة ----------
// ⚠️ نفحصه فقط إن لم يكن الطالب من الإدارة بالتوكن
if ($requesterType !== 'admin' && $sentSig !== '' && $sentExpires !== '') {

    // ⭐ قراءة السر المُعرَّف في connect.php
    global $admin_secret_key;

    // ⚠️ التحقق أن التوقيع لم تنتهِ صلاحيته
    // ⭐ نستخدم time() هنا لأن المقارنة مع طابع Unix لا مع MySQL
    //    فاختلاف المنطقة الزمنية لا يؤثر على طوابع Unix إطلاقاً
    if ((int)$sentExpires < time()) {
        // رسالة توضح انتهاء الرابط مع الحل
        printFailure(
            "انتهت صلاحية رابط المستند — أعد تحميل الصفحة واضغط عرض مرة أخرى",
            401
        );
        // إيقاف التنفيذ
        exit;
    }

    // ⚠️ حماية من رابط بصلاحية طويلة مُصنَّعة يدوياً
    // ⭐ نرفض أي رابط أطول من ساعة حتى لو كان توقيعه صحيحاً
    if ((int)$sentExpires > time() + 3600) {
        // رسالة موحّدة لا تكشف السبب
        printFailure("رابط المستند غير صالح", 401);
        // إيقاف التنفيذ
        exit;
    }

    // ⭐ إعادة بناء نص التوقيع بنفس ترتيب مكوّناته في اللوحة
    // ⚠️ أي اختلاف في الترتيب أو الفواصل يُفشل المقارنة
    $expectedPayload = $type . '|' . $company_id . '|'
                     . $sentAdminId . '|' . $sentExpires;

    // حساب التوقيع المتوقَّع بالسر نفسه
    $expectedSig = hash_hmac('sha256', $expectedPayload, $admin_secret_key);

    // ⭐ مقارنة آمنة ضد هجوم التوقيت
    // ⚠️ == تتوقف عند أول حرف مختلف فيمكن تخمين التوقيع حرفاً حرفاً
    if (!hash_equals($expectedSig, $sentSig)) {
        // رسالة موحّدة لا تكشف السبب
        printFailure("رابط المستند غير صالح", 401);
        // إيقاف التنفيذ
        exit;
    }

    // ============================================================
    // ⭐ التحقق أن الموظف ما زال مفعّلاً
    //
    // ⭐ لماذا؟ لأن التوقيع صالح 15 دقيقة
    //    ولو عُطّل الموظف خلالها وجب أن يتوقف رابطه فوراً
    // ============================================================
    // تجهيز استعلام جلب الموظف
    $stmtSigAdmin = $con->prepare(
        "SELECT admin_id, admin_full_name, admin_is_active
         FROM admin_users WHERE admin_id = ? LIMIT 1"
    );
    // تنفيذ الاستعلام بمعرّف الموظف من الرابط
    $stmtSigAdmin->execute([(int)$sentAdminId]);
    // جلب صف الموظف
    $sigAdmin = $stmtSigAdmin->fetch(PDO::FETCH_ASSOC);

    // ⚠️ نرفض إن لم يوجد الموظف أو كان معطّلاً
    if (!$sigAdmin || (int)$sigAdmin['admin_is_active'] !== 1) {
        // رسالة توضح تعطّل الحساب
        printFailure("هذا الحساب معطّل — لا يمكن عرض المستند", 403);
        // إيقاف التنفيذ
        exit;
    }

    // ⭐ منح صلاحية الإدارة الكاملة لهذا الطلب
    $currentAdmin  = $sigAdmin;
    // تسجيل أن الطالب جاء برابط موقَّع (يظهر في السجل)
    $requesterType = 'admin_signed';
}

// ============================================================
// الخطوة 5: قراءة اسم الملف ومالك الشركة من قاعدة البيانات
//
// ⚠️ اسم العمود يأتي من خريطتنا الثابتة وليس من المستخدم
//    لذلك دمجه في نص الاستعلام آمن تماماً هنا
// ============================================================
// تجهيز استعلام محمي لجلب اسم الملف ومعرّف المالك
$stmt = $con->prepare(
    "SELECT
        company_id,
        company_user_id,
        company_name,
        $column AS file_name
     FROM company_registering
     WHERE company_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف الشركة
$stmt->execute([$company_id]);
// جلب صف النتيجة
$row = $stmt->fetch(PDO::FETCH_ASSOC);

// إذا لم توجد الشركة نرفض الطلب
if (!$row) {
    // رسالة توضح أن الشركة غير موجودة
    printFailure("الشركة غير موجودة", 404);
    // إيقاف التنفيذ
    exit;
}

// ---------- المسار الثاني: صاحب الشركة ----------
// ⭐ نتحقق فقط إن لم يكن الطالب من الإدارة (بتوكن أو برابط موقَّع)
// ⚠️ أضفنا admin_signed وإلا سقط الرابط الموقَّع في مسار صاحب الشركة
//    وهذا هو سبب رسالة 401 التي ظهرت لك
if ($requesterType !== 'admin' && $requesterType !== 'admin_signed') {

    // إذا لم يُرسل معرّف المستخدم نرفض الطلب
    if ($user_id === '') {
        // رسالة توضح أن التوثيق مطلوب
        printFailure("مطلوب تسجيل الدخول لعرض هذا المستند", 401);
        // إيقاف التنفيذ
        exit;
    }

    // ⭐ التحقق أن الطالب هو مالك الشركة فعلاً
    // وهذا يمنع أي شخص من قراءة مستندات شركة غيره
    if ((int)$row['company_user_id'] !== (int)$user_id) {
        // رسالة توضح عدم الصلاحية
        printFailure("لا تملك صلاحية عرض مستندات هذه الشركة", 403);
        // إيقاف التنفيذ
        exit;
    }

    // تسجيل أن الطالب صاحب الشركة
    $requesterType = 'owner';
}

// ⚠️⚠️ تنبيه أمني مهم:
//   مسار صاحب الشركة يعتمد على company_user_id القادم من الطلب
//   ولأن checkAuthenticate() معطّلة في connect.php (السطر ~138)
//   فلا يوجد ما يمنع شخصاً من تمرير معرّف مستخدم آخر
//   والحماية الحقيقية تحتاج تفعيل توكن المستخدم (مؤجَّل بطلبك)
//
//   ⭐ الخيار الأقوى (غير مُفعَّل): قصر البوّابة على الإدارة وحدها
//   ولتفعيله أزل التعليق عن السطرين التاليين
// if ($requesterType !== 'admin') {
//     printFailure("عرض المستندات متاح للإدارة فقط", 403);
//     exit;
// }

// ============================================================
// الخطوة 6: التحقق من أن المستند مرفوع فعلاً
// ============================================================
// إذا كان العمود فارغاً فالمستند لم يُرفع (وهو اختياري)
if (empty($row['file_name'])) {
    // رسالة توضح أن المستند غير مرفوع
    printFailure("هذا المستند غير مرفوع لهذه الشركة", 404);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 7: تنظيف اسم الملف من أي محاولة تسلّق للمجلدات
//
// basename تُزيل أي مسار مثل ../../ فلا يمكن قراءة ملف خارج المجلد
// ============================================================
// استخراج اسم الملف فقط بدون أي مسار
$fileName = basename($row['file_name']);

// بناء المسار الكامل للملف على القرص
$filePath = __DIR__ . "/../upload/" . $folder . "/" . $fileName;

// ============================================================
// الخطوة 8: التحقق من وجود الملف فعلياً على القرص
// ============================================================
// قد يكون السجل موجوداً في قاعدة البيانات والملف محذوفاً
if (!file_exists($filePath) || !is_file($filePath)) {
    // رسالة توضح أن الملف مفقود من السيرفر
    printFailure("ملف المستند مفقود من السيرفر", 404);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 9: تحديد نوع المحتوى حسب امتداد الملف
// ============================================================
// استخراج الامتداد وتحويله لحروف صغيرة
$extension = strtolower(pathinfo($fileName, PATHINFO_EXTENSION));

// خريطة الامتدادات المسموحة وأنواع محتواها
$mimeMap = [
    // الصيغة الأساسية للمستندات التجارية
    'pdf'  => 'application/pdf',
    // ⭐ نقبل الصور أيضاً لأن بعض أصحاب الشركات قد يصوّرون السجل
    // (الرفع نفسه يقبل PDF فقط حالياً، وهذا للتوافق المستقبلي)
    'jpg'  => 'image/jpeg',
    'jpeg' => 'image/jpeg',
    'png'  => 'image/png',
    'webp' => 'image/webp',
];

// إذا كان الامتداد غير مسموح نرفض العرض
if (!isset($mimeMap[$extension])) {
    // رسالة توضح أن نوع الملف غير مدعوم
    printFailure("نوع المستند غير مدعوم", 415);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 10: بناء اسم ملف واضح للتنزيل
//
// ⭐ اسم الملف على القرص عشوائي مثل 8412_1788.pdf
//    فنبني اسماً مفهوماً يظهر للموظف عند التنزيل
// ============================================================
// ترجمة نوع المستند لاسم عربي واضح
$typeLabel = $type === 'commercial_register' ? 'commercial_register' : 'tax_card';

// بناء اسم الملف المعروض (اسم النوع + معرّف الشركة + الامتداد)
$displayName = $typeLabel . '_company_' . $company_id . '.' . $extension;

// ============================================================
// الخطوة 11: إرسال الملف
//
// ⚠️ نُلغي هيدر Content-Type: application/json الذي ضبطه connect.php
//    لأننا نُرسل ملفاً وليس JSON
// ============================================================
// إزالة أي هيدرات سابقة قد تُفسد الملف
if (!headers_sent()) {
    // حذف هيدر نوع المحتوى الذي ضبطه connect.php
    header_remove('Content-Type');
}

// ضبط نوع المحتوى الصحيح للملف
header('Content-Type: ' . $mimeMap[$extension]);
// إخبار المتصفح بحجم الملف
header('Content-Length: ' . filesize($filePath));
// عرض الملف داخل الصفحة وليس تنزيله إجبارياً
header('Content-Disposition: inline; filename="' . $displayName . '"');
// ⚠️ منع تخزين المستند الحساس في كاش المتصفح أو الوسائط
header('Cache-Control: private, no-store, no-cache, must-revalidate');
header('Pragma: no-cache');
// منع المتصفح من تخمين نوع المحتوى (حماية ضد XSS)
header('X-Content-Type-Options: nosniff');

// ⭐ تسجيل من قرأ المستند في سجل السيرفر للمراجعة الأمنية لاحقاً
error_log(sprintf(
    "SECURE_DOC_ACCESS type=%s company_id=%d requester=%s id=%s",
    $type,
    $company_id,
    $requesterType,
        // ⭐ نُسجّل معرّف الموظف في مساري الإدارة معاً
    // ⚠️ بلا هذا يُطبع معرّف فارغ في سجل الرابط الموقَّع
    in_array($requesterType, ['admin', 'admin_signed'], true)
        ? $currentAdmin['admin_id'] : $user_id
));

// قراءة الملف من القرص وإرساله للمتصفح مباشرة
readfile($filePath);
// إيقاف التنفيذ فوراً حتى لا يُضاف أي محتوى بعد الملف
exit;
?>