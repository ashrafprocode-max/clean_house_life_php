<?php
// ============================================================
// ملف: payments/customer/payment_callback.php
// الغرض: استقبال عودة العميل من صفحة Paymob (Callback)
//
// كيفية العمل:
//   بعد إدخال بيانات الكارت أو المحفظة، يُعيد Paymob توجيه المتصفح
//   إلى هذا الملف مع كل بيانات العملية + توقيع hmac في الرابط.
//
// خطوات الأمان:
//   1) نقرأ الـ Query String يدوياً حتى لا تُفسَد أسماء الحقول.
//   2) نتحقق من توقيع HMAC قبل أي تحديث في قاعدة البيانات.
//   3) نحدّث الدفع والحجز مرة واحدة فقط (Idempotent).
//   4) نُعيد توجيه العميل لصفحة نتيجة عربية واضحة.
//
// ملاحظة:
//   هذا الملف لا يعتمد عليه وحده في تأكيد الدفع، لأن العميل قد يُغلق
//   المتصفح قبل العودة. لذلك يوجد Webhook مستقل (payment_webhook.php)
//   هو المصدر الموثوق النهائي.
// ============================================================

// ربط قاعدة البيانات والدوال العامة
include "../../connect.php";

// تضمين دوال الدفع المساعدة
include "../includes/payment_helper.php";

// ============================================================
// الخطوة 1: قراءة الاستعلام الخام والحفاظ على النقاط
// ============================================================
$flat = parseRawQuery($_SERVER['QUERY_STRING'] ?? '');

// توقيع HMAC القادم من Paymob
$receivedHmac = (string) ($flat['hmac'] ?? '');

// ============================================================
// الخطوة 2: التحقق من التوقيع قبل أي معالجة
// ============================================================
$hmacValid = paymobVerifyHmac($flat, $receivedHmac);

// تجهيز الكائن الموحّد
$obj = normalizeCallbackObject($flat);

// الرقم المرجعي لعملية الدفع
$reference = resolvePaymentReference($con, $obj);

// ============================================================
// الخطوة 3: تسجيل الحدث في جدول سجلات البوابة
// ============================================================
try {
    // نحفظ النص الخام للمراجعة حتى لو رُفض التوقيع
    logGatewayPayload(
        $con,
        'callback',
        $reference,
        json_encode($flat, JSON_UNESCAPED_UNICODE),
        $hmacValid
    );
} catch (Throwable $e) {
    // لا نوقف العملية بسبب فشل التسجيل
}

// ============================================================
// الخطوة 4: إذا كان التوقيع غير صالح نُظهر صفحة رفض
// ============================================================
if (!$hmacValid || $reference === null) {
    // توجيه لصفحة النتيجة بحالة invalid
    $url = paymentResultUrl($reference ?? 'UNKNOWN') . '&state=invalid';
    header('Location: ' . $url);
    exit;
}

// ============================================================
// الخطوة 5: قراءة نجاح العملية ورقم المعاملة
// ============================================================
$success = gatewayBool($flat['success'] ?? false);

// رقم المعاملة لدى Paymob
$txnId = (string) ($flat['id'] ?? '');

// ============================================================
// الخطوة 6: تطبيق النتيجة على الدفع والحجز
// ============================================================
$result = applyPaymentResult($con, $reference, $success, $txnId, $obj);

// ============================================================
// الخطوة 7: توجيه العميل لصفحة النتيجة
// ============================================================
$state = $success ? 'paid' : 'failed';

// إذا فشل التحديث لأي سبب نُظهر حالة pending لتُعيد Flutter الاستعلام
if (empty($result['ok'])) {
    $state = 'pending';
}

// التوجيه النهائي
header('Location: ' . paymentResultUrl($reference) . '&state=' . $state);
exit;
