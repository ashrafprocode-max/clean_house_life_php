<?php
/**
 * إرسال رمز OTP للتحقق من رقم الهاتف
 * POST: users_phone****
 */
// ============================================================
// ملف: auth/send_otp.php
// الغرض: إرسال كود OTP عبر Twilio SMS وواتساب معاً
// الطريقة: POST
// الحقول المطلوبة: users_phone
// ملاحظة: SMS تبقى كما هي؛ واتساب يعمل بجانبها. Trial يقيّد الأرقام غير الموثّقة
// ============================================================

// تضمين ملف الاتصال بقاعدة البيانات والوظائف المساعدة
include "../connect.php";

// ============================================================
// الخطوة 1: استقبال رقم الهاتف من الطلب
// ============================================================
$phone = filterRequest("users_phone");// رقم الهاتف المُرسَل من Flutter

// ============================================================
// الخطوة 2: التحقق من وجود رقم الهاتف
// ============================================================
if (empty($phone)) {
    printFailure("Phone number is required");
    exit;
}

// ============================================================
// الخطوة 3: تنظيف رقم الهاتف
// إزالة كل شيء غير الأرقام و + في البداية
// ============================================================
$phone = preg_replace('/[^0-9+]/', '', $phone);

// ============================================================
// الخطوة 4: تحويل رقم الهاتف لصيغة دولية مع كود مصر +20
// أمثلة التحويل:
//   01122449170  → +201122449170
//   1122449170   → +201122449170
//   +201122449170 → +201122449170 (لا تغيير)
//   2011224401170 → +2011224401170 (تُكمَّل بـ +)
// ============================================================
if (strpos($phone, '+') !== 0) {
    // الرقم لا يبدأ بـ +

    if (substr($phone, 0, 2) === '20') {
        // يبدأ بـ 20 (كود مصر بدون +)، نضيف + فقط
        $phone = '+' . $phone;

    } elseif (substr($phone, 0, 1) === '0') {
        // يبدأ بصفر مثل 01122449170، نستبدل الصفر بـ +20
        $phone = '+20' . substr($phone, 1);

    } else {
        // رقم بدون صفر ولا كود دولة مثل 1122449170
        $phone = '+20' . $phone;
    }
}

// ============================================================
// الخطوة 5: التحقق من طول الرقم الدولي
// الرقم المصري الصحيح: +201XXXXXXXXX = 13 رقم مع +
// ============================================================
if (strlen($phone) < 12 || strlen($phone) > 15) {
    printFailure("Invalid phone number format");
    exit;
}

// ============================================================
// الخطوة 6: توليد كود OTP عشوائي من 6 أرقام
// str_pad يضمن أن الرقم دائماً 6 خانات (مثلاً 034521)
// ============================================================
$otp_code = str_pad(random_int(0, 999999), 6, '0', STR_PAD_LEFT);

// ============================================================
// الخطوة 7: تحديد وقت انتهاء صلاحية الـ OTP (5 دقائق)
// strtotime('+5 minutes') يحسب الوقت الحالي + 5 دقائق
// ============================================================
$expires_at = date('Y-m-d H:i:s', strtotime('+5 minutes'));

global $con;

// ============================================================
// الخطوة 8: حذف أي OTP قديم لهذا الرقم
// لا نريد تراكم OTP قديمة في قاعدة البيانات
// ============================================================
$stmt = $con->prepare("DELETE FROM otp_codes WHERE otp_phone = ?");
$stmt->execute([$phone]);

// ============================================================
// الخطوة 9: حفظ الـ OTP الجديد في قاعدة البيانات
// نحفظ: الهاتف، الكود، وقت الانتهاء
// ============================================================
$stmt = $con->prepare("INSERT INTO otp_codes (otp_phone, otp_code, otp_expires_at) VALUES (?, ?, ?)");
$stmt->execute([$phone, $otp_code, $expires_at]);

// ============================================================
// الخطوة 10: إرسال الـ OTP عبر SMS وواتساب معاً
// SMS تبقى كما هي (قد تفشل قبل الاشتراك)
// واتساب يُرسل بجانبها بنفس الكود
// ============================================================
$otpChannels = sendOtpChannels($phone, $otp_code);
$sms_sent = !empty($otpChannels['ok']);

// ============================================================
// الخطوة 11: التحقق من بيئة التشغيل
// في بيئة Dev المحلية نرجع الكود مباشرة للاختبار
// في بيئة Prod نخفي الكود للأمان
// ============================================================
$serverName = $_SERVER['SERVER_NAME'] ?? '';
$isDev = in_array($serverName, ['localhost', '127.0.0.1', '::1'])
    || strpos($serverName, '192.168.') === 0;

if ($sms_sent) {
    // ============================================================
    // النجاح: وصلت الرسالة عبر SMS أو واتساب أو الاثنين
    // ============================================================
    echo json_encode(array(
        "status" => "success",
        "message" => "OTP sent successfully",
        "expires_in" => 300, // مدة الصلاحية بالثواني (5 دقائق)
        // نُعيد الكود فقط في بيئة Dev للاختبار
        "otp_code" => $isDev ? $otp_code : null,
        "channels" => array(
            "sms" => !empty($otpChannels['sms']),
            "whatsapp" => !empty($otpChannels['whatsapp']),
        ),
    ));

} else {
    // ============================================================
    // فشل إرسال SMS (مشكلة في Twilio أو Trial Account)
    // في بيئة Dev: نرجع الكود للاختبار بدون SMS
    // في بيئة Prod: نُبلغ بالفشل
    // ============================================================
    if ($isDev) {
        // بيئة محلية: نرجع الكود للاختبار بدون SMS
        echo json_encode(array(
            "status" => "success",
            "message" => "OTP saved (SMS not configured - use code for testing)",
            "expires_in" => 300,
            "otp_code" => $otp_code, // نُعيد الكود للاختبار
        ));
    } else {
        // بيئة Prod: نُبلغ بفشل الإرسال
        echo json_encode(array(
            "status" => "error",
            "message" => "Failed to send OTP via SMS and WhatsApp. Please check Twilio configuration.",
            "expires_in" => 300,
            "otp_code" => null, // نخفي الكود في Prod
        ));
    }
}
?>