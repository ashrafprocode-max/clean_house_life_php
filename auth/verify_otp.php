<?php
// ============================================================
// ملف: auth/verify_otp.php
// الغرض: التحقق من كود OTP للتسجيل الجديد
//
// ⭐ المشكلة التي كانت موجودة (سبب فشل verify_otp):
//   - send_otp.php يحفظ الرقم في DB بصيغة: +201122449170
//   - verify_otp.php كان يبحث بصيغة: 01122449170 (بدون +20)
//   - لذلك كان الـ query يرجع 0 نتائج دائماً رغم صحة الكود!
//
// ✅ الحل: تحويل الرقم القادم من Flutter لنفس الصيغة الدولية
//         التي حفظها send_otp.php في قاعدة البيانات
// ============================================================

// تضمين ملف الاتصال بقاعدة البيانات والدوال المساعدة
include "../connect.php";

// ============================================================
// الخطوة 1: استقبال البيانات من Flutter
// ============================================================
$phone    = filterRequest("phone");    // رقم الهاتف من Flutter
$otp_code = filterRequest("otp_code"); // الكود الذي كتبه المستخدم

// ============================================================
// الخطوة 2: التحقق من وجود البيانات
// ============================================================
if (empty($phone) || empty($otp_code)) {
    printFailure("Phone and OTP code are required");
    exit;
}

// ============================================================
// الخطوة 3: تنظيف البيانات
// - الرقم: نبقي الأرقام و + فقط
// - الكود: أرقام فقط
// ============================================================
$phone    = preg_replace('/[^0-9+]/', '', $phone);
$otp_code = preg_replace('/[^0-9]/', '', $otp_code);

// ============================================================
// الخطوة 4: التحقق من طول الكود
// ============================================================
if (strlen($otp_code) !== 6) {
    printFailure("Invalid OTP format");
    exit;
}

// ============================================================
// الخطوة 5: ⭐ تحويل الرقم لصيغة دولية للبحث في otp_codes
// send_otp.php حفظ الرقم بـ +201122449170
// نحن نحتاج نفس الصيغة للبحث
// ============================================================
$phone_international = $phone; // نسخة دولية للبحث في otp_codes

if (strpos($phone_international, '+') !== 0) {
    if (substr($phone_international, 0, 2) === '20') {
        // 201122449170 → +201122449170
        $phone_international = '+' . $phone_international;
    } elseif (substr($phone_international, 0, 1) === '0') {
        // 01122449170 → +201122449170
        $phone_international = '+20' . substr($phone_international, 1);
    } else {
        // 1122449170 → +201122449170
        $phone_international = '+20' . $phone_international;
    }
}

// ============================================================
// الخطوة 6: تحويل الرقم لصيغة محلية للبحث في جدول users
// جدول users يحفظ الرقم بـ 01122449170 (بدون +20)
// ============================================================
$phone_local = $phone_international;
if (strpos($phone_local, '+20') === 0) {
    // +201122449170 → 01122449170
    $phone_local = '0' . substr($phone_local, 3);
}

// ============================================================
// الخطوة 7: البحث في otp_codes بالصيغة الدولية
// نبحث بنفس الصيغة التي حفظها send_otp.php
// ============================================================
$stmt = $con->prepare(
    "SELECT * FROM otp_codes
     WHERE otp_phone = ? AND otp_code = ?
     ORDER BY otp_created_at DESC
     LIMIT 1"
);
$stmt->execute([$phone_international, $otp_code]);
$count = $stmt->rowCount();

// ============================================================
// الخطوة 8: التحقق من النتيجة
// ============================================================
if ($count > 0) {

    // ============================================================
    // الخطوة 9: تحديث users_approve = 1
    // نجرب الصيغة المحلية أولاً ثم الدولية
    // ============================================================
    $stmtUpdate = $con->prepare(
        "UPDATE users SET users_approve = '1' WHERE users_phone = ?"
    );

    // جرب بالصيغة المحلية: 01122449170
    $stmtUpdate->execute([$phone_local]);

    // إذا لم يجد مستخدم، جرب الصيغة الدولية: +201122449170
    if ($stmtUpdate->rowCount() === 0) {
        $stmtUpdate->execute([$phone_international]);
    }

    // ============================================================
    // الخطوة 10: حذف OTP المستخدم من قاعدة البيانات
    // ============================================================
    $stmtDelete = $con->prepare(
        "DELETE FROM otp_codes WHERE otp_phone = ?"
    );
    $stmtDelete->execute([$phone_international]);

    // ============================================================
    // الخطوة 11: إرسال رد النجاح
    // ============================================================
    echo json_encode([
        "status"  => "success",
        "message" => "Phone verified successfully",
    ]);
} else {
    // الكود غير صحيح أو منتهي الصلاحية
    printFailure("Invalid or expired OTP");
}
?>