<?php
// ============================================================
// ملف: admin/service_timing/add_service_timing.php
// الغرض: إضافة نوع دوام جديد في جدول service_timing من لوحة الإدارة
//
// ⭐ أنواع الدوام مثل: إقامة كاملة، يومي، ساعات، أسبوعي، شهري
//    وهي التي يختارها مقدم الخدمة عند تسعير تخصصه
//
// ⚠️ هذا الملف للإضافة فقط
//    التعطيل (الحذف الناعم) في: delete_service_timing.php
//    التعديل في: edit_service_timing.php
//    العرض في: list_service_timing.php
//
// ⭐ التوقيت الجديد يُحفظ مفعّلاً دائماً:
//    timing_is_active = 1  → ظاهر ويُختار فور إنشائه
//
// الحقول الإجبارية: timing_name_ar, timing_name_en
// الطريقة: POST
// الصلاحية المطلوبة: catalog.manage
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/service_timing)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ catalog.manage يملكها: owner و manager
//    ولا يملكها: support و accountant
//    لأن تغيير أنواع الدوام يغيّر شكل التطبيق لكل المستخدمين
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج
requirePermission($currentAdmin, 'catalog.manage');

// معرّف الموظف المنفّذ مأخوذ من التوكن لا من الطلب
$adminId = (int) $currentAdmin['admin_id'];

// ============================================================
// الخطوة 2: استقبال بيانات التوقيت الجديد
// ============================================================
// الاسم العربي لنوع الدوام - إجباري
$timing_name_ar = trim(filterRequest("timing_name_ar"));
// الاسم الإنجليزي لنوع الدوام - إجباري
$timing_name_en = trim(filterRequest("timing_name_en"));

// ============================================================
// الخطوة 3: التحقق من الحقول الإجبارية
// ============================================================
// نستخدم === '' وليس empty لأن empty ترفض الرقم صفر بالخطأ
if ($timing_name_ar === '' || $timing_name_en === '') {
    // رسالة توضح الحقول المطلوبة
    printFailure("الحقول المطلوبة: timing_name_ar, timing_name_en");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: التحقق من طول الاسمين
// لأن العمودين varchar(100) يرفضان أي نص أطول
// ============================================================
// قياس طول الاسم العربي بالأحرف مع دعم العربية عبر mb_strlen
if (mb_strlen($timing_name_ar) > 100) {
    // رسالة توضح الحد الأقصى المسموح
    printFailure("timing_name_ar يجب ألا يتجاوز 100 حرف");
    // إيقاف التنفيذ
    exit;
}

// قياس طول الاسم الإنجليزي
if (mb_strlen($timing_name_en) > 100) {
    // رسالة توضح الحد الأقصى المسموح
    printFailure("timing_name_en يجب ألا يتجاوز 100 حرف");
    // إيقاف التنفيذ
    exit;
}

// الحد الأدنى حتى لا يُحفظ حرف واحد بلا معنى
if (mb_strlen($timing_name_ar) < 2) {
    // رسالة توضح الحد الأدنى للاسم العربي
    printFailure("الاسم العربي يجب أن يكون حرفين على الأقل");
    // إيقاف التنفيذ
    exit;
}

// الحد الأدنى للاسم الإنجليزي
if (mb_strlen($timing_name_en) < 2) {
    // رسالة توضح الحد الأدنى للاسم الإنجليزي
    printFailure("الاسم الإنجليزي يجب أن يكون حرفين على الأقل");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 5: منع تكرار اسم نوع الدوام
// ⭐ نفحص المفعّل والمعطّل معاً حتى لا يُنشأ توقيت بنفس الاسم
//    بينما صف قديم معطّل يحمل نفس التسمية
// ============================================================
// استعلام يبحث عن نفس الاسم العربي أو الإنجليزي
$stmtDup = $con->prepare(
    "SELECT timing_id, timing_name_ar, timing_is_active
     FROM service_timing
     WHERE timing_name_ar = ? OR timing_name_en = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بالاسمين
$stmtDup->execute([$timing_name_ar, $timing_name_en]);
// جلب الصف المكرر إن وُجد
$duplicate = $stmtDup->fetch(PDO::FETCH_ASSOC);

// إذا وُجد اسم مطابق نرفض الإضافة
if ($duplicate) {
    // نميّز الرسالة إن كان التوقيت المكرر معطّلاً حتى يعيد الموظف تفعيله
    $dupHint = ((int) ($duplicate['timing_is_active'] ?? 1) === 0)
        ? " — نوع الدوام موجود لكنه معطّل، فعّله بدلاً من إنشاء نوع جديد"
        : "";
    // رسالة توضح أن الاسم مستخدم بالفعل
    printFailure("اسم نوع الدوام مستخدم بالفعل" . $dupHint, 409);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 6: إدخال التوقيت في جدول service_timing
//
// ⭐ timing_is_active = 1 دائماً عند الإنشاء
//    النوع الجديد يظهر فوراً في قوائم التطبيق
//    والتعطيل يتم لاحقاً من delete_service_timing.php وليس من هنا
// ============================================================
// تجهيز مصفوفة البيانات بأسماء الأعمدة الحقيقية في الجدول
$insertData = [
    // الاسم العربي لنوع الدوام
    "timing_name_ar"   => $timing_name_ar,
    // الاسم الإنجليزي لنوع الدوام
    "timing_name_en"   => $timing_name_en,
    // ⭐ مفعّل من لحظة إنشائه — التعطيل يتم من delete_service_timing.php
    "timing_is_active" => 1,
];

// تنفيذ عملية الإدخال باستخدام دالتك الموحدة مع false لمنع طباعة JSON مرتين
$result = insertData("service_timing", $insertData, false);

// ============================================================
// الخطوة 7: إرسال الرد النهائي
// ============================================================
// التحقق من نجاح عملية الإدخال
if ($result > 0) {

    // قراءة المعرّف الذي أنشأته قاعدة البيانات تلقائياً
    $newTimingId = (int) $con->lastInsertId();

    // ============================================================
    // تسجيل الإجراء في سجل النشاط الإداري
    // ============================================================
    // تسجيل إضافة نوع الدوام
    logAdminActivity(
        // بيانات الموظف المنفّذ
        $currentAdmin,
        // نوع الإجراء
        'create_service_timing',
        // نوع الكيان
        'service_timing',
        // معرّف التوقيت الجديد
        $newTimingId,
        // تفاصيل المراجعة
        [
            // الاسم العربي
            "name_ar" => $timing_name_ar,
            // الاسم الإنجليزي
            "name_en" => $timing_name_en,
        ]
    );

    // إرسال JSON يحتوي بيانات التوقيت الجديد
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // رسالة نجاح بالعربية جاهزة للعرض في اللوحة
        "message" => "تم إضافة نوع الدوام بنجاح",
        // بيانات التوقيت المُضاف
        "data"    => [
            // المعرّف الذي أنشأته قاعدة البيانات تلقائياً
            "timing_id"        => $newTimingId,
            // الاسم العربي
            "timing_name_ar"   => $timing_name_ar,
            // الاسم الإنجليزي
            "timing_name_en"   => $timing_name_en,
            // ⭐ مفعّل — يظهر للمستخدمين ويمكن اختياره
            "timing_is_active" => 1,
            // من أضاف هذا النوع (للسجل)
            "created_by"       => $currentAdmin['admin_full_name'],
        ],
    ]);
} else {
    // في حالة فشل الإدخال نُرجع رسالة فشل واضحة
    printFailure("فشل إضافة نوع الدوام، يرجى المحاولة مرة أخرى");
}
?>
