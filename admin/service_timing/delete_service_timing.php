<?php
// ============================================================
// ملف: admin/service_timing/delete_service_timing.php
// الغرض: تعطيل نوع دوام من لوحة الإدارة (حذف ناعم)
//
// ⚠️⚠️ لا يوجد DELETE فعلي في هذا الملف إطلاقاً
//      لأن حذف صف يترك provider_services.ps_timing_id يشير لتوقيت مفقود
//      فتظهر خدمات بلا اسم دوام في شاشة البحث وقد ينهار أي JOIN
//      والجدول عليه FOREIGN KEY ... ON DELETE CASCADE
//      فحذف التوقيت قد يمسح خدمات مقدّمي الخدمة المرتبطة به
//
// ⭐ البديل المعتمد: التعطيل
//    timing_is_active = 0  → الصف يبقى فتعمل كل الـ JOINs
//                           لكن النوع لا يظهر في قوائم الاختيار الجديدة
//
// ⭐ إعادة التفعيل تتم من edit_service_timing.php بإرسال timing_is_active = 1
//
// الحقل الإجباري: timing_id
// الطريقة: POST
// الصلاحية المطلوبة: catalog.manage
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/service_timing)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ catalog.manage يملكها: owner و manager
//    ولا يملكها: support و accountant
//    لأن إخفاء نوع دوام يغيّر شكل التطبيق لكل المستخدمين
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج
requirePermission($currentAdmin, 'catalog.manage');

// ============================================================
// الخطوة 2: استقبال معرّف التوقيت والتحقق منه
// ============================================================
// معرّف نوع الدوام المراد تعطيله - إجباري
$timing_id = filterRequest("timing_id");

// إذا لم يُرسل المعرّف نوقف التنفيذ فوراً
if ($timing_id === '') {
    // رسالة توضح الحقل المطلوب
    printFailure("الحقل timing_id مطلوب لتعطيل نوع الدوام");
    // إيقاف التنفيذ
    exit;
}

// تحويل المعرّف لرقم صحيح لحماية جملة WHERE من أي محتوى غير رقمي
$timing_id = (int) $timing_id;

// لا نقبل صفراً لأن AUTO_INCREMENT يبدأ من 1
if ($timing_id < 1) {
    // رسالة توضح أن المعرّف غير صالح
    printFailure("timing_id غير صالح");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 3: جلب التوقيت للتأكد أنه موجود قبل التعطيل
// ============================================================
// تجهيز استعلام محمي لجلب الصف الحالي
$stmtTiming = $con->prepare(
    "SELECT timing_id, timing_name_ar, timing_name_en, timing_is_active
     FROM service_timing
     WHERE timing_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف التوقيت
$stmtTiming->execute([$timing_id]);
// جلب صف التوقيت
$targetTiming = $stmtTiming->fetch(PDO::FETCH_ASSOC);

// إذا لم يوجد التوقيت نرفض التعطيل
if (!$targetTiming) {
    // رسالة توضح أن نوع الدوام غير موجود
    printFailure("نوع الدوام غير موجود", 404);
    // إيقاف التنفيذ
    exit;
}

// إذا كان معطّلاً مسبقاً نُخبر الموظف بدل تكرار التحديث
if (isset($targetTiming['timing_is_active']) &&
    (int) $targetTiming['timing_is_active'] === 0) {
    // رسالة توضح أن النوع معطّل بالفعل
    printFailure("نوع الدوام معطّل بالفعل", 409);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: التحديث — timing_is_active = 0 فقط
//
// ⚠️ لا DELETE حتى لا تُمسح خدمات مقدّمي الخدمة بـ ON DELETE CASCADE
// ============================================================
// تجهيز استعلام التعطيل المحمي
$stmtOff = $con->prepare(
    "UPDATE service_timing
     SET timing_is_active = 0
     WHERE timing_id = ?
     LIMIT 1"
);
// تنفيذ التحديث بمعرّف التوقيت
$stmtOff->execute([$timing_id]);

// ============================================================
// الخطوة 5: تسجيل الإجراء في سجل النشاط الإداري
// ============================================================
// تسجيل تعطيل نوع الدوام باسم الموظف المنفّذ
logAdminActivity(
    // بيانات الموظف المنفّذ
    $currentAdmin,
    // نوع الإجراء
    'deactivate_service_timing',
    // نوع الكيان
    'service_timing',
    // معرّف التوقيت المعطّل
    $timing_id,
    // تفاصيل المراجعة
    [
        // الاسم العربي
        "name_ar" => $targetTiming['timing_name_ar'],
        // الاسم الإنجليزي
        "name_en" => $targetTiming['timing_name_en'],
    ]
);

// ============================================================
// الخطوة 6: إرسال رد نجاح التعطيل
// ============================================================
// إرسال JSON يوضح أن النوع أُخفي دون حذفه
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة عربية جاهزة للعرض في اللوحة
    "message" => "تم تعطيل نوع الدوام بنجاح — لم يُحذف من قاعدة البيانات",
    // بيانات التوقيت بعد التعطيل
    "data"    => [
        // معرّف التوقيت
        "timing_id"        => $timing_id,
        // الاسم العربي
        "timing_name_ar"   => $targetTiming['timing_name_ar'],
        // الاسم الإنجليزي
        "timing_name_en"   => $targetTiming['timing_name_en'],
        // ⭐ صفر = معطّل ولا يظهر للمستخدمين
        "timing_is_active" => 0,
        // من نفّذ التعطيل
        "deactivated_by"   => $currentAdmin['admin_full_name'],
    ],
]);
?>
