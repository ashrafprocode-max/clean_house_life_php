<?php
// ============================================================
// ملف: admin/service_timing/list_service_timing.php
// الغرض: عرض قائمة أنواع الدوام للإدارة مع حالتها
//
// ⭐ الفرق عن service_timing/get_all.php:
//    get_all    → التطبيق: الأنواع المفعّلة فقط بلا توكن
//    هذا الملف  → اللوحة: كل الأنواع بما فيها المعطّلة + توكن
//
// ⭐ الفلاتر:
//   is_active → 1 مفعّل / 0 معطّل / all الكل (افتراضي)
//   search    → بحث في الاسم العربي أو الإنجليزي
//
// الطريقة: POST أو GET
// الصلاحية المطلوبة: catalog.view
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/service_timing)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ catalog.view يملكها المدير وخدمة العملاء
//    لأن القائمة للعرض فقط ولا تغيّر شيئاً
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية عرض الكتالوج
requirePermission($currentAdmin, 'catalog.view');

// ============================================================
// الخطوة 2: استقبال معاملات الفلترة والبحث
// ============================================================
// فلتر حالة التفعيل: 1 / 0 / all
$isActive = filterRequest("is_active");
// نص البحث في اسم نوع الدوام عربي أو إنجليزي
$search   = trim(filterRequest("search"));

// ============================================================
// الخطوة 3: بناء شروط WHERE المشتركة
// ============================================================
// نبدأ بشرط ثابت دائماً صحيح لتبسيط دمج الشروط بعده
$whereConditions = ["1 = 1"];
// مصفوفة معاملات الاستعلام
$params = [];

// ============================================================
// الخطوة 4: فلتر حالة التفعيل
// ============================================================
// نُضيف الشرط فقط إذا طُلب مفعّل أو معطّل صراحةً
if ($isActive === '1' || $isActive === '0') {
    // إضافة شرط التفعيل
    $whereConditions[] = "st.timing_is_active = ?";
    // تمرير القيمة للاستعلام
    $params[] = (int) $isActive;
}

// ============================================================
// الخطوة 5: البحث في الاسم العربي والإنجليزي
//
// ⚠️ الأقواس حول شروط OR إجبارية
//    وإلا تعارض OR مع شروط AND الأخرى وأعطى نتائج خاطئة
// ============================================================
// نُضيف الشرط فقط إذا أرسلت الواجهة نصاً للبحث
if ($search !== '') {
    // بناء شرط البحث في الاسمين بـ OR
    $whereConditions[] = "("
        . " st.timing_name_ar LIKE ?"
        . " OR st.timing_name_en LIKE ?"
        . ")";
    // تجهيز نص البحث مع % قبله وبعده للبحث الجزئي
    $searchTerm = "%{$search}%";
    // تمرير النص مرتين (مرة لكل حقل)
    $params[] = $searchTerm;
    $params[] = $searchTerm;
}

// تجميع الشروط في جملة WHERE واحدة
$whereSQL = implode(" AND ", $whereConditions);

// ============================================================
// الخطوة 6: جلب أنواع الدوام مع عدد الخدمات المرتبطة بكل نوع
//
// ⭐ الترتيب حسب المعرّف حتى تبقى الأنواع الأساسية أولاً
//    (إقامة، يومي، ساعات، أسبوعي، شهري)
// ============================================================
// تجهيز استعلام القائمة
$stmt = $con->prepare(
    "SELECT
        st.timing_id,
        st.timing_name_ar,
        st.timing_name_en,
        st.timing_is_active,
        -- عدد خدمات مقدّمي الخدمة المرتبطة بهذا النوع
        (SELECT COUNT(ps.ps_id)
         FROM provider_services ps
         WHERE ps.ps_timing_id = st.timing_id) AS services_count
     FROM service_timing st
     WHERE $whereSQL
     ORDER BY st.timing_id ASC"
);
// تنفيذ الاستعلام بمعاملات الفلترة
$stmt->execute($params);
// جلب كل الصفوف كمصفوفة
$timings = $stmt->fetchAll(PDO::FETCH_ASSOC);

// ============================================================
// الخطوة 7: تحويل كل سجل لشكل مناسب لـ Flutter
// ============================================================
$resultData = array_map(function ($timing) {
    // إرجاع مصفوفة نوع الدوام بالشكل الذي يقرأه موديل Flutter
    return [
        // معرّف نوع الدوام
        "timing_id"        => (int) $timing['timing_id'],
        // الاسم العربي
        "timing_name_ar"   => $timing['timing_name_ar'],
        // الاسم الإنجليزي
        "timing_name_en"   => $timing['timing_name_en'],
        // حالة التفعيل: 1 ظاهر · 0 معطّل
        "timing_is_active" => (int) $timing['timing_is_active'],
        // عدد الخدمات المرتبطة بهذا النوع
        "services_count"   => (int) $timing['services_count'],
    ];
}, $timings);

// ============================================================
// الخطوة 8: حساب إحصائيات سريعة لأعلى الصفحة
// ⚠️ الإحصائيات على الجدول كله لا على نتيجة الفلتر
//    حتى يبقى عدّاد المفعّل/المعطّل ثابتاً أثناء البحث
// ============================================================
$statsSQL = "
    SELECT
        -- عدد الأنواع المفعّلة
        SUM(CASE WHEN timing_is_active = 1 THEN 1 ELSE 0 END) AS active_count,
        -- عدد الأنواع المعطّلة
        SUM(CASE WHEN timing_is_active = 0 THEN 1 ELSE 0 END) AS inactive_count,
        -- العدد الكلي
        COUNT(timing_id) AS all_count
    FROM service_timing
";
// تنفيذ استعلام الإحصائيات
$statsStmt = $con->prepare($statsSQL);
$statsStmt->execute();
// قراءة صف الإحصائيات
$stats = $statsStmt->fetch(PDO::FETCH_ASSOC);

// ============================================================
// الخطوة 9: إرسال الرد
// ============================================================
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة نجاح
    "message" => "تم جلب قائمة أنواع الدوام بنجاح",
    // عدد النتائج في هذه الصفحة
    "count"   => count($resultData),
    // مصفوفة أنواع الدوام
    "data"    => $resultData,
    // إحصائيات للعرض في أعلى الصفحة
    "stats"   => [
        // عدد الأنواع المفعّلة
        "active_count"   => (int) ($stats['active_count']   ?? 0),
        // عدد الأنواع المعطّلة
        "inactive_count" => (int) ($stats['inactive_count'] ?? 0),
        // العدد الكلي
        "all_count"      => (int) ($stats['all_count']      ?? 0),
    ],
]);
?>
