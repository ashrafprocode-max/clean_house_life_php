<?php
// ============================================================
// ملف: admin/service_timing/edit_service_timing.php
// الغرض: تعديل بيانات نوع دوام موجود في جدول service_timing
//
// الحقل الإجباري الوحيد: timing_id
// وكل الحقول الأخرى اختيارية — نُحدّث ما أُرسل فقط
//
// ⭐ لماذا التحديث الجزئي؟
//    لأن الموظف قد يريد تصحيح الاسم العربي وحده
//    ولو أرسلنا كل الحقول لأصبح أي حقل نسيه = مسح للبيانات
//
// الحقول القابلة للتعديل:
//   timing_name_ar
//   timing_name_en
//   timing_is_active  (1 لإعادة التفعيل بعد delete_service_timing.php)
//
// ⚠️ لا حذف فعلي هنا — التعطيل من delete_service_timing.php
//    وهذا الملف يسمح بإعادة التفعيل فقط عبر timing_is_active = 1
//
// الطريقة: POST
// الصلاحية المطلوبة: catalog.manage
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/service_timing)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج
requirePermission($currentAdmin, 'catalog.manage');

// ============================================================
// الخطوة 2: استقبال معرّف التوقيت والتحقق منه
// ============================================================
// معرّف نوع الدوام المراد تعديله - إجباري
$timing_id = filterRequest("timing_id");

// إذا لم يُرسل المعرّف نوقف التنفيذ فوراً
if ($timing_id === '') {
    // رسالة توضح الحقل المطلوب
    printFailure("الحقل timing_id مطلوب");
    // إيقاف التنفيذ
    exit;
}

// تحويل المعرّف لرقم صحيح لحماية جملة WHERE من أي محتوى غير رقمي
$timing_id = (int) $timing_id;

// لا نقبل صفراً لأن AUTO_INCREMENT يبدأ من 1
if ($timing_id < 1) {
    // رسالة توضح أن المعرّف غير صالح
    printFailure("timing_id غير صالح");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 3: جلب بيانات التوقيت الحالية
//
// ⭐ نحتاجها لسببين:
//    1. التأكد أن النوع موجود قبل التعديل
//    2. معرفة الاسم الحالي عند فحص التكرار
// ============================================================
// تجهيز استعلام محمي لجلب الصف الحالي
$stmtCurrent = $con->prepare(
    "SELECT
        timing_id,
        timing_name_ar,
        timing_name_en,
        timing_is_active
     FROM service_timing
     WHERE timing_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف التوقيت
$stmtCurrent->execute([$timing_id]);
// جلب الصف الحالي
$current = $stmtCurrent->fetch(PDO::FETCH_ASSOC);

// إذا لم يوجد التوقيت نرفض التعديل
if (!$current) {
    // رسالة توضح أن نوع الدوام غير موجود
    printFailure("نوع الدوام غير موجود", 404);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: استقبال الحقول القابلة للتعديل (كلها اختيارية)
// ============================================================
// الاسم العربي الجديد
$timing_name_ar   = trim(filterRequest("timing_name_ar"));
// الاسم الإنجليزي الجديد
$timing_name_en   = trim(filterRequest("timing_name_en"));
// حالة التفعيل الجديدة (1 لإعادة التفعيل)
$timing_is_active = filterRequest("timing_is_active");

// ============================================================
// الخطوة 5: بناء مصفوفة التحديث بالحقول المُرسَلة فقط
// ============================================================
// تهيئة مصفوفة فارغة سنملأها بما أرسله الموظف
$updateData = [];

// ---------- الاسم العربي ----------
// نتحقق فقط إذا أُرسل الحقل
if ($timing_name_ar !== '') {
    // قياس الطول لأن العمود varchar(100)
    if (mb_strlen($timing_name_ar) > 100) {
        // رسالة توضح الحد الأقصى
        printFailure("timing_name_ar يجب ألا يتجاوز 100 حرف");
        // إيقاف التنفيذ
        exit;
    }
    // الحد الأدنى حتى لا يُحفظ حرف واحد بلا معنى
    if (mb_strlen($timing_name_ar) < 2) {
        // رسالة توضح الحد الأدنى
        printFailure("الاسم العربي يجب أن يكون حرفين على الأقل");
        // إيقاف التنفيذ
        exit;
    }
    // إضافة الاسم العربي للتحديث
    $updateData["timing_name_ar"] = $timing_name_ar;
}

// ---------- الاسم الإنجليزي ----------
// نتحقق فقط إذا أُرسل الحقل
if ($timing_name_en !== '') {
    // قياس الطول لأن العمود varchar(100)
    if (mb_strlen($timing_name_en) > 100) {
        // رسالة توضح الحد الأقصى
        printFailure("timing_name_en يجب ألا يتجاوز 100 حرف");
        // إيقاف التنفيذ
        exit;
    }
    // الحد الأدنى للاسم الإنجليزي
    if (mb_strlen($timing_name_en) < 2) {
        // رسالة توضح الحد الأدنى
        printFailure("الاسم الإنجليزي يجب أن يكون حرفين على الأقل");
        // إيقاف التنفيذ
        exit;
    }
    // إضافة الاسم الإنجليزي للتحديث
    $updateData["timing_name_en"] = $timing_name_en;
}

// ============================================================
// الخطوة 6: منع تكرار الاسم مع استثناء الصف الحالي
// ============================================================
// الاسم العربي الذي سنفحصه: الجديد إن أُرسل وإلا الاسم الحالي
$checkNameAr = $updateData["timing_name_ar"] ?? $current['timing_name_ar'];
// الاسم الإنجليزي الذي سنفحصه: الجديد إن أُرسل وإلا الاسم الحالي
$checkNameEn = $updateData["timing_name_en"] ?? $current['timing_name_en'];

// نفحص التكرار فقط إذا تغيّر أحد الاسمين فعلاً
if (isset($updateData["timing_name_ar"]) || isset($updateData["timing_name_en"])) {
    // استعلام يبحث عن نفس الاسم في صف آخر غير هذا التوقيت
    $stmtDup = $con->prepare(
        "SELECT timing_id FROM service_timing
         WHERE (timing_name_ar = ? OR timing_name_en = ?)
           AND timing_id <> ?
         LIMIT 1"
    );
    // تنفيذ الاستعلام بالاسمين ومعرّف الصف الحالي
    $stmtDup->execute([$checkNameAr, $checkNameEn, $timing_id]);
    // إذا وُجد نوع دوام آخر بنفس الاسم نرفض التعديل
    if ($stmtDup->rowCount() > 0) {
        // رسالة توضح أن الاسم مستخدم
        printFailure("اسم نوع الدوام مستخدم بالفعل لنوع آخر", 409);
        // إيقاف التنفيذ
        exit;
    }
}

// ---------- حالة التفعيل (إعادة تفعيل نوع معطّل) ----------
// نقبل القيمة صفر لذلك نقارن بالنص الفارغ وليس empty
if ($timing_is_active !== '') {
    // تحويل القيمة لرقم صحيح (0 أو 1 فقط)
    $updateData["timing_is_active"] = ((int) $timing_is_active === 1) ? 1 : 0;
}

// ============================================================
// الخطوة 7: التأكد من وجود حقل واحد على الأقل للتحديث
// ============================================================
// إذا كانت المصفوفة فارغة فلا يوجد ما نُحدّثه
if (empty($updateData)) {
    // رسالة توضح عدم إرسال أي حقل
    printFailure("لم يتم إرسال أي حقل للتعديل");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 8: تنفيذ التحديث باستخدام دالتك الموحدة
// ============================================================
// استدعاء دالة التحديث مع false لمنع طباعة JSON مرتين
$result = updateData(
    "service_timing",
    $updateData,
    "timing_id = $timing_id",
    false
);

// ============================================================
// الخطوة 9: جلب البيانات بعد التعديل
//
// ⚠️ updateData تُرجع rowCount
//    و MySQL تُرجع 0 إذا كانت القيم الجديدة مطابقة للقديمة
//    فلا نعتبر 0 فشلاً، بل نُعيد جلب الصف
// ============================================================
// تجهيز استعلام لجلب الصف بعد التعديل
$stmtAfter = $con->prepare(
    "SELECT
        timing_id,
        timing_name_ar,
        timing_name_en,
        timing_is_active
     FROM service_timing
     WHERE timing_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف التوقيت
$stmtAfter->execute([$timing_id]);
// جلب الصف المحدَّث
$updated = $stmtAfter->fetch(PDO::FETCH_ASSOC);

// إذا فشل الجلب فهناك خطأ حقيقي في قاعدة البيانات
if (!$updated) {
    // رسالة توضح فشل جلب البيانات
    printFailure("تم التعديل لكن تعذّر جلب البيانات المحدَّثة", 500);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 10: تسجيل الإجراء في سجل النشاط الإداري
// ============================================================
// تسجيل تعديل نوع الدوام
logAdminActivity(
    // بيانات الموظف المنفّذ
    $currentAdmin,
    // نوع الإجراء
    'edit_service_timing',
    // نوع الكيان
    'service_timing',
    // معرّف التوقيت
    $timing_id,
    // الحقول التي تغيّرت فقط
    [
        // مفاتيح الحقول المحدَّثة
        "updated_fields" => array_keys($updateData),
    ]
);

// ============================================================
// الخطوة 11: إرسال الرد النهائي
// ============================================================
// إرسال JSON يحتوي البيانات بعد التعديل
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة نجاح بالعربية
    "message" => "تم تحديث بيانات نوع الدوام بنجاح",
    // بيانات التوقيت بعد التعديل
    "data"    => [
        // معرّف التوقيت
        "timing_id"        => (int) $updated['timing_id'],
        // الاسم العربي بعد التعديل
        "timing_name_ar"   => $updated['timing_name_ar'],
        // الاسم الإنجليزي بعد التعديل
        "timing_name_en"   => $updated['timing_name_en'],
        // حالة التفعيل
        "timing_is_active" => (int) $updated['timing_is_active'],
        // من نفّذ التعديل
        "updated_by"       => $currentAdmin['admin_full_name'],
    ],
]);
?>
