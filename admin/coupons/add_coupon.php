<?php
// ============================================================
// ملف: bookings/admin/add_coupon.php
// الغرض: إضافة كوبون خصم جديد في جدول coupon بواسطة الإدارة فقط
//
// ⭐ فكرة الكوبون في هذا المشروع:
//   نسبة الخصم تُخصم من قيمة العمولة فقط، ولا تُخصم من سعر مقدم الخدمة
//   مثال: سعر الخدمة 1000 ج.م + عمولة 100 ج.م = 1100 ج.م
//         كوبون 10% ⇒ العمولة تصبح 100 - (100 × 10 ÷ 100) = 90 ج.م
//         الإجمالي = 1000 + 90 = 1090 ج.م
//
// الحقول الإجبارية: coupon_name, coupon_count, coupon_discount, coupon_expiredate
// الطريقة: POST
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات 
include "../../connect.php";

// ⭐ حماية ملف الإدارة: يجب إرسال المفتاح السري في هيدر X-Admin-Key
// ⚠️ لو أردت تعطيل الحماية مؤقتاً أثناء التطوير ضع // قبل السطر التالي فقط
//checkAdminKey();

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ coupons.manage يملكها: owner و manager
//    ولا يملكها: support و accountant
//    لأن اصدار الكوبونات من شأن المالك والمدير 
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج (الأقسام والتخصصات والتوقيتات)
requirePermission($currentAdmin, 'coupons.manage');

// معرّف الموظف المنفّذ مأخوذ من التوكن لا من الطلب
$adminId = (int) $currentAdmin['admin_id'];

// ============================================================
// الخطوة 1: استقبال البيانات القادمة من لوحة الإدارة
// ============================================================
// اسم الكوبون الذي سيكتبه العميل (نُنظّفه من المسافات الزائدة أول وآخر النص)
$coupon_name       = trim(filterRequest("coupon_name"));
// عدد المرات المسموح باستخدام هذا الكوبون فيها
$coupon_count      = filterRequest("coupon_count");
// نسبة الخصم المئوية التي ستُخصم من العمولة (من 1 إلى 100)
$coupon_discount   = filterRequest("coupon_discount");
// تاريخ ووقت انتهاء صلاحية الكوبون بصيغة Y-m-d H:i:s
$coupon_expiredate = filterRequest("coupon_expiredate");

// ============================================================
// الخطوة 2: التحقق من الحقول الإجبارية الأربعة
// ============================================================
// نستخدم === '' وليس empty لأن empty ترفض الرقم صفر بالخطأ
if ($coupon_name === '' || $coupon_count === '' ||
    $coupon_discount === '' || $coupon_expiredate === '') {
    // إرسال رسالة فشل تُوضّح الحقول المطلوبة
    printFailure("Required fields: coupon_name, coupon_count, coupon_discount, coupon_expiredate");
    // إيقاف تنفيذ باقي الملف
    exit;
}

// ============================================================
// الخطوة 3: التحقق من طول اسم الكوبون
//           لأن العمود varchar(50) يرفض أي نص أطول من ذلك
// ============================================================
// قياس طول الاسم بالأحرف مع دعم العربية عبر mb_strlen
if (mb_strlen($coupon_name) > 50) {
    // رسالة توضح الحد الأقصى المسموح
    printFailure("coupon_name must not exceed 50 characters");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: التحقق من أن نسبة الخصم رقم منطقي بين 1 و 100
// ============================================================
// تحويل النسبة لرقم صحيح لأن العمود من نوع smallint
$coupon_discount = (int) $coupon_discount;
// النسبة يجب أن تكون أكبر من صفر وألا تتجاوز 100%
if ($coupon_discount < 1 || $coupon_discount > 100) {
    // رسالة توضح النطاق المسموح للنسبة
    printFailure("coupon_discount must be a percentage between 1 and 100");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 5: التحقق من أن عدد الاستخدامات رقم منطقي
// ============================================================
// تحويل العدد لرقم صحيح لأن العمود من نوع int
$coupon_count = (int) $coupon_count;
// لا معنى لكوبون بعدد استخدامات صفر أو سالب
if ($coupon_count < 1) {
    // رسالة توضح أن العدد يجب أن يكون 1 على الأقل
    printFailure("coupon_count must be at least 1");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 6: التحقق من صحة تاريخ الانتهاء وأنه في المستقبل
// ============================================================
// محاولة تحويل النص المُرسَل لتاريخ صالح
$expireTimestamp = strtotime($coupon_expiredate);
// إذا فشل التحويل فالصيغة المُرسَلة غير صحيحة
if ($expireTimestamp === false) {
    // رسالة توضح الصيغة المطلوبة
    printFailure("coupon_expiredate must be a valid datetime (Y-m-d H:i:s)");
    // إيقاف التنفيذ
    exit;
}
// لا نقبل كوبوناً منتهي الصلاحية من لحظة إنشائه
if ($expireTimestamp <= time()) {
    // رسالة توضح أن التاريخ يجب أن يكون في المستقبل
    printFailure("coupon_expiredate must be a future date");
    // إيقاف التنفيذ
    exit;
}
// إعادة تنسيق التاريخ بالصيغة التي يقبلها عمود datetime في MySQL
$coupon_expiredate = date("Y-m-d H:i:s", $expireTimestamp);

// ============================================================
// الخطوة 7: منع تكرار اسم الكوبون
//   ⚠️ ضروري لأن جدول coupon لا يحتوي على قيد UNIQUE على الاسم
//   ولو تكرر الاسم فسيجلب checkcoupon أول صف فقط وتحدث فوضى
// ============================================================
// استعلام آمن يبحث عن نفس الاسم (المقارنة غير حساسة لحالة الأحرف بسبب utf8mb4_unicode_ci)
$stmtDup = $con->prepare(
    "SELECT coupon_id FROM coupon WHERE coupon_name = ? LIMIT 1"
);
// تنفيذ الاستعلام بتمرير اسم الكوبون
$stmtDup->execute([$coupon_name]);
// إذا وُجد اسم مطابق نرفض الإضافة
if ($stmtDup->rowCount() > 0) {
    // رسالة توضح أن الاسم مستخدم بالفعل
    printFailure("This coupon name already exists");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 8: إدخال الكوبون في جدول coupon
// ============================================================
// تجهيز مصفوفة البيانات بأسماء الأعمدة الحقيقية في الجدول
$insertData = [
    // اسم الكوبون الذي سيكتبه العميل
    "coupon_name"       => $coupon_name,
    // عدد المرات المتاحة لاستخدامه
    "coupon_count"      => $coupon_count,
    // نسبة الخصم المئوية من العمولة
    "coupon_discount"   => $coupon_discount,
    // تاريخ ووقت انتهاء الصلاحية
    "coupon_expiredate" => $coupon_expiredate,
];

// تنفيذ عملية الإدخال باستخدام دالتك الموحدة مع false لمنع طباعة JSON مرتين
$result = insertData("coupon", $insertData, false);

// ============================================================
// الخطوة 9: إرسال الرد النهائي
// ============================================================
// التحقق من نجاح عملية الإدخال
if ($result > 0) {
    // إرسال JSON يحتوي على بيانات الكوبون الجديد
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // رسالة نجاح واضحة
        "message" => "Coupon added successfully",
        // بيانات الكوبون المُضاف
        "data"    => [
            // المعرّف الذي أنشأته قاعدة البيانات تلقائياً
            "coupon_id"        => (int) $con->lastInsertId(),
            // اسم الكوبون
            "coupon_name"      => $coupon_name,
            // عدد الاستخدامات المتاح
            "coupon_count"     => $coupon_count,
            // نسبة الخصم من العمولة
            "coupon_discount"  => $coupon_discount,
            // تاريخ انتهاء الصلاحية
            "coupon_expiredate"=> $coupon_expiredate,
            // توضيح لطريقة عمل الخصم حتى لا تُنسى القاعدة
            "discount_applies_on" => "commission_only",
        ],
    ]);
} else {
    // في حالة فشل الإدخال نُرجع رسالة فشل واضحة
    printFailure("Failed to add coupon. Please try again.");
}
?>