<?php
// ============================================================
// ملف: admin/auth/login.php
// الغرض: تسجيل دخول موظفي الإدارة (مالك / مدير / محاسب / موارد / دعم / بائع)
//        والتحقق من كلمة المرور بـ password_verify
//        ثم إصدار توكن يُستخدم في كل طلبات لوحة التحكم
//
// ⭐ كيف يعمل التوكن (نسخة مبسّطة بلا جدول توكنات)؟
//   التوكن = sha256(admin_id | admin_phone | password_hash | سر السيرفر)
//   السيرفر يتحقق منه بإعادة حسابه من قاعدة البيانات ومقارنته
//
//   الفائدة: لا نحتاج جدولاً للتوكنات ولا تنظيفاً دورياً
//   وإذا غيّر الموظف كلمة مروره أو عُطّل حسابه يُبطَل توكنه تلقائياً
//   لأن هاش كلمة المرور جزء من معادلة التوكن
//
// الحقول الإجبارية: admin_phone, admin_password
// الطريقة: POST
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/auth)
include "../../connect.php";

// ⚠️ لا نستدعي checkAdminKey هنا إطلاقاً
//    لأن هذه هي صفحة تسجيل الدخول نفسها، والموظف لا يملك توكناً بعد

// ============================================================
// الخطوة 1: استقبال بيانات تسجيل الدخول
// ============================================================
// رقم هاتف الموظف (هو اسم المستخدم في نظامنا) - إجباري
$admin_phone    = trim(filterRequest("admin_phone"));
// كلمة مرور الموظف كما كتبها - إجباري
$admin_password = filterRequest("admin_password");

// ============================================================
// الخطوة 2: التحقق من الحقلين الإجباريين
// ============================================================
// إذا نقص أي حقل نوقف التنفيذ فوراً
if ($admin_phone === '' || $admin_password === '') {
    // رسالة توضح الحقول المطلوبة
    printFailure("Required fields: admin_phone, admin_password");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 3: البحث عن الموظف برقم هاتفه
// ============================================================
$stmt = $con->prepare(
    "SELECT admin_id, admin_full_name, admin_phone,
            admin_password, admin_role, admin_is_active
     FROM admin_users
     WHERE admin_phone = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير رقم الهاتف
$stmt->execute([$admin_phone]);
// جلب صف الموظف كمصفوفة
$admin = $stmt->fetch(PDO::FETCH_ASSOC);

// ============================================================
// الخطوة 4: التحقق من وجود الموظف وصحة كلمة المرور
//
// ⚠️ رسالة الخطأ موحّدة في الحالتين (غير موجود / كلمة خطأ)
//    حتى لا يعرف المهاجم أي أرقام هواتف مسجّلة في النظام
// ============================================================
// نتحقق أولاً من وجود الموظف
if (!$admin) {
    // رسالة موحّدة لا تكشف السبب الحقيقي
    printFailure("رقم الهاتف أو كلمة المرور غير صحيحة", 401);
    // إيقاف التنفيذ
    exit;
}

// ⭐ التحقق من كلمة المرور بـ password_verify
// الدالة تقارن الكلمة المكتوبة بالهاش المحفوظ في قاعدة البيانات
// ولا يمكن فكّ الهاش عكسياً للحصول على كلمة المرور
if (!password_verify($admin_password, $admin['admin_password'])) {
    // نفس الرسالة الموحّدة
    printFailure("رقم الهاتف أو كلمة المرور غير صحيحة", 401);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 5: التحقق من أن حساب الموظف مفعّل
// ============================================================
// إذا عطّل المدير حساب الموظف نرفض دخوله
if ((int)$admin['admin_is_active'] !== 1) {
    // رسالة توضح أن الحساب معطّل
    printFailure("هذا الحساب معطّل، يرجى مراجعة المدير", 403);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 6: توليد التوكن
//
// المعادلة: sha256(admin_id | admin_phone | password_hash | سر السيرفر)
// نستخدم hash_hmac لأنها أقوى من sha256 المجردة (تدمج السر بأمان)
// ============================================================
// قراءة السر المُعرَّف في connect.php
global $admin_secret_key;

// بناء نص البصمة من بيانات الموظف الثابتة
$tokenPayload = $admin['admin_id'] . '|'
              . $admin['admin_phone'] . '|'
              . $admin['admin_password'];

// توليد بصمة التوكن باستخدام السر
$tokenHash = hash_hmac('sha256', $tokenPayload, $admin_secret_key);

// ⭐ التوكن النهائي = معرّف الموظف + نقطة + البصمة
// نضع المعرّف في المقدمة حتى يستطيع السيرفر معرفة الموظف بلا بحث
$adminToken = $admin['admin_id'] . '.' . $tokenHash;

// ============================================================
// الخطوة 7: تسجيل وقت آخر دخول
// ============================================================
// تحديث حقل آخر دخول بالوقت الحالي
updateData(
    "admin_users",
    ["admin_last_login" => date("Y-m-d H:i:s")],
    "admin_id = " . (int)$admin['admin_id'],
    false
);

// ============================================================
// الخطوة 8: تحديد صلاحيات الموظف حسب دوره
// لوحة التحكم تُخفي أو تُظهر الأزرار بناءً على هذه القائمة
// ============================================================
// المالك والمدير لهما كل الصلاحيات الثنائية القديمة
$permissions = in_array($admin['admin_role'], ['owner', 'manager'], true)
    ? [
        // مراجعة طلبات مقدمي الخدمة
        "review_providers"  => true,
        // تعديل بيانات مقدمي الخدمة
        "edit_providers"    => true,
        // إدارة الحجوزات وتعديل أسعارها
        "manage_bookings"   => true,
        // إضافة وإدارة كوبونات الخصم
        "manage_coupons"    => true,
        // إضافة وتعطيل موظفي الإدارة (للمالك والمدير)
        "manage_admins"     => true,
        // عرض التقارير والإحصائيات
        "view_reports"      => true,
      ]
    // باقي الأدوار لها صلاحيات محدودة في هذا الرد القديم
    : [
        // مراجعة طلبات مقدمي الخدمة
        "review_providers"  => true,
        // ⭐ التعديل مسموح حالياً (الدرجة "ج")
        // ⚠️ لتحويلها للدرجة "أ" غيّر القيمة إلى false
        "edit_providers"    => true,
        // إدارة الحجوزات
        "manage_bookings"   => true,
        // لا تستطيع إدارة الكوبونات
        "manage_coupons"    => false,
        // لا تستطيع إدارة الموظفين
        "manage_admins"     => false,
        // لا تستطيع رؤية التقارير
        "view_reports"      => false,
      ];

// ============================================================
// الخطوة 9: إرسال الرد مع التوكن وبيانات الموظف
// ⚠️ لا نُرجع هاش كلمة المرور إطلاقاً
// ============================================================
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة نجاح بالعربية
    "message" => "تم تسجيل الدخول بنجاح",
    // بيانات الجلسة
    "data"    => [
        // ⭐ التوكن الذي تحفظه لوحة التحكم وتُرسله في كل طلب
        "admin_token"     => $adminToken,
        // معرّف الموظف
        "admin_id"        => (int)$admin['admin_id'],
        // اسم الموظف لعرضه في أعلى لوحة التحكم
        "admin_full_name" => $admin['admin_full_name'],
        // رقم هاتف الموظف
        "admin_phone"     => $admin['admin_phone'],
        // دور الموظف (owner / manager / accountant / hr / support / seller)
        "admin_role"      => $admin['admin_role'],
        // ترجمة الدور للعربية من الخريطة الموحدة في functions.php
        "admin_role_ar"   => adminRoleAr($admin['admin_role']),
        // قائمة الصلاحيات لإظهار أو إخفاء الأزرار
        "permissions"     => $permissions,
    ],
]);
?>