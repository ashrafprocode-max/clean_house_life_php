<?php
// ============================================================
// ملف: admin/staff/add_staff.php
// الغرض: إضافة موظف إدارة جديد (مدير أو خدمة عملاء او محاسب)
//
// ⚠️⚠️ هذا الملف للمدير (manager) فقط ولا يستطيع موظف الدعم استخدامه
//      لأنه لو استطاع لصنع لنفسه حساب manager وحصل على كل الصلاحيات
//
// ⭐ لا يوجد signup عام في النظام إطلاقاً — الحسابات تُنشأ من هنا فقط
//    والمدير يُسلّم الموظف رقم هاتفه وكلمة مروره شفهياً
//
// الحقول الإجبارية: admin_full_name, admin_phone, admin_password, admin_role
// الطريقة: POST
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/staff)
include "../../connect.php";

// ⭐ التحقق من التوكن مع فرض دور المدير
// تمرير 'manager' يجعل الدالة ترفض أي موظف دعم برسالة 403
$currentAdmin = checkAdminToken('manager');

// ============================================================
// الخطوة 1: استقبال بيانات الموظف الجديد
// ============================================================
// الاسم الكامل للموظف - إجباري
$admin_full_name = trim(filterRequest("admin_full_name"));
// رقم هاتف الموظف (هو اسم المستخدم في النظام) - إجباري
$admin_phone     = trim(filterRequest("admin_phone"));
// كلمة المرور المؤقتة التي سيسلّمها المدير للموظف - إجباري
$admin_password  = trim(filterRequest("admin_password")); // "filter...d");
// دور الموظف: manager أو support - إجباري
$admin_role      = filterRequest("admin_role");

// ============================================================
// الخطوة 2: التحقق من الحقول الإجبارية الأربعة
// ============================================================
// إذا نقص أي حقل نوقف التنفيذ فوراً
if ($admin_full_name === '' || $admin_phone === '' ||
    $admin_password ===''  || $admin_role === '') {
    // رسالة توضح الحقول المطلوبة
    printFailure("Required fields: admin_full_name, admin_phone, admin_password, admin_role");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 3: التحقق من صحة الدور المطلوب
// ============================================================
// قائمة الأدوار المسموحة (نفس قيم enum في قاعدة البيانات)
$allowedRoles = ['manager', 'support'];

// إذا كان الدور غير معروف نرفض الإضافة
if (!in_array($admin_role, $allowedRoles, true)) {
    // رسالة توضح الأدوار المسموحة
    printFailure("admin_role must be: manager or support");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: التحقق من طول الاسم
// لأن العمود varchar(100) يرفض أي نص أطول
// ============================================================
// قياس طول الاسم بالأحرف مع دعم العربية عبر mb_strlen
if (mb_strlen($admin_full_name) > 100) {
    // رسالة توضح الحد الأقصى المسموح
    printFailure("admin_full_name must not exceed 100 characters");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 5: التحقق من صحة رقم الهاتف
// ============================================================
// نتأكد أن الرقم يحتوي أرقاماً فقط وطوله بين 10 و 15 خانة
if (!preg_match('/^[0-9]{10,15}$/', $admin_phone)) {
    // رسالة توضح الصيغة المطلوبة
    printFailure("admin_phone must be 10 to 15 digits only");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 6: التحقق من قوة كلمة المرور
// ⚠️ حساب إداري بكلمة مرور ضعيفة يعني اختراق النظام بالكامل
// ============================================================
// الحد الأدنى 8 أحرف
if (strlen($admin_password) < 8) {
    // رسالة توضح الحد الأدنى
    printFailure("كلمة المرور يجب أن تكون 8 أحرف على الأقل");
    // إيقاف التنفيذ
    exit;
}

// نتأكد أنها تحتوي حرفاً ورقماً على الأقل
if (!preg_match('/[A-Za-z]/', $admin_password) ||
    !preg_match('/[0-9]/', $admin_password)) {
    // رسالة توضح الشرط
    printFailure("كلمة المرور يجب أن تحتوي حروفاً وأرقاماً");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 7: منع تكرار رقم الهاتف
// ⭐ العمود عليه قيد UNIQUE، فنتحقق أولاً لنُرجع رسالة واضحة
//    بدلاً من خطأ SQL خام يظهر للمستخدم
// ============================================================
$stmtDup = $con->prepare(
    "SELECT admin_id FROM admin_users WHERE admin_phone = ? LIMIT 1"
);
// تنفيذ الاستعلام بتمرير رقم الهاتف
$stmtDup->execute([$admin_phone]);

// إذا وُجد موظف بنفس الرقم نرفض الإضافة
if ($stmtDup->rowCount() > 0) {
    // رسالة توضح أن الرقم مستخدم بالفعل
    printFailure("رقم الهاتف مستخدم بالفعل لموظف آخر", 409);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// ⭐ الخطوة 8: تشفير كلمة المرور بـ password_hash
//
// لماذا لا نحفظها كنص عادي؟
//   لو سُرّبت قاعدة البيانات لأصبحت كل الحسابات مكشوفة
//   password_hash تُنتج هاشاً لا يمكن فكّه عكسياً
//   ويحتوي "ملحاً" (salt) عشوائياً فنفس الكلمة تُنتج هاشاً مختلفاً كل مرة
// ============================================================
// توليد الهاش بالخوارزمية الافتراضية الآمنة (bcrypt حالياً)
$hashedPassword = password_hash($admin_password, PASSWORD_DEFAULT);

// ============================================================
// الخطوة 9: إدخال الموظف في جدول admin_users
// ============================================================
// تجهيز مصفوفة البيانات بأسماء الأعمدة الحقيقية في الجدول
$insertData = [
    // الاسم الكامل للموظف
    "admin_full_name" => $admin_full_name,
    // رقم الهاتف (اسم المستخدم)
    "admin_phone"     => $admin_phone,
    // ⚠️ نحفظ الهاش وليس كلمة المرور نفسها
    "admin_password"  => $hashedPassword,
    // دور الموظف
    "admin_role"      => $admin_role,
    // الحساب مفعّل من لحظة إنشائه
    "admin_is_active" => 1,
];

// تنفيذ عملية الإدخال باستخدام دالتك الموحدة مع false لمنع طباعة JSON مرتين
$result = insertData("admin_users", $insertData, false);

// ============================================================
// الخطوة 10: إرسال الرد النهائي
// ⚠️ لا نُرجع كلمة المرور ولا هاشها إطلاقاً
// ============================================================
// التحقق من نجاح عملية الإدخال
if ($result > 0) {
    // إرسال JSON يحتوي بيانات الموظف الجديد
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // رسالة نجاح بالعربية جاهزة للعرض في اللوحة
        "message" => "تم إضافة الموظف بنجاح — سلّمه رقم هاتفه وكلمة المرور",
        // بيانات الموظف المُضاف
        "data"    => [
            // المعرّف الذي أنشأته قاعدة البيانات تلقائياً
            "admin_id"        => (int) $con->lastInsertId(),
            // الاسم الكامل
            "admin_full_name" => $admin_full_name,
            // رقم الهاتف الذي سيستخدمه للدخول
            "admin_phone"     => $admin_phone,
            // الدور
            "admin_role"      => $admin_role,
            // ترجمة الدور للعربية من الخريطة الموحدة
            "admin_role_ar"   => adminRoleAr($admin_role),
            // حالة التفعيل
            "admin_is_active" => 1,
            // من أضاف هذا الموظف (للسجل)
            "created_by"      => $currentAdmin['admin_full_name'],
        ],
    ]);
} else {
    // في حالة فشل الإدخال نُرجع رسالة فشل واضحة
    printFailure("فشل إضافة الموظف، يرجى المحاولة مرة أخرى");
}
?>