<?php
// ============================================================
// ملف: admin/sub_categories/edit_sub_category.php
// الغرض: تعديل بيانات قسم فرعي موجود في جدول sub_categories
//
// الحقل الإجباري الوحيد: sub_id
// وكل الحقول الأخرى اختيارية — نُحدّث ما أُرسل فقط
//
// ⭐ لماذا التحديث الجزئي؟
//    لأن الموظف قد يريد تصحيح الاسم العربي وحده
//    ولو أرسلنا كل الحقول لأصبح أي حقل نسيه = مسح للبيانات
//
// الحقول القابلة للتعديل:
//   sub_name_ar
//   sub_name_en
//   sub_category_id     (نقل التخصص لقسم رئيسي آخر)
//   sub_is_active       (1 لإعادة التفعيل بعد delete_sub_category.php)
//
// ⚠️ لا حذف فعلي هنا — التعطيل من delete_sub_category.php
//    وهذا الملف يسمح بإعادة التفعيل فقط عبر sub_is_active = 1
//
// الطريقة: POST
// الصلاحية المطلوبة: catalog.manage
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/sub_categories)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج
requirePermission($currentAdmin, 'catalog.manage');

// ============================================================
// الخطوة 2: استقبال معرّف التخصص والتحقق منه
// ============================================================
// معرّف التخصص المراد تعديله - إجباري
$sub_id = filterRequest("sub_id");

// إذا لم يُرسل المعرّف نوقف التنفيذ فوراً
if ($sub_id === '') {
    // رسالة توضح الحقل المطلوب
    printFailure("الحقل sub_id مطلوب");
    // إيقاف التنفيذ
    exit;
}

// تحويل المعرّف لرقم صحيح لحماية جملة WHERE من أي محتوى غير رقمي
$sub_id = (int) $sub_id;

// لا نقبل صفراً لأن AUTO_INCREMENT يبدأ من 1
if ($sub_id < 1) {
    // رسالة توضح أن المعرّف غير صالح
    printFailure("sub_id غير صالح");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 3: جلب بيانات التخصص الحالية
//
// ⭐ نحتاجها لسببين:
//    1. التأكد أن التخصص موجود قبل التعديل
//    2. معرفة الأب الحالي عند فحص تكرار الاسم
// ============================================================
// تجهيز استعلام محمي لجلب الصف الحالي مع اسم الأب
$stmtCurrent = $con->prepare(
    "SELECT
        sc.sub_id,
        sc.sub_category_id,
        sc.sub_name_ar,
        sc.sub_name_en,
        sc.sub_is_active,
        c.categories_name_ar
     FROM sub_categories sc
     INNER JOIN categories c
        ON c.categories_id = sc.sub_category_id
     WHERE sc.sub_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف التخصص
$stmtCurrent->execute([$sub_id]);
// جلب الصف الحالي
$current = $stmtCurrent->fetch(PDO::FETCH_ASSOC);

// إذا لم يوجد التخصص نرفض التعديل
if (!$current) {
    // رسالة توضح أن التخصص غير موجود
    printFailure("التخصص غير موجود", 404);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: استقبال الحقول القابلة للتعديل (كلها اختيارية)
// ============================================================
// الاسم العربي الجديد
$sub_name_ar     = trim(filterRequest("sub_name_ar"));
// الاسم الإنجليزي الجديد
$sub_name_en     = trim(filterRequest("sub_name_en"));
// معرّف القسم الرئيسي الجديد (لنقل التخصص)
$sub_category_id = filterRequest("sub_category_id");
// حالة التفعيل الجديدة (1 لإعادة التفعيل)
$sub_is_active   = filterRequest("sub_is_active");

// ============================================================
// الخطوة 5: بناء مصفوفة التحديث بالحقول المُرسَلة فقط
// ============================================================
// تهيئة مصفوفة فارغة سنملأها بما أرسله الموظف
$updateData = [];

// ---------- الاسم العربي ----------
// نتحقق فقط إذا أُرسل الحقل
if ($sub_name_ar !== '') {
    // قياس الطول لأن العمود varchar(100)
    if (mb_strlen($sub_name_ar) > 100) {
        // رسالة توضح الحد الأقصى
        printFailure("sub_name_ar يجب ألا يتجاوز 100 حرف");
        // إيقاف التنفيذ
        exit;
    }
    // الحد الأدنى حتى لا يُحفظ حرف واحد بلا معنى
    if (mb_strlen($sub_name_ar) < 2) {
        // رسالة توضح الحد الأدنى
        printFailure("الاسم العربي يجب أن يكون حرفين على الأقل");
        // إيقاف التنفيذ
        exit;
    }
    // إضافة الاسم العربي للتحديث
    $updateData["sub_name_ar"] = $sub_name_ar;
}

// ---------- الاسم الإنجليزي ----------
// نتحقق فقط إذا أُرسل الحقل
if ($sub_name_en !== '') {
    // قياس الطول لأن العمود varchar(100)
    if (mb_strlen($sub_name_en) > 100) {
        // رسالة توضح الحد الأقصى
        printFailure("sub_name_en يجب ألا يتجاوز 100 حرف");
        // إيقاف التنفيذ
        exit;
    }
    // الحد الأدنى للاسم الإنجليزي
    if (mb_strlen($sub_name_en) < 2) {
        // رسالة توضح الحد الأدنى
        printFailure("الاسم الإنجليزي يجب أن يكون حرفين على الأقل");
        // إيقاف التنفيذ
        exit;
    }
    // إضافة الاسم الإنجليزي للتحديث
    $updateData["sub_name_en"] = $sub_name_en;
}

// ---------- نقل التخصص لقسم رئيسي آخر ----------
// نتحقق فقط إذا أُرسل معرّف أب جديد
if ($sub_category_id !== '') {
    // تحويل المعرّف لرقم صحيح
    $newParentId = (int) $sub_category_id;

    // لا نقبل صفراً
    if ($newParentId < 1) {
        // رسالة توضح أن المعرّف غير صالح
        printFailure("sub_category_id غير صالح");
        // إيقاف التنفيذ
        exit;
    }

    // ============================================================
    // التحقق من وجود القسم الجديد وأنه مفعّل
    // ============================================================
    // متغيّر يحمل بيانات الأب الجديد
    $newParent = null;

    // ⚠️ نحمي الفحص بـ try/catch لأن عمود التفعيل قد لا يكون مُنفَّذاً بعد
    try {
        // محاولة الاستعلام مع عمود التفعيل
        $stmtParent = $con->prepare(
            "SELECT categories_id, categories_name_ar, categories_is_active
             FROM categories WHERE categories_id = ? LIMIT 1"
        );
        // تنفيذ الاستعلام بمعرّف الأب الجديد
        $stmtParent->execute([$newParentId]);
        // جلب صف الأب الجديد
        $newParent = $stmtParent->fetch(PDO::FETCH_ASSOC);
    } catch (Exception $e) {
        // العمود غير موجود بعد فنستعلم بلا عمود التفعيل
        $stmtParent = $con->prepare(
            "SELECT categories_id, categories_name_ar
             FROM categories WHERE categories_id = ? LIMIT 1"
        );
        // تنفيذ الاستعلام بمعرّف الأب الجديد
        $stmtParent->execute([$newParentId]);
        // جلب صف الأب الجديد
        $newParent = $stmtParent->fetch(PDO::FETCH_ASSOC);
    }

    // إذا لم يوجد القسم الجديد نرفض النقل
    if (!$newParent) {
        // رسالة توضح أن القسم الأب غير موجود
        printFailure("القسم الرئيسي الجديد غير موجود", 404);
        // إيقاف التنفيذ
        exit;
    }

    // ⚠️ نرفض النقل لقسم معطّل إن كان العمود موجوداً
    if (isset($newParent['categories_is_active']) &&
        (int) $newParent['categories_is_active'] !== 1) {
        // رسالة توضح أن الأب الجديد معطّل
        printFailure(
            "القسم الرئيسي (" . $newParent['categories_name_ar'] . ") "
            . "معطّل — لا يمكن نقل التخصص إليه",
            409
        );
        // إيقاف التنفيذ
        exit;
    }

    // إضافة معرّف الأب الجديد للتحديث
    $updateData["sub_category_id"] = $newParentId;
}

// ============================================================
// الخطوة 6: منع تكرار الاسم تحت نفس الأب مع استثناء الصف الحالي
// ============================================================
// الأب الذي سنفحص التكرار تحته: الجديد إن نُقل وإلا الأب الحالي
$checkParentId = $updateData["sub_category_id"] ?? (int) $current['sub_category_id'];
// الاسم العربي الذي سنفحصه: الجديد إن أُرسل وإلا الاسم الحالي
$checkNameAr   = $updateData["sub_name_ar"] ?? $current['sub_name_ar'];
// الاسم الإنجليزي الذي سنفحصه: الجديد إن أُرسل وإلا الاسم الحالي
$checkNameEn   = $updateData["sub_name_en"] ?? $current['sub_name_en'];

// نفحص التكرار فقط إذا تغيّر الاسم أو الأب فعلاً
if (isset($updateData["sub_name_ar"]) ||
    isset($updateData["sub_name_en"]) ||
    isset($updateData["sub_category_id"])) {
    // استعلام يبحث عن نفس الاسم تحت نفس الأب في صف آخر
    $stmtDup = $con->prepare(
        "SELECT sub_id FROM sub_categories
         WHERE sub_category_id = ?
           AND (sub_name_ar = ? OR sub_name_en = ?)
           AND sub_id <> ?
         LIMIT 1"
    );
    // تنفيذ الاستعلام بالأب والاسمين ومعرّف الصف الحالي
    $stmtDup->execute([$checkParentId, $checkNameAr, $checkNameEn, $sub_id]);
    // إذا وُجد تخصص آخر بنفس الاسم تحت نفس الأب نرفض التعديل
    if ($stmtDup->rowCount() > 0) {
        // رسالة توضح أن الاسم مستخدم
        printFailure("اسم التخصص مستخدم بالفعل داخل نفس القسم الرئيسي", 409);
        // إيقاف التنفيذ
        exit;
    }
}

// ---------- حالة التفعيل (إعادة تفعيل تخصص معطّل) ----------
// نقبل القيمة صفر لذلك نقارن بالنص الفارغ وليس empty
if ($sub_is_active !== '') {
    // تحويل القيمة لرقم صحيح (0 أو 1 فقط)
    $updateData["sub_is_active"] = ((int) $sub_is_active === 1) ? 1 : 0;
}

// ============================================================
// الخطوة 7: التأكد من وجود حقل واحد على الأقل للتحديث
// ============================================================
// إذا كانت المصفوفة فارغة فلا يوجد ما نُحدّثه
if (empty($updateData)) {
    // رسالة توضح عدم إرسال أي حقل
    printFailure("لم يتم إرسال أي حقل للتعديل");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 8: تنفيذ التحديث باستخدام دالتك الموحدة
// ============================================================
// استدعاء دالة التحديث مع false لمنع طباعة JSON مرتين
$result = updateData(
    "sub_categories",
    $updateData,
    "sub_id = $sub_id",
    false
);

// ============================================================
// الخطوة 9: جلب البيانات بعد التعديل
//
// ⚠️ updateData تُرجع rowCount
//    و MySQL تُرجع 0 إذا كانت القيم الجديدة مطابقة للقديمة
//    فلا نعتبر 0 فشلاً، بل نُعيد جلب الصف
// ============================================================
// تجهيز استعلام لجلب الصف بعد التعديل مع اسم الأب
$stmtAfter = $con->prepare(
    "SELECT
        sc.sub_id,
        sc.sub_category_id,
        sc.sub_name_ar,
        sc.sub_name_en,
        sc.sub_is_active,
        c.categories_name_ar
     FROM sub_categories sc
     INNER JOIN categories c
        ON c.categories_id = sc.sub_category_id
     WHERE sc.sub_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف التخصص
$stmtAfter->execute([$sub_id]);
// جلب الصف المحدَّث
$updated = $stmtAfter->fetch(PDO::FETCH_ASSOC);

// إذا فشل الجلب فهناك خطأ حقيقي في قاعدة البيانات
if (!$updated) {
    // رسالة توضح فشل جلب البيانات
    printFailure("تم التعديل لكن تعذّر جلب البيانات المحدَّثة", 500);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 10: تسجيل الإجراء في سجل النشاط الإداري
// ============================================================
// تسجيل تعديل التخصص
logAdminActivity(
    // بيانات الموظف المنفّذ
    $currentAdmin,
    // نوع الإجراء
    'edit_sub_category',
    // نوع الكيان
    'sub_category',
    // معرّف التخصص
    $sub_id,
    // الحقول التي تغيّرت فقط
    [
        // مفاتيح الحقول المحدَّثة
        "updated_fields" => array_keys($updateData),
    ]
);

// ============================================================
// الخطوة 11: إرسال الرد النهائي
// ============================================================
// إرسال JSON يحتوي البيانات بعد التعديل
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة نجاح بالعربية
    "message" => "تم تحديث بيانات التخصص بنجاح",
    // بيانات التخصص بعد التعديل
    "data"    => [
        // معرّف التخصص
        "sub_id"          => (int) $updated['sub_id'],
        // معرّف القسم الرئيسي الأب
        "sub_category_id" => (int) $updated['sub_category_id'],
        // اسم القسم الأب بالعربية
        "parent_name_ar"  => $updated['categories_name_ar'],
        // الاسم العربي بعد التعديل
        "sub_name_ar"     => $updated['sub_name_ar'],
        // الاسم الإنجليزي بعد التعديل
        "sub_name_en"     => $updated['sub_name_en'],
        // حالة التفعيل
        "sub_is_active"   => (int) $updated['sub_is_active'],
        // من نفّذ التعديل
        "updated_by"      => $currentAdmin['admin_full_name'],
    ],
]);
?>
