<?php
// ============================================================
// ملف: admin/sub_categories/add_sub_category.php
// الغرض: إضافة قسم فرعي جديد (تخصص دقيق) في جدول sub_categories
//
// ⭐ الأقسام الفرعية مثل: طباخ، ممرض، سباك
//    وهي الابن للقسم الرئيسي في categories
//
// ⚠️ هذا الملف للإضافة فقط
//    التعطيل (الحذف الناعم) في: delete_sub_category.php
//    التعديل في: edit_sub_category.php
//    العرض في: list_sub_category.php
//
// ⭐ القسم الفرعي الجديد يُحفظ مفعّلاً دائماً:
//    sub_is_active = 1  → ظاهر ويُختار فور إنشائه
//
// ⚠️ لا نضيف قسماً فرعياً تحت قسم رئيسي معطّل
//    لأن المستخدم لن يراه في قوائم الاختيار أصلاً
//
// الحقول الإجبارية: sub_category_id, sub_name_ar, sub_name_en
// الطريقة: POST
// الصلاحية المطلوبة: catalog.manage
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/sub_categories)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ catalog.manage يملكها: owner و manager
//    ولا يملكها: support و accountant
//    لأن تغيير التخصصات يغيّر شكل التطبيق لكل المستخدمين
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج
requirePermission($currentAdmin, 'catalog.manage');

// معرّف الموظف المنفّذ مأخوذ من التوكن لا من الطلب
$adminId = (int) $currentAdmin['admin_id'];

// ============================================================
// الخطوة 2: استقبال بيانات القسم الفرعي الجديد
// ============================================================
// معرّف القسم الرئيسي الأب - إجباري
$sub_category_id = filterRequest("sub_category_id");
// الاسم العربي للتخصص - إجباري
$sub_name_ar     = trim(filterRequest("sub_name_ar"));
// الاسم الإنجليزي للتخصص - إجباري
$sub_name_en     = trim(filterRequest("sub_name_en"));

// ============================================================
// الخطوة 3: التحقق من الحقول الإجبارية
// ============================================================
// نستخدم === '' وليس empty لأن empty ترفض الرقم صفر بالخطأ
if ($sub_category_id === '' || $sub_name_ar === '' || $sub_name_en === '') {
    // رسالة توضح الحقول المطلوبة
    printFailure("الحقول المطلوبة: sub_category_id, sub_name_ar, sub_name_en");
    // إيقاف التنفيذ
    exit;
}

// تحويل معرّف الأب لرقم صحيح لحماية جملة WHERE
$sub_category_id = (int) $sub_category_id;

// لا نقبل صفراً لأن AUTO_INCREMENT يبدأ من 1
if ($sub_category_id < 1) {
    // رسالة توضح أن المعرّف غير صالح
    printFailure("sub_category_id غير صالح");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: التحقق من طول الاسمين
// لأن العمودين varchar(100) يرفضان أي نص أطول
// ============================================================
// قياس طول الاسم العربي بالأحرف مع دعم العربية عبر mb_strlen
if (mb_strlen($sub_name_ar) > 100) {
    // رسالة توضح الحد الأقصى المسموح
    printFailure("sub_name_ar يجب ألا يتجاوز 100 حرف");
    // إيقاف التنفيذ
    exit;
}

// قياس طول الاسم الإنجليزي
if (mb_strlen($sub_name_en) > 100) {
    // رسالة توضح الحد الأقصى المسموح
    printFailure("sub_name_en يجب ألا يتجاوز 100 حرف");
    // إيقاف التنفيذ
    exit;
}

// الحد الأدنى حتى لا يُحفظ حرف واحد بلا معنى
if (mb_strlen($sub_name_ar) < 2) {
    // رسالة توضح الحد الأدنى للاسم العربي
    printFailure("الاسم العربي يجب أن يكون حرفين على الأقل");
    // إيقاف التنفيذ
    exit;
}

// الحد الأدنى للاسم الإنجليزي
if (mb_strlen($sub_name_en) < 2) {
    // رسالة توضح الحد الأدنى للاسم الإنجليزي
    printFailure("الاسم الإنجليزي يجب أن يكون حرفين على الأقل");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 5: التحقق من وجود القسم الرئيسي وأنه مفعّل
//
// ⭐ نفحص categories_is_active لأنك وافقت على التعطيل بدل الحذف
// ⚠️ لكن نفحص وجود العمود أولاً حتى يعمل الملف قبل تنفيذ SQL
// ============================================================
// متغيّر يحمل بيانات القسم الرئيسي الأب
$parentCategory = null;

// ⚠️ نحمي الفحص بـ try/catch لأن العمود قد لا يكون مُنفَّذاً بعد
try {
    // ⭐ محاولة الاستعلام مع عمود التفعيل
    $stmtParent = $con->prepare(
        "SELECT categories_id, categories_name_ar, categories_is_active
         FROM categories WHERE categories_id = ? LIMIT 1"
    );
    // تنفيذ الاستعلام بمعرّف القسم الأب
    $stmtParent->execute([$sub_category_id]);
    // جلب صف القسم الأب
    $parentCategory = $stmtParent->fetch(PDO::FETCH_ASSOC);
} catch (Exception $e) {
    // ⚠️ العمود غير موجود بعد فنستعلم بلا عمود التفعيل
    $stmtParent = $con->prepare(
        "SELECT categories_id, categories_name_ar
         FROM categories WHERE categories_id = ? LIMIT 1"
    );
    // تنفيذ الاستعلام بمعرّف القسم الأب
    $stmtParent->execute([$sub_category_id]);
    // جلب صف القسم الأب
    $parentCategory = $stmtParent->fetch(PDO::FETCH_ASSOC);
}

// إذا لم يوجد القسم الرئيسي نرفض الإضافة
if (!$parentCategory) {
    // رسالة توضح أن القسم الأب غير موجود
    printFailure("القسم الرئيسي غير موجود", 404);
    // إيقاف التنفيذ
    exit;
}

// ⚠️ نرفض الإضافة تحت قسم معطّل إن كان العمود موجوداً
if (isset($parentCategory['categories_is_active']) &&
    (int) $parentCategory['categories_is_active'] !== 1) {
    // رسالة توضح أن الأب معطّل فلا معنى لإضافة ابن تحته
    printFailure(
        "القسم الرئيسي (" . $parentCategory['categories_name_ar'] . ") "
        . "معطّل — لا يمكن إضافة تخصصات فيه",
        409
    );
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 6: منع تكرار اسم التخصص داخل نفس القسم الرئيسي
//
// ⭐ نفحص المفعّل والمعطّل معاً حتى لا يُنشأ تخصص بنفس الاسم
//    بينما صف قديم معطّل يحمل نفس التسمية تحت نفس الأب
// ⚠️ التكرار مسموح بين أقسام رئيسية مختلفة
//    (مثلاً "تنظيف عام" تحت النظافة وآخر تحت الضيافة)
// ============================================================
// استعلام يبحث عن نفس الاسم العربي أو الإنجليزي تحت نفس الأب
$stmtDup = $con->prepare(
    "SELECT sub_id, sub_name_ar, sub_is_active
     FROM sub_categories
     WHERE sub_category_id = ?
       AND (sub_name_ar = ? OR sub_name_en = ?)
     LIMIT 1"
);
// تنفيذ الاستعلام بمعرّف الأب والاسمين
$stmtDup->execute([$sub_category_id, $sub_name_ar, $sub_name_en]);
// جلب الصف المكرر إن وُجد
$duplicate = $stmtDup->fetch(PDO::FETCH_ASSOC);

// إذا وُجد اسم مطابق تحت نفس الأب نرفض الإضافة
if ($duplicate) {
    // نميّز الرسالة إن كان التخصص المكرر معطّلاً حتى يعيد الموظف تفعيله
    $dupHint = ((int) ($duplicate['sub_is_active'] ?? 1) === 0)
        ? " — التخصص موجود لكنه معطّل، فعّله بدلاً من إنشاء تخصص جديد"
        : "";
    // رسالة توضح أن الاسم مستخدم بالفعل تحت هذا القسم
    printFailure(
        "اسم التخصص مستخدم بالفعل داخل القسم ("
        . $parentCategory['categories_name_ar'] . ")"
        . $dupHint,
        409
    );
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 7: إدخال التخصص في جدول sub_categories
//
// ⭐ sub_is_active = 1 دائماً عند الإنشاء
//    التخصص الجديد يظهر فوراً في قوائم التطبيق
//    والتعطيل يتم لاحقاً من delete_sub_category.php وليس من هنا
// ============================================================
// تجهيز مصفوفة البيانات بأسماء الأعمدة الحقيقية في الجدول
$insertData = [
    // معرّف القسم الرئيسي الأب
    "sub_category_id" => $sub_category_id,
    // الاسم العربي للتخصص
    "sub_name_ar"     => $sub_name_ar,
    // الاسم الإنجليزي للتخصص
    "sub_name_en"     => $sub_name_en,
    // ⭐ مفعّل من لحظة إنشائه — التعطيل يتم من delete_sub_category.php
    "sub_is_active"   => 1,
];

// تنفيذ عملية الإدخال باستخدام دالتك الموحدة مع false لمنع طباعة JSON مرتين
$result = insertData("sub_categories", $insertData, false);

// ============================================================
// الخطوة 8: إرسال الرد النهائي
// ============================================================
// التحقق من نجاح عملية الإدخال
if ($result > 0) {

    // قراءة المعرّف الذي أنشأته قاعدة البيانات تلقائياً
    $newSubId = (int) $con->lastInsertId();

    // ============================================================
    // تسجيل الإجراء في سجل النشاط الإداري
    // ============================================================
    // تسجيل إضافة التخصص
    logAdminActivity(
        // بيانات الموظف المنفّذ
        $currentAdmin,
        // نوع الإجراء
        'create_sub_category',
        // نوع الكيان
        'sub_category',
        // معرّف التخصص الجديد
        $newSubId,
        // تفاصيل المراجعة
        [
            // الاسم العربي
            "name_ar"     => $sub_name_ar,
            // الاسم الإنجليزي
            "name_en"     => $sub_name_en,
            // معرّف الأب
            "parent_id"   => $sub_category_id,
            // اسم الأب العربي
            "parent_ar"   => $parentCategory['categories_name_ar'],
        ]
    );

    // إرسال JSON يحتوي بيانات التخصص الجديد
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // رسالة نجاح بالعربية جاهزة للعرض في اللوحة
        "message" => "تم إضافة التخصص بنجاح تحت القسم ("
                     . $parentCategory['categories_name_ar'] . ")",
        // بيانات التخصص المُضاف
        "data"    => [
            // المعرّف الذي أنشأته قاعدة البيانات تلقائياً
            "sub_id"          => $newSubId,
            // معرّف القسم الرئيسي الأب
            "sub_category_id" => $sub_category_id,
            // اسم القسم الرئيسي بالعربية
            "parent_name_ar"  => $parentCategory['categories_name_ar'],
            // الاسم العربي للتخصص
            "sub_name_ar"     => $sub_name_ar,
            // الاسم الإنجليزي للتخصص
            "sub_name_en"     => $sub_name_en,
            // ⭐ مفعّل — يظهر للمستخدمين ويمكن اختياره
            "sub_is_active"   => 1,
            // من أضاف هذا التخصص (للسجل)
            "created_by"      => $currentAdmin['admin_full_name'],
        ],
    ]);
} else {
    // في حالة فشل الإدخال نُرجع رسالة فشل واضحة
    printFailure("فشل إضافة التخصص، يرجى المحاولة مرة أخرى");
}
?>
