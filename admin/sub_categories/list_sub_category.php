<?php
// ============================================================
// ملف: admin/sub_categories/list_sub_category.php
// الغرض: عرض قائمة الأقسام الفرعية للإدارة مع حالتها واسم الأب
//
// ⭐ الفرق عن sub_categories/get_by_category.php:
//    get_by_category → التطبيق: تخصصات قسم واحد مفعّلة بلا توكن
//    هذا الملف       → اللوحة: كل التخصصات بما فيها المعطّلة + توكن
//
// ⭐ الفلاتر:
//   category_id → معرّف القسم الرئيسي (اختياري — فارغ = الكل)
//   is_active   → 1 مفعّل / 0 معطّل / all الكل (افتراضي)
//   search      → بحث في الاسم العربي أو الإنجليزي
//
// الطريقة: POST أو GET
// الصلاحية المطلوبة: catalog.view
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/sub_categories)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ catalog.view يملكها المدير وخدمة العملاء
//    لأن القائمة للعرض فقط ولا تغيّر شيئاً
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية عرض الكتالوج
requirePermission($currentAdmin, 'catalog.view');

// ============================================================
// الخطوة 2: استقبال معاملات الفلترة والبحث
// ============================================================
// فلتر القسم الرئيسي الأب (اختياري)
$categoryId = filterRequest("category_id");
// فلتر حالة التفعيل: 1 / 0 / all
$isActive   = filterRequest("is_active");
// نص البحث في اسم التخصص عربي أو إنجليزي
$search     = trim(filterRequest("search"));

// ============================================================
// الخطوة 3: بناء شروط WHERE المشتركة
// ============================================================
// نبدأ بشرط ثابت دائماً صحيح لتبسيط دمج الشروط بعده
$whereConditions = ["1 = 1"];
// مصفوفة معاملات الاستعلام
$params = [];

// ============================================================
// الخطوة 4: فلتر القسم الرئيسي
// ============================================================
// نُضيف الشرط فقط إذا أُرسل معرّف أب صالح
if ($categoryId !== '' && (int) $categoryId > 0) {
    // إضافة شرط الأب
    $whereConditions[] = "sc.sub_category_id = ?";
    // تمرير القيمة للاستعلام
    $params[] = (int) $categoryId;
}

// ============================================================
// الخطوة 5: فلتر حالة التفعيل
// ============================================================
// نُضيف الشرط فقط إذا طُلب مفعّل أو معطّل صراحةً
if ($isActive === '1' || $isActive === '0') {
    // إضافة شرط التفعيل
    $whereConditions[] = "sc.sub_is_active = ?";
    // تمرير القيمة للاستعلام
    $params[] = (int) $isActive;
}

// ============================================================
// الخطوة 6: البحث في الاسم العربي والإنجليزي
//
// ⚠️ الأقواس حول شروط OR إجبارية
//    وإلا تعارض OR مع شروط AND الأخرى وأعطى نتائج خاطئة
// ============================================================
// نُضيف الشرط فقط إذا أرسلت الواجهة نصاً للبحث
if ($search !== '') {
    // بناء شرط البحث في الاسمين بـ OR
    $whereConditions[] = "("
        . " sc.sub_name_ar LIKE ?"
        . " OR sc.sub_name_en LIKE ?"
        . ")";
    // تجهيز نص البحث مع % قبله وبعده للبحث الجزئي
    $searchTerm = "%{$search}%";
    // تمرير النص مرتين (مرة لكل حقل)
    $params[] = $searchTerm;
    $params[] = $searchTerm;
}

// تجميع الشروط في جملة WHERE واحدة
$whereSQL = implode(" AND ", $whereConditions);

// ============================================================
// الخطوة 7: جلب التخصصات مع اسم القسم الأب
//
// ⭐ الترتيب: حسب ترتيب الأب ثم معرّف التخصص
//    حتى تظهر تخصصات نفس القسم متجاورة في اللوحة
// ============================================================
// تجهيز استعلام القائمة
$stmt = $con->prepare(
    "SELECT
        sc.sub_id,
        sc.sub_category_id,
        sc.sub_name_ar,
        sc.sub_name_en,
        sc.sub_is_active,
        c.categories_name_ar,
        c.categories_name_en,
        c.categories_is_active,
        c.categories_sort
     FROM sub_categories sc
     INNER JOIN categories c
        ON c.categories_id = sc.sub_category_id
     WHERE $whereSQL
     ORDER BY
        c.categories_sort ASC,
        c.categories_id ASC,
        sc.sub_id ASC"
);
// تنفيذ الاستعلام بمعاملات الفلترة
$stmt->execute($params);
// جلب كل الصفوف كمصفوفة
$subCategories = $stmt->fetchAll(PDO::FETCH_ASSOC);

// ============================================================
// الخطوة 8: تحويل كل سجل لشكل مناسب لـ Flutter
// ============================================================
$resultData = array_map(function ($sub) {
    // إرجاع مصفوفة التخصص بالشكل الذي يقرأه موديل Flutter
    return [
        // معرّف التخصص
        "sub_id"               => (int) $sub['sub_id'],
        // معرّف القسم الرئيسي الأب
        "sub_category_id"      => (int) $sub['sub_category_id'],
        // اسم القسم الأب بالعربية
        "parent_name_ar"       => $sub['categories_name_ar'],
        // اسم القسم الأب بالإنجليزية
        "parent_name_en"       => $sub['categories_name_en'],
        // حالة تفعيل الأب (حتى تعرف اللوحة إن كان الأب معطّلاً)
        "parent_is_active"     => (int) $sub['categories_is_active'],
        // الاسم العربي للتخصص
        "sub_name_ar"          => $sub['sub_name_ar'],
        // الاسم الإنجليزي للتخصص
        "sub_name_en"          => $sub['sub_name_en'],
        // حالة التفعيل: 1 ظاهر · 0 معطّل
        "sub_is_active"        => (int) $sub['sub_is_active'],
    ];
}, $subCategories);

// ============================================================
// الخطوة 9: حساب إحصائيات سريعة لأعلى الصفحة
// ⚠️ الإحصائيات على الجدول كله لا على نتيجة الفلتر
//    حتى يبقى عدّاد المفعّل/المعطّل ثابتاً أثناء البحث
// ============================================================
$statsSQL = "
    SELECT
        -- عدد التخصصات المفعّلة
        SUM(CASE WHEN sub_is_active = 1 THEN 1 ELSE 0 END) AS active_count,
        -- عدد التخصصات المعطّلة
        SUM(CASE WHEN sub_is_active = 0 THEN 1 ELSE 0 END) AS inactive_count,
        -- العدد الكلي
        COUNT(sub_id) AS all_count
    FROM sub_categories
";
// تنفيذ استعلام الإحصائيات
$statsStmt = $con->prepare($statsSQL);
$statsStmt->execute();
// قراءة صف الإحصائيات
$stats = $statsStmt->fetch(PDO::FETCH_ASSOC);

// ============================================================
// الخطوة 10: إرسال الرد
// ============================================================
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة نجاح
    "message" => "تم جلب قائمة التخصصات بنجاح",
    // عدد النتائج في هذه الصفحة
    "count"   => count($resultData),
    // مصفوفة التخصصات
    "data"    => $resultData,
    // إحصائيات للعرض في أعلى الصفحة
    "stats"   => [
        // عدد التخصصات المفعّلة
        "active_count"   => (int) ($stats['active_count']   ?? 0),
        // عدد التخصصات المعطّلة
        "inactive_count" => (int) ($stats['inactive_count'] ?? 0),
        // العدد الكلي
        "all_count"      => (int) ($stats['all_count']      ?? 0),
    ],
]);
?>
