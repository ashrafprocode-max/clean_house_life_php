<?php
// ============================================================
// ملف: admin/sub_categories/delete_sub_category.php
// الغرض: تعطيل قسم فرعي من لوحة الإدارة (حذف ناعم)
//
// ⚠️⚠️ لا يوجد DELETE فعلي في هذا الملف إطلاقاً
//      لأن حذف صف يترك provider_services.ps_sub_cat_id يشير لتخصص مفقود
//      فتظهر خدمات بلا اسم مهنة في شاشة البحث وقد ينهار أي JOIN
//      والجدول عليه FOREIGN KEY ... ON DELETE CASCADE
//      فحذف التخصص قد يمسح خدمات مقدّمي الخدمة المرتبطة به
//
// ⭐ البديل المعتمد: التعطيل
//    sub_is_active = 0  → الصف يبقى فتعمل كل الـ JOINs
//                        لكن التخصص لا يظهر في قوائم الاختيار الجديدة
//
// ⭐ إعادة التفعيل تتم من edit_sub_category.php بإرسال sub_is_active = 1
//
// الحقل الإجباري: sub_id
// الطريقة: POST
// الصلاحية المطلوبة: catalog.manage
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/sub_categories)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ catalog.manage يملكها: owner و manager
//    ولا يملكها: support و accountant
//    لأن إخفاء تخصص يغيّر شكل التطبيق لكل المستخدمين
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج
requirePermission($currentAdmin, 'catalog.manage');

// ============================================================
// الخطوة 2: استقبال معرّف التخصص والتحقق منه
// ============================================================
// معرّف التخصص المراد تعطيله - إجباري
$sub_id = filterRequest("sub_id");

// إذا لم يُرسل المعرّف نوقف التنفيذ فوراً
if ($sub_id === '') {
    // رسالة توضح الحقل المطلوب
    printFailure("الحقل sub_id مطلوب لتعطيل التخصص");
    // إيقاف التنفيذ
    exit;
}

// تحويل المعرّف لرقم صحيح لحماية جملة WHERE من أي محتوى غير رقمي
$sub_id = (int) $sub_id;

// لا نقبل صفراً لأن AUTO_INCREMENT يبدأ من 1
if ($sub_id < 1) {
    // رسالة توضح أن المعرّف غير صالح
    printFailure("sub_id غير صالح");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 3: جلب التخصص للتأكد أنه موجود قبل التعطيل
// ============================================================
// تجهيز استعلام محمي لجلب الصف الحالي مع اسم القسم الأب
$stmtSub = $con->prepare(
    "SELECT
        sc.sub_id,
        sc.sub_category_id,
        sc.sub_name_ar,
        sc.sub_name_en,
        sc.sub_is_active,
        c.categories_name_ar
     FROM sub_categories sc
     INNER JOIN categories c
        ON c.categories_id = sc.sub_category_id
     WHERE sc.sub_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف التخصص
$stmtSub->execute([$sub_id]);
// جلب صف التخصص
$targetSub = $stmtSub->fetch(PDO::FETCH_ASSOC);

// إذا لم يوجد التخصص نرفض التعطيل
if (!$targetSub) {
    // رسالة توضح أن التخصص غير موجود
    printFailure("التخصص غير موجود", 404);
    // إيقاف التنفيذ
    exit;
}

// إذا كان معطّلاً مسبقاً نُخبر الموظف بدل تكرار التحديث
if (isset($targetSub['sub_is_active']) &&
    (int) $targetSub['sub_is_active'] === 0) {
    // رسالة توضح أن التخصص معطّل بالفعل
    printFailure("التخصص معطّل بالفعل", 409);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: التحديث — sub_is_active = 0 فقط
//
// ⚠️ لا DELETE حتى لا تُمسح خدمات مقدّمي الخدمة بـ ON DELETE CASCADE
// ============================================================
// تجهيز استعلام التعطيل المحمي
$stmtOff = $con->prepare(
    "UPDATE sub_categories
     SET sub_is_active = 0
     WHERE sub_id = ?
     LIMIT 1"
);
// تنفيذ التحديث بمعرّف التخصص
$stmtOff->execute([$sub_id]);

// ============================================================
// الخطوة 5: تسجيل الإجراء في سجل النشاط الإداري
// ============================================================
// تسجيل تعطيل التخصص باسم الموظف المنفّذ
logAdminActivity(
    // بيانات الموظف المنفّذ
    $currentAdmin,
    // نوع الإجراء
    'deactivate_sub_category',
    // نوع الكيان
    'sub_category',
    // معرّف التخصص المعطّل
    $sub_id,
    // تفاصيل المراجعة
    [
        // الاسم العربي للتخصص
        "name_ar"   => $targetSub['sub_name_ar'],
        // الاسم الإنجليزي للتخصص
        "name_en"   => $targetSub['sub_name_en'],
        // اسم القسم الأب
        "parent_ar" => $targetSub['categories_name_ar'],
    ]
);

// ============================================================
// الخطوة 6: إرسال رد نجاح التعطيل
// ============================================================
// إرسال JSON يوضح أن التخصص أُخفي دون حذفه
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة عربية جاهزة للعرض في اللوحة
    "message" => "تم تعطيل التخصص بنجاح — لم يُحذف من قاعدة البيانات",
    // بيانات التخصص بعد التعطيل
    "data"    => [
        // معرّف التخصص
        "sub_id"          => $sub_id,
        // معرّف القسم الرئيسي الأب
        "sub_category_id" => (int) $targetSub['sub_category_id'],
        // اسم القسم الأب
        "parent_name_ar"  => $targetSub['categories_name_ar'],
        // الاسم العربي
        "sub_name_ar"     => $targetSub['sub_name_ar'],
        // الاسم الإنجليزي
        "sub_name_en"     => $targetSub['sub_name_en'],
        // ⭐ صفر = معطّل ولا يظهر للمستخدمين
        "sub_is_active"   => 0,
        // من نفّذ التعطيل
        "deactivated_by"  => $currentAdmin['admin_full_name'],
    ],
]);
?>
