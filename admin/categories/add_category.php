<?php
// ============================================================
// ملف: admin/categories/add_category.php
// الغرض: إضافة قسم رئيسي جديد في جدول categories من لوحة الإدارة
//
// ⭐ الأقسام الكبرى مثل: ضيافة، رعاية، صيانة
//    وهي الأب لكل التخصصات الدقيقة في sub_categories
//
// ⚠️ هذا الملف للإضافة فقط
//    التعطيل (الحذف الناعم) انتقل إلى: delete_category.php
//    التعديل انتقل إلى: edit_category.php
//    العرض انتقل إلى: list_category.php
//
// ⭐ القسم الجديد يُحفظ مفعّلاً دائماً:
//    categories_is_active = 1  → ظاهر ويُختار فور إنشائه
//
// الحقول الإجبارية: categories_name_ar, categories_name_en
// الحقول الاختيارية: categories_image, categories_sort
// الطريقة: POST (multipart/form-data إذا رُفعت أيقونة)
// الصلاحية المطلوبة: catalog.manage
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/categories)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ catalog.manage يملكها: owner و manager
//    ولا يملكها: support و accountant
//    لأن تغيير الأقسام يغيّر شكل التطبيق لكل المستخدمين
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج (الأقسام والتخصصات والتوقيتات)
requirePermission($currentAdmin, 'catalog.manage');

// معرّف الموظف المنفّذ مأخوذ من التوكن لا من الطلب
$adminId = (int) $currentAdmin['admin_id'];

// ============================================================
// الخطوة 2: استقبال بيانات القسم الجديد
// ============================================================
// الاسم العربي للقسم - إجباري
$categories_name_ar = trim(filterRequest("categories_name_ar"));
// الاسم الإنجليزي للقسم - إجباري
$categories_name_en = trim(filterRequest("categories_name_en"));
// ترتيب العرض — الأصغر يظهر أولاً - اختياري (الافتراضي 0)
$categories_sort    = trim(filterRequest("categories_sort"));

// ============================================================
// الخطوة 3: التحقق من الحقول الإجبارية
// ============================================================
// نستخدم === '' وليس empty لأن empty ترفض الرقم صفر بالخطأ
if ($categories_name_ar === '' || $categories_name_en === '') {
    // رسالة توضح الحقول المطلوبة
    printFailure("الحقول المطلوبة: categories_name_ar, categories_name_en");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: التحقق من طول الاسمين
// لأن العمودين varchar(100) يرفضان أي نص أطول
// ============================================================
// قياس طول الاسم العربي بالأحرف مع دعم العربية عبر mb_strlen
if (mb_strlen($categories_name_ar) > 100) {
    // رسالة توضح الحد الأقصى المسموح
    printFailure("categories_name_ar يجب ألا يتجاوز 100 حرف");
    // إيقاف التنفيذ
    exit;
}

// قياس طول الاسم الإنجليزي
if (mb_strlen($categories_name_en) > 100) {
    // رسالة توضح الحد الأقصى المسموح
    printFailure("categories_name_en يجب ألا يتجاوز 100 حرف");
    // إيقاف التنفيذ
    exit;
}

// الحد الأدنى حتى لا يُحفظ حرف واحد بلا معنى
if (mb_strlen($categories_name_ar) < 2) {
    // رسالة توضح الحد الأدنى للاسم العربي
    printFailure("الاسم العربي يجب أن يكون حرفين على الأقل");
    // إيقاف التنفيذ
    exit;
}

// الحد الأدنى للاسم الإنجليزي
if (mb_strlen($categories_name_en) < 2) {
    // رسالة توضح الحد الأدنى للاسم الإنجليزي
    printFailure("الاسم الإنجليزي يجب أن يكون حرفين على الأقل");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 5: معالجة ترتيب العرض
// العمود SMALLINT UNSIGNED فالقيم السالبة مرفوضة
// ============================================================
// إن لم يُرسل الترتيب نضع صفر (يظهر في النهاية عادة)
if ($categories_sort === '') {
    // القيمة الافتراضية لعمود categories_sort
    $categories_sort = 0;
}

// تحويل الترتيب لرقم صحيح
$categories_sort = (int) $categories_sort;

// رفض القيم السالبة لأن العمود UNSIGNED
if ($categories_sort < 0) {
    // رسالة توضح أن الترتيب لا يكون سالباً
    printFailure("categories_sort يجب أن يكون صفراً أو أكبر");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 6: منع تكرار اسم القسم
// ⭐ نفحص المفعّل والمعطّل معاً حتى لا يُنشأ قسم بنفس الاسم
//    بينما صف قديم معطّل يحمل نفس التسمية
// ============================================================
// استعلام يبحث عن نفس الاسم العربي أو الإنجليزي
$stmtDup = $con->prepare(
    "SELECT categories_id, categories_name_ar, categories_is_active
     FROM categories
     WHERE categories_name_ar = ? OR categories_name_en = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بالاسمين
$stmtDup->execute([$categories_name_ar, $categories_name_en]);
// جلب الصف المكرر إن وُجد
$duplicate = $stmtDup->fetch(PDO::FETCH_ASSOC);

// إذا وُجد اسم مطابق نرفض الإضافة
if ($duplicate) {
    // نميّز الرسالة إن كان القسم المكرر معطّلاً حتى يعيد الموظف تفعيله بدل الإنشاء
    $dupHint = ((int) ($duplicate['categories_is_active'] ?? 1) === 0)
        ? " — القسم موجود لكنه معطّل، فعّله بدلاً من إنشاء قسم جديد"
        : "";
    // رسالة توضح أن الاسم مستخدم بالفعل
    printFailure("اسم القسم مستخدم بالفعل" . $dupHint, 409);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 7: رفع أيقونة القسم (اختياري)
//
// ⭐ الأيقونة تُحفظ في upload/categories/
//    والعمود يحفظ اسم الملف فقط لا المسار الكامل
//
// ⚠️ الامتدادات المسموحة: png / svg / jpg / jpeg / webp
//    حسب تعليق الجدول: أيقونة SVG أو PNG عند إضافة قسم جديد
// ============================================================
// اسم ملف الأيقونة — null إن لم تُرفع
$imageName = null;

// نتحقق أن الملف أُرسل فعلاً وليس حقلاً فارغاً
if (isset($_FILES['categories_image']) &&
    $_FILES['categories_image']['error'] !== UPLOAD_ERR_NO_FILE) {

    // استخراج امتداد الملف الأصلي وتحويله لحروف صغيرة
    $imgExt = strtolower(pathinfo(
        $_FILES['categories_image']['name'],
        PATHINFO_EXTENSION
    ));

    // ⭐ قائمة امتدادات الأيقونات المسموحة للأقسام
    $allowedIconExt = ['png', 'svg', 'jpg', 'jpeg', 'webp'];

    // إذا كان الامتداد غير مسموح نرفض الرفع
    if (!in_array($imgExt, $allowedIconExt, true)) {
        // رسالة توضح الامتدادات المسموحة
        printFailure("أيقونة القسم يجب أن تكون: png أو svg أو jpg أو jpeg أو webp");
        // إيقاف التنفيذ
        exit;
    }

    // رفع الأيقونة لمجلد الأقسام بدالتك الموحدة
    $imageName = imageUploadtwo(
        // مسار مجلد أيقونات الأقسام من موقع هذا الملف
        __DIR__ . "/../../upload/categories/",
        // اسم حقل الملف في الطلب
        "categories_image"
    );

    // نتحقق من نجاح الرفع
    if (in_array($imageName,
                 ["fail", "empty", "extension_error", "size_error"], true)) {
        // ⚠️ نُفرّغ المتغيّر لأن الملف لم يُرفع فعلاً
        $imageName = null;
        // رسالة توضح فشل الرفع
        printFailure("فشل رفع أيقونة القسم، تأكد أن حجمها أقل من 10 ميجا");
        // إيقاف التنفيذ
        exit;
    }
}

// ============================================================
// الخطوة 8: إدخال القسم في جدول categories
//
// ⭐ categories_is_active = 1 دائماً عند الإنشاء
//    القسم الجديد يظهر فوراً في قوائم التطبيق
//    والتعطيل يتم لاحقاً من delete_category.php وليس من هنا
// ============================================================
// تجهيز مصفوفة البيانات بأسماء الأعمدة الحقيقية في الجدول
$insertData = [
    // الاسم العربي للقسم
    "categories_name_ar"   => $categories_name_ar,
    // الاسم الإنجليزي للقسم
    "categories_name_en"   => $categories_name_en,
    // اسم ملف الأيقونة أو null إن لم تُرفع
    "categories_image"     => $imageName,
    // ⭐ مفعّل من لحظة إنشائه — التعطيل يتم من delete_category.php
    "categories_is_active" => 1,
    // ترتيب العرض
    "categories_sort"      => $categories_sort,
];

// تنفيذ عملية الإدخال باستخدام دالتك الموحدة مع false لمنع طباعة JSON مرتين
$result = insertData("categories", $insertData, false);

// ============================================================
// الخطوة 9: إرسال الرد النهائي
// ============================================================
// التحقق من نجاح عملية الإدخال
if ($result > 0) {

    // قراءة المعرّف الذي أنشأته قاعدة البيانات تلقائياً
    $newCatId = (int) $con->lastInsertId();

    // ============================================================
    // تسجيل الإجراء في سجل النشاط الإداري
    // ============================================================
    // تسجيل إضافة القسم
    logAdminActivity(
        // بيانات الموظف المنفّذ
        $currentAdmin,
        // نوع الإجراء
        'create_category',
        // نوع الكيان
        'category',
        // معرّف القسم الجديد
        $newCatId,
        // تفاصيل المراجعة
        [
            // الاسم العربي
            "name_ar" => $categories_name_ar,
            // الاسم الإنجليزي
            "name_en" => $categories_name_en,
            // هل رُفعت أيقونة
            "has_image" => $imageName !== null,
        ]
    );

    // ============================================================
    // بناء رابط الأيقونة بنفس أسلوب categories/get_all.php
    // حتى لا يتكرر مسار categories/categories في الرابط
    // ============================================================
    // الرجوع من admin/categories إلى جذر المشروع
    $scriptDir = dirname(dirname(dirname($_SERVER['SCRIPT_NAME'])));
    // بناء عنوان الأساس مع دعم https
    $baseUrl = (isset($_SERVER['HTTPS']) ? 'https' : 'http')
        . '://' . $_SERVER['HTTP_HOST']
        . ($scriptDir === '/' || $scriptDir === '\\' ? '' : $scriptDir);
    // إزالة الشرطة المائلة الزائدة من نهاية الرابط
    $baseUrl = rtrim($baseUrl, '/');

    // إرسال JSON يحتوي بيانات القسم الجديد
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // رسالة نجاح بالعربية جاهزة للعرض في اللوحة
        "message" => "تم إضافة القسم بنجاح",
        // بيانات القسم المُضاف
        "data"    => [
            // المعرّف الذي أنشأته قاعدة البيانات تلقائياً
            "categories_id"        => $newCatId,
            // الاسم العربي
            "categories_name_ar"   => $categories_name_ar,
            // الاسم الإنجليزي
            "categories_name_en"   => $categories_name_en,
            // رابط الأيقونة الكامل أو null
            "categories_image"     => $imageName
                ? $baseUrl . '/upload/categories/' . $imageName
                : null,
            // ⭐ مفعّل — يظهر للمستخدمين ويمكن اختياره
            "categories_is_active" => 1,
            // ترتيب العرض
            "categories_sort"      => $categories_sort,
            // من أضاف هذا القسم (للسجل)
            "created_by"           => $currentAdmin['admin_full_name'],
        ],
    ]);
} else {
    // في حالة فشل الإدخال نُرجع رسالة فشل واضحة
    printFailure("فشل إضافة القسم، يرجى المحاولة مرة أخرى");
}
?>