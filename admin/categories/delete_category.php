<?php
// ============================================================
// ملف: admin/categories/delete_category.php
// الغرض: تعطيل قسم رئيسي من لوحة الإدارة (حذف ناعم)
//
// ⚠️⚠️ لا يوجد DELETE فعلي في هذا الملف إطلاقاً
//      لأن حذف صف يترك provider_services.ps_cat_id يشير لقسم مفقود
//      فتظهر خدمات بلا اسم في شاشة البحث وقد ينهار أي JOIN
//
// ⭐ البديل المعتمد: التعطيل
//    categories_is_active = 0  → الصف يبقى فتعمل كل الـ JOINs
//                               لكن القسم لا يظهر في قوائم الاختيار الجديدة
//
// ⭐ إعادة التفعيل تتم من edit_category.php بإرسال categories_is_active = 1
//
// الحقل الإجباري: categories_id
// الطريقة: POST
// الصلاحية المطلوبة: catalog.manage
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء لأن الملف داخل admin/categories)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ catalog.manage يملكها: owner و manager
//    ولا يملكها: support و accountant
//    لأن إخفاء قسم يغيّر شكل التطبيق لكل المستخدمين
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إدارة الكتالوج
requirePermission($currentAdmin, 'catalog.manage');

// ============================================================
// الخطوة 2: استقبال معرّف القسم والتحقق منه
// ============================================================
// معرّف القسم المراد تعطيله - إجباري
$categories_id = filterRequest("categories_id");

// إذا لم يُرسل المعرّف نوقف التنفيذ فوراً
if ($categories_id === '') {
    // رسالة توضح الحقل المطلوب
    printFailure("الحقل categories_id مطلوب لتعطيل القسم");
    // إيقاف التنفيذ
    exit;
}

// تحويل المعرّف لرقم صحيح لحماية جملة WHERE من أي محتوى غير رقمي
$categories_id = (int) $categories_id;

// لا نقبل صفراً لأن AUTO_INCREMENT يبدأ من 1
if ($categories_id < 1) {
    // رسالة توضح أن المعرّف غير صالح
    printFailure("categories_id غير صالح");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 3: جلب القسم للتأكد أنه موجود قبل التعطيل
// ============================================================
// تجهيز استعلام محمي لجلب الصف الحالي
$stmtCat = $con->prepare(
    "SELECT categories_id, categories_name_ar, categories_name_en,
            categories_is_active
     FROM categories
     WHERE categories_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف القسم
$stmtCat->execute([$categories_id]);
// جلب صف القسم
$targetCat = $stmtCat->fetch(PDO::FETCH_ASSOC);

// إذا لم يوجد القسم نرفض التعطيل
if (!$targetCat) {
    // رسالة توضح أن القسم غير موجود
    printFailure("القسم غير موجود", 404);
    // إيقاف التنفيذ
    exit;
}

// إذا كان معطّلاً مسبقاً نُخبر الموظف بدل تكرار التحديث
if (isset($targetCat['categories_is_active']) &&
    (int) $targetCat['categories_is_active'] === 0) {
    // رسالة توضح أن القسم معطّل بالفعل
    printFailure("القسم معطّل بالفعل", 409);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 4: التحديث — categories_is_active = 0 فقط
//
// ⚠️ لا DELETE ولا مسح للأيقونة
//    الأيقونة تبقى لأن إعادة التفعيل من edit_category.php
//    يجب أن تُظهر نفس الصورة دون رفعها من جديد
// ============================================================
// تجهيز استعلام التعطيل المحمي
$stmtOff = $con->prepare(
    "UPDATE categories
     SET categories_is_active = 0
     WHERE categories_id = ?
     LIMIT 1"
);
// تنفيذ التحديث بمعرّف القسم
$stmtOff->execute([$categories_id]);

// ============================================================
// الخطوة 5: تسجيل الإجراء في سجل النشاط الإداري
// ============================================================
// تسجيل تعطيل القسم باسم الموظف المنفّذ
logAdminActivity(
    // بيانات الموظف المنفّذ
    $currentAdmin,
    // نوع الإجراء
    'deactivate_category',
    // نوع الكيان
    'category',
    // معرّف القسم المعطّل
    $categories_id,
    // تفاصيل المراجعة
    [
        // الاسم العربي للقسم
        "name_ar" => $targetCat['categories_name_ar'],
        // الاسم الإنجليزي للقسم
        "name_en" => $targetCat['categories_name_en'],
    ]
);

// ============================================================
// الخطوة 6: إرسال رد نجاح التعطيل
// ============================================================
// إرسال JSON يوضح أن القسم أُخفي دون حذفه
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة عربية جاهزة للعرض في اللوحة
    "message" => "تم تعطيل القسم بنجاح — لم يُحذف من قاعدة البيانات",
    // بيانات القسم بعد التعطيل
    "data"    => [
        // معرّف القسم
        "categories_id"        => $categories_id,
        // الاسم العربي
        "categories_name_ar"   => $targetCat['categories_name_ar'],
        // الاسم الإنجليزي
        "categories_name_en"   => $targetCat['categories_name_en'],
        // ⭐ صفر = معطّل ولا يظهر للمستخدمين
        "categories_is_active" => 0,
        // من نفّذ التعطيل
        "deactivated_by"       => $currentAdmin['admin_full_name'],
    ],
]);
?>
