<?php
// ============================================================
// ملف: admin/customers/check_phone.php
// الغرض: فحص رقم هاتف قبل إنشاء حساب جديد من لوحة الإدارة
// الطريقة: POST
//
// ⭐⭐ لماذا هذا الملف قبل الإنشاء؟
//   لأن users_phone عليه UNIQUE، فلو أنشأ المندوب حساباً برقم موجود
//   لظهر خطأ SQL غامض. وهذا الملف يُخبره قبل أن يكتب أي بيانات:
//     "الرقم لـ (أحمد علي) — عميل مسجّل بلا شركة، أتربط الشركة بحسابه؟"
//
// ⭐ ويُغطّي كل الحالات الخمس في طلب واحد
//
// الحقل الإجباري: phone
// ============================================================

// تضمين ملف الاتصال (مستويان للوراء لأن الملف داخل admin/customers)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من توكن الإدارة والصلاحية
//
// ⭐ نطلب صلاحية العرض فقط لأن الفحص قراءة لا كتابة
//    والمندوب يملك companies.view فيستطيع الفحص
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// فرض صلاحية عرض الشركات
requirePermission($currentAdmin, 'companies.view');

// ============================================================
// الخطوة 2: استقبال رقم الهاتف وتوحيد صيغته
// ============================================================
// رقم الهاتف كما كتبه الموظف - إجباري
$rawPhone = filterRequest("phone");

// إذا لم يُرسل الرقم نوقف التنفيذ فوراً
if ($rawPhone === '') {
    // رسالة توضح الحقل المطلوب
    printFailure("الحقل phone مطلوب");
    // إيقاف التنفيذ
    exit;
}

// ⭐ توحيد صيغة الرقم قبل البحث
// ⚠️ إلزامي وإلا لم نجد 01055555555 عند البحث عن +201****5555
$phone = normalizePhoneNumber($rawPhone);

// ============================================================
// الخطوة 3: التحقق من صيغة الرقم بعد التوحيد
// ============================================================
// نتأكد أن الرقم أرقام فقط وطوله بين 10 و 15 خانة
if (!preg_match('/^[0-9]{10,15}$/', $phone)) {
    // رسالة توضح الصيغة المطلوبة مع الرقم بعد التوحيد
    printFailure(
        "رقم الهاتف غير صحيح — يجب أن يكون من 10 إلى 15 رقماً",
        400,
        [
            // ⭐ نُرجع الرقم بعد التوحيد ليرى الموظف ما فُهم من كتابته
            "normalized_phone" => $phone,
        ]
    );
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// ⭐ الخطوة 4: البحث عن الحساب مع كل ملحقاته في استعلام واحد
//
// ⭐ لماذا استعلام واحد بـ LEFT JOIN؟
//   لأن المندوب واقف أمام العميل، وثلاثة استعلامات متتابعة
//   على اتصال موبايل ضعيف تعني ثلاث ثوانٍ انتظار
// ============================================================
// تجهيز استعلام شامل يجمع الحساب وشركته وملفه المهني وملفه كعميل
$stmt = $con->prepare(
    "SELECT
        -- ===== بيانات الحساب =====
        u.users_id,
        u.users_full_name,
        u.users_phone,
        u.users_type,
        u.users_is_active,
        u.users_approve,
        u.users_country,
        u.users_region,
        u.users_created_at,
        -- ⭐ هل أنشأه موظف أم سجّل نفسه؟
        u.users_created_by_admin,
        -- ⭐ هل كلمة مروره ما زالت مؤقتة؟
        u.users_password_is_temp,
        -- ⭐ اسم الموظف الذي أنشأ الحساب
        a.admin_full_name AS created_by_admin_name,
        -- ===== ⭐ بيانات الشركة إن وُجدت =====
        c.company_id,
        c.company_name,
        c.company_business_type,
        -- ===== ⭐ بيانات الملف المهني إن وُجد =====
        pp.providers_id,
        pp.providers_is_verified,
        -- ===== بيانات ملف العميل إن وُجد =====
        cp.clients_id
     FROM users u
     -- ربط الموظف المنشئ (قد يكون NULL)
     LEFT JOIN admin_users a
            ON a.admin_id = u.users_created_by_admin
     -- ⭐ ربط الشركة المسجّلة لهذا المستخدم
     LEFT JOIN company_registering c
            ON c.company_user_id = u.users_id
     -- ربط الملف المهني لمقدم الخدمة
     LEFT JOIN professional_profiles pp
            ON pp.providers_users_id = u.users_id
     -- ربط ملف العميل
     LEFT JOIN client_profiles cp
            ON cp.clients_users_id = u.users_id
     WHERE u.users_phone = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بالرقم الموحّد
$stmt->execute([$phone]);
// جلب الصف إن وُجد
$row = $stmt->fetch(PDO::FETCH_ASSOC);

// ============================================================
// ⭐ الحالة الأولى: الرقم غير مسجّل — يمكن الإنشاء
// ============================================================
// إذا لم يوجد أي حساب بهذا الرقم
if (!$row) {
    // إرسال رد يوضح أن الرقم متاح
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // رسالة عربية جاهزة للعرض
        "message" => "الرقم غير مسجّل — يمكنك إنشاء حساب جديد",
        // بيانات النتيجة
        "data"    => [
            // ⭐ المفتاح الذي تقرأه فلاتر لتحديد الشاشة التالية
            "state"            => "available",
            // ⭐ ترجمة الحالة جاهزة من PHP
            "state_ar"         => "متاح للإنشاء",
            // الرقم بعد التوحيد ليحفظه التطبيق ويُرسله كما هو
            "normalized_phone" => $phone,
            // ⭐ هل يستطيع المندوب المتابعة للإنشاء؟
            "can_create"       => true,
            // لا حساب موجود
            "user"             => null,
        ],
    ]);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 5: تجهيز بيانات الحساب الموجود للعرض
// ============================================================
// معرّف المستخدم
$userId = (int) $row['users_id'];
// ⭐ هل له شركة مسجّلة؟
$hasCompany  = !empty($row['company_id']);
// ⭐ هل له ملف مهني كمقدم خدمة؟
$hasProvider = !empty($row['providers_id']);
// هل له ملف عميل؟
$hasClient   = !empty($row['clients_id']);

// ============================================================
// ⭐⭐ الخطوة 6: تحديد الحالة وما يستطيع المندوب فعله
//
// ⭐ نُرجع الحالة كمفتاح إنجليزي للمنطق وترجمة عربية للعرض
//    فلا تحتاج فلاتر أي شرط لغوي
// ============================================================
// تهيئة الحالة ورسالتها والإجراء المتاح
$state       = "";
$stateAr     = "";
$message     = "";
$canCreate   = false;
$canLink     = false;

// ⭐ الحالة الثانية: له شركة بالفعل
if ($hasCompany) {
    // مفتاح الحالة للمنطق
    $state     = "has_company";
    // ترجمة الحالة للعرض
    $stateAr   = "لديه شركة مسجّلة";
    // رسالة توضح الموقف والحل
    $message   = "هذا الرقم لديه نشاط مسجّل بالفعل باسم: "
                 . $row['company_name']
                 . " — افتح صفحة التعديل بدلاً من الإنشاء";
    // ⚠️ لا يجوز إنشاء شركة ثانية لنفس المستخدم
    $canCreate = false;
    // ولا يجوز الربط لأنه مربوط بالفعل
    $canLink   = false;

// ⭐⭐ الحالة الثالثة: حساب موجود بلا شركة — يمكن الربط
} else {
    // مفتاح الحالة للمنطق
    $state     = "exists_no_company";
    // ترجمة الحالة للعرض
    $stateAr   = "حساب موجود بلا نشاط";
    // ⭐ رسالة تشرح الخيار الوحيد المتاح
    $message   = "الرقم مسجّل بالفعل لحساب: " . $row['users_full_name']
                 . " (" . ($row['users_type'] === 'provider'
                           ? 'مقدم خدمة' : 'عميل') . ")"
                 . " — يمكنك ربط النشاط الجديد بحسابه الحالي";
    // ⚠️ لا نُنشئ حساباً جديداً لأن الرقم محجوز
    $canCreate = false;
    // ⭐ لكن نستطيع ربط الشركة بحسابه الموجود
    $canLink   = true;
}

// ============================================================
// ⚠️ الخطوة 7: تنبيه إن كان الحساب معطّلاً
// ============================================================
// ⭐ نُجهّز تنبيهاً منفصلاً لأن الحساب المعطّل لا يستطيع الدخول
$warning = null;

// نتحقق من حالة التفعيل
if ((int)$row['users_is_active'] !== 1) {
    // تنبيه أن الحساب معطّل
    $warning = "⚠️ هذا الحساب معطّل ولا يستطيع صاحبه الدخول — "
               . "فعّله أولاً من إدارة العملاء";
    // ⚠️ ولا نسمح بالربط بحساب معطّل
    $canLink = false;

// نتحقق من حالة التحقق بـ OTP
} elseif ((int)$row['users_approve'] !== 1) {
    // تنبيه أن الحساب لم يتحقق من رقمه
    $warning = "⚠️ هذا الحساب لم يتحقق من رقمه بـ OTP بعد — "
               . "لن يستطيع الدخول حتى يتحقق";
}

// ============================================================
// الخطوة 8: إرسال الرد النهائي
// ============================================================
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // ⭐ رسالة عربية جاهزة للعرض مباشرة
    "message" => $message,
    // بيانات النتيجة
    "data"    => [
        // ⭐ مفتاح الحالة للمنطق في فلاتر
        "state"            => $state,
        // ⭐ ترجمة الحالة للعرض
        "state_ar"         => $stateAr,
        // الرقم بعد التوحيد
        "normalized_phone" => $phone,
        // ⭐ هل يمكن إنشاء حساب جديد؟
        "can_create"       => $canCreate,
        // ⭐⭐ هل يمكن ربط النشاط بالحساب الموجود؟
        "can_link"         => $canLink,
        // ⚠️ تنبيه إن وُجد (null إن لم يوجد)
        "warning"          => $warning,

        // ===== ⭐ بيانات الحساب الموجود =====
        "user" => [
            // معرّف المستخدم (يُمرَّر لـ add_company_account عند الربط)
            "users_id"          => $userId,
            // الاسم الكامل
            "users_full_name"   => $row['users_full_name'],
            // رقم الهاتف
            "users_phone"       => $row['users_phone'],
            // نوع الحساب
            "users_type"        => $row['users_type'],
            // ⭐ ترجمة نوع الحساب
            "users_type_ar"     => $row['users_type'] === 'provider'
                                   ? 'مقدم خدمة' : 'عميل',
            // الدولة المسجّلة
            "users_country"     => $row['users_country'] ?: null,
            // المنطقة المسجّلة
            "users_region"      => $row['users_region'] ?: null,
            // هل الحساب مفعّل؟
            "users_is_active"   => (int) $row['users_is_active'],
            // هل تحقّق من رقمه؟
            "users_approve"     => (int) $row['users_approve'],
            // تاريخ إنشاء الحساب
            "users_created_at"  => $row['users_created_at'],
            // ⭐ هل كلمة مروره ما زالت مؤقتة من الإدارة؟
            "password_is_temp"  => (int) ($row['users_password_is_temp'] ?? 0) === 1,
            // ⭐ اسم الموظف الذي أنشأ الحساب (null = سجّل نفسه)
            "created_by_admin"  => $row['created_by_admin_name'],
            // ⭐ ترجمة مصدر الحساب
            "account_source_ar" => $row['users_created_by_admin']
                                   ? 'أنشأته الإدارة'
                                   : 'سجّل نفسه من التطبيق',
        ],

        // ===== ⭐ ملحقات الحساب (ما يملكه هذا المستخدم) =====
        "profiles" => [
            // ⭐ الشركة إن وُجدت
            "company" => $hasCompany ? [
                // معرّف الشركة (يُفتح به صفحة التعديل)
                "company_id"       => (int) $row['company_id'],
                // اسم النشاط
                "company_name"     => $row['company_name'],
                // نوع النشاط بالإنجليزية
                "business_type"    => $row['company_business_type'],
                // ⭐ ترجمة نوع النشاط
                "business_type_ar" => match($row['company_business_type']) {
                    'company'             => 'شركة',
                    'factory'             => 'مصنع',
                    'commercial_activity' => 'نشاط تجاري',
                    default               => 'غير محدد',
                },
            ] : null,

            // ⭐ الملف المهني إن وُجد
            "provider" => $hasProvider ? [
                // معرّف الملف المهني
                "providers_id"     => (int) $row['providers_id'],
                // حالة التوثيق رقماً
                "is_verified"      => (int) $row['providers_is_verified'],
                // ⭐ ترجمة حالة التوثيق
                "verification_ar"  => match((int)$row['providers_is_verified']) {
                    0       => 'في انتظار المراجعة',
                    1       => 'موثق',
                    2       => 'مرفوض',
                    default => 'غير محدد',
                },
            ] : null,

            // ملف العميل إن وُجد
            "client" => $hasClient ? [
                // معرّف ملف العميل
                "clients_id" => (int) $row['clients_id'],
            ] : null,
        ],
    ],
]);
?>