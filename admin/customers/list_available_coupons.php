<?php
// ============================================================
// ملف: admin/customers/list_available_coupons.php
// الغرض: قائمة الكوبونات الصالحة للاستخدام الآن في اللوحة
//        تُستخدم لملء الـ Dropdown في صفحة تأكيد الحجز
// الطريقة: POST
//
// ⭐⭐ معنى "صالحة الآن": لا تُصفّيها الإدارة يدوياً فقط،
//   بل يشترط الملف ثلاثة شروط معاً:
//     1. coupon_is_active = 1  (غير محذوف حذفاً ناعماً)
//     2. coupon_count > 0      (لم ينفد رصيده)
//     3. coupon_expiredate > NOW() أو NULL (لم تنتهِ صلاحيته)
//
// ⚠️ لا نُرجع كلمة مرور ولا بيانات حساسة — أسماء ونسب فقط.
//
// الصلاحية المطلوبة: coupons.view
// ============================================================

// تضمين ملف الاتصال (مستويان للوراء لأن الملف داخل admin/customers)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من توكن الإدارة والصلاحية
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية عرض الكوبونات
requirePermission($currentAdmin, 'coupons.view');

// ============================================================
// الخطوة 2: استقبال حدّ الإرجاع (اختياري)
// ============================================================
// عدد الكوبونات المطلوبة
$limit = (int) filterRequest("limit");

// القيمة الافتراضية 50 والحد الأقصى 100
if ($limit < 1)   $limit = 50;
if ($limit > 100) $limit = 100;

// ============================================================
// الخطوة 3: جلب الكوبونات الصالحة فقط
//
// ⭐ الترتيب: الأقرب انتهاءً أولاً ليدرك الموظف أن يستخدمها
//   ونتجاهل الكوبونات بلا تاريخ انتهاء في الترتيب الأخير.
// ============================================================
$stmt = $con->prepare(
    "SELECT
        coupon_id,
        coupon_name,
        coupon_count,
        coupon_discount,
        coupon_expiredate
     FROM coupon
     WHERE coupon_is_active = 1
       AND coupon_count > 0
       AND (coupon_expiredate IS NULL OR coupon_expiredate > NOW())
     ORDER BY (coupon_expiredate IS NULL) ASC, coupon_expiredate ASC
     LIMIT $limit"
);
// تنفيذ الاستعلام (لا معاملات لأن الحدّ رقمي محسوب في PHP)
$stmt->execute();
// جلب كل الكوبونات الصالحة
$rows = $stmt->fetchAll(PDO::FETCH_ASSOC);

// ============================================================
// الخطوة 4: تجهيز قائمة الـ Dropdown
// ============================================================
// مصفوفة النتائج
$coupons = [];

// المرور على كل كوبون وبناء عنصره
foreach ($rows as $row) {
    // نسبة الخصم كرقم
    $discount = (float) $row['coupon_discount'];

    // ⭐ نص جاهز للعرض في الـ Dropdown
    $display = $row['coupon_name']
        . ' — خصم ' . rtrim(rtrim(number_format($discount, 2, '.', ''), '0'), '.')
        . '% على العمولة';

    // ⭐ إضافة الكوبون للنتيجة
    $coupons[] = [
        // معرّف الكوبون
        "coupon_id"         => (int) $row['coupon_id'],
        // اسم الكوبون (يُرسل في check_booking_coupon)
        "coupon_name"       => $row['coupon_name'],
        // ⭐ نص جاهز للعرض بدل بناء الجملة في فلاتر
        "display_ar"        => $display,
        // نسبة الخصم
        "coupon_discount"   => $discount,
        // تاريخ الانتهاء (قد يكون null)
        "coupon_expiredate" => $row['coupon_expiredate'],
        // ⭐ الرصيد المتبقي
        "remaining_count"   => (int) $row['coupon_count'],
    ];
}

// ============================================================
// الخطوة 5: إرسال الرد النهائي
// ============================================================
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // ⭐ رسالة عربية جاهزة للعرض
    "message" => count($coupons) > 0
        ? "يوجد " . count($coupons) . " كوبون صالح للاستخدام"
        : "لا يوجد كوبونات صالحة للاستخدام حالياً",
    // ===== مصفوفة الكوبونات =====
    "data"    => $coupons,
    // ===== سجل التنفيذ =====
    "requested_by" => [
        // معرّف الموظف
        "admin_id"   => (int) $currentAdmin['admin_id'],
        // اسم الموظف
        "admin_name" => $currentAdmin['admin_full_name'] ?? null,
    ],
]);
// إيقاف التنفيذ
exit;
