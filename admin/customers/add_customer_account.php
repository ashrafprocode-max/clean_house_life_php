<?php
// ============================================================
// ملف: admin/customers/add_customer_account.php
// الغرض: إنشاء حساب عميل (client) من لوحة الإدارة
//        بلا أن يُسجّل العميل نفسه في التطبيق إطلاقاً
// الطريقة: POST (Form-Urlencoded — لا ملفات هنا)
//
// ⭐⭐ نفس أسلوب add_company_account.php لكن بدون إنشاء شركة
//   فالمندوب يقابل العميل شخصياً، يأخذ اسمه ورقمه،
//   ويُسلّمه كلمة مرور مؤقتة يدخل بها التطبيق لاحقاً إن أراد.
//
// ⚠️ خطوة واحدة فقط: INSERT في جدول users
//   ولا نُنشئ صفاً في client_profiles لأن بيانات الملف الشخصي
//   الاختيارية (البريد/الصورة/العنوان) يُكملها العميل بنفسه.
//
// الصلاحية المطلوبة: clients.create
// ============================================================

// تضمين ملف الاتصال (مستويان للوراء لأن الملف داخل admin/customers)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ clients.create يملكها: owner و manager و seller
//    ⚠️ ولا يملكها support افتراضياً — ولهذا نُرفق مع هذا الملف
//       ملف SQL يمنح support هذه الصلاحية حتى يستطيع خدمة
//       العملاء تسجيل عميل جديد من اللوحة
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إضافة عميل
requirePermission($currentAdmin, 'clients.create');

// معرّف الموظف المنفّذ مأخوذ من التوكن لا من الطلب
$adminId = (int) $currentAdmin['admin_id'];

// ============================================================
// الخطوة 2: استقبال بيانات العميل
// ============================================================
// الاسم الكامل للعميل - إجباري
$fullName = trim(filterRequest("users_full_name"));
// رقم هاتف العميل - إجباري (وهو نفسه اسم الدخول في التطبيق)
$phone    = filterRequest("users_phone");
// دولة العميل - اختياري
$country  = trim(filterRequest("users_country"));
// منطقة العميل - اختياري
// ⚠️ العمود NOT NULL بلا قيمة افتراضية فنرسل نصاً فارغاً لا NULL
$region   = trim(filterRequest("users_region"));
// ⭐ كلمة مرور يكتبها الموظف - اختياري (نُولّدها إن لم يُرسلها)
$password = trim(filterRequest("users_password"));

// ============================================================
// الخطوة 3: التحقق من الحقول الإجبارية
// ============================================================
// الاسم لا يقل عن حرفين
if (mb_strlen($fullName) < 2) {
    // رسالة توضح الحد الأدنى للاسم
    printFailure("اسم العميل يجب أن يكون حرفين على الأقل");
    // إيقاف التنفيذ
    exit;
}

// ⚠️ الاسم لا يزيد على 100 حرف لأن العمود varchar(100)
if (mb_strlen($fullName) > 100) {
    // رسالة توضح الحد الأقصى
    printFailure("اسم العميل يجب ألا يتجاوز 100 حرف");
    // إيقاف التنفيذ
    exit;
}

// رقم الهاتف إجباري
if ($phone === '') {
    // رسالة توضح الحقل المطلوب
    printFailure("رقم هاتف العميل مطلوب");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// ⭐ الخطوة 4: بدء المعاملة
//
// ⚠️⚠️ لماذا معاملة ونحن نُدخل جدولاً واحداً؟
//   لأن adminCreateUserAccount تُدخل صفاً في users
//   ثم صفاً في users_tokens — ولو فشل الثاني لبقى الحساب
//   يحجز رقم الهاتف للأبد بسبب قيد UNIQUE.
//
// ⭐ والجداول كلها InnoDB فالمعاملات تعمل ✅
// ============================================================
// بدء المعاملة
$con->beginTransaction();

// ⚠️ نحيط كل عمليات الكتابة بـ try/catch لضمان التراجع عند أي خطأ
try {

    // ============================================================
    // الخطوة 5: استدعاء الدالة المشتركة لإنشاء الحساب
    //
    // ⚠️ لا تُدير الدالة المعاملة — نحن نُديرها هنا
    // ⭐ نوع الحساب client وليس provider
    // ============================================================
    $accountResult = adminCreateUserAccount([
        // الاسم الكامل
        "full_name" => $fullName,
        // رقم الهاتف (تُوحّده الدالة داخلياً)
        "phone"     => $phone,
        // ⭐⭐ النوع client وليس provider
        "user_type" => "client",
        // الدولة الاختيارية
        "country"   => $country,
        // المنطقة الاختيارية
        "region"    => $region,
        // كلمة المرور إن كتبها الموظف
        "password"  => $password,
        // ⭐ معرّف الموظف المنشئ للمساءلة
        "admin_id"  => $adminId,
    ]);

    // ============================================================
    // ⚠️ إن كان الرقم مسجّلاً بالفعل نُرجع بياناته ونتراجع
    //
    // ⭐ الكود 409 يخبر الواجهة أن تنتقل للتاب الثاني (العميل
    //    المسجّل) بدلاً من إنشاء حساب مكرَّر.
    // ============================================================
    if ($accountResult['status'] === 'exists') {
        // إلغاء المعاملة قبل الخروج
        $con->rollBack();
        // ⭐ رد 409 يحمل معرّف الحساب الموجود
        printFailure(
            $accountResult['message']
            . " — ابحث عنه في تاب «عميل مسجّل» لإتمام الحجز",
            409,
            // بيانات الحساب الموجود
            $accountResult['data']
        );
        // إيقاف التنفيذ
        exit;
    }

    // ⚠️ إن فشل الإنشاء لأي سبب آخر نتراجع ونُرجع الرسالة
    if ($accountResult['status'] !== 'success') {
        // إلغاء المعاملة قبل الخروج
        $con->rollBack();
        // رسالة الفشل القادمة من الدالة
        printFailure($accountResult['message']);
        // إيقاف التنفيذ
        exit;
    }

    // ⭐ قراءة بيانات الحساب الجديد
    $userId       = (int) $accountResult['data']['users_id'];
    $userFullName = $accountResult['data']['users_full_name'];
    $userPhone    = $accountResult['data']['users_phone'];
    // ⭐⭐ كلمة المرور المؤقتة — تُعرض مرة واحدة فقط
    $tempPassword = $accountResult['data']['temp_password'];
    // توكن جلسة المستخدم (لا يُعرض للموظف)
    $userToken    = $accountResult['data']['token'];

    // ============================================================
    // الخطوة 6: تسجيل الإجراء في سجل الموظفين
    // ⚠️ لا نُسجّل كلمة المرور المؤقتة في السجل إطلاقاً
    // ============================================================
    logAdminActivity(
        // الموظف المنفّذ
        $currentAdmin,
        // نوع الإجراء
        'create_client_account',
        // نوع الكيان
        'users',
        // معرّف العميل الجديد
        $userId,
        // ⭐ تفاصيل مساعدة للمراجعة
        [
            // اسم العميل
            "users_full_name" => $userFullName,
            // رقم الهاتف
            "users_phone"     => $userPhone,
            // ⭐ هل كُتبت كلمة المرور يدوياً أم وُلِّدت؟
            "password_manual" => $password !== '',
        ]
    );

    // ============================================================
    // الخطوة 7: إنهاء المعاملة بنجاح
    // ============================================================
    // تثبيت كل الكتابات في قاعدة البيانات
    $con->commit();

    // ============================================================
    // الخطوة 8: إرسال الرد النهائي
    // ============================================================
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // ⭐ رسالة عربية جاهزة للعرض
        "message" => "تم إنشاء حساب العميل بنجاح",
        // بيانات النتيجة
        "data"    => [

            // ===== ⭐ بيانات الحساب =====
            "account" => [
                // مفتاح الوضع للمنطق في فلاتر
                "mode"            => "created",
                // ترجمة الوضع للعرض
                "mode_ar"         => "حساب جديد",
                // معرّف المستخدم
                "users_id"        => $userId,
                // الاسم الكامل
                "users_full_name" => $userFullName,
                // ⭐ الرقم بعد التوحيد (قد يختلف عمّا كتبه الموظف)
                "users_phone"     => $userPhone,
                // نوع الحساب دائماً client
                "users_type"      => "client",
            ],

            // ===== ⭐⭐ بيانات الدخول المؤقتة =====
            // ⚠️⚠️ كلمة المرور تُعرض في هذا الرد وحده ولا تُرجَع لاحقاً
            "credentials" => [
                // رقم الهاتف = اسم المستخدم في التطبيق
                "login_phone"    => $userPhone,
                // ⭐⭐ كلمة المرور المؤقتة
                "temp_password"  => $tempPassword,
                // ⭐ تعليمات جاهزة يقرأها الموظف على العميل
                "instructions_ar" =>
                    "سلّم العميل هذه البيانات إن أراد الدخول للتطبيق:\n"
                    . "• رقم الدخول: " . $userPhone . "\n"
                    . "• كلمة المرور المؤقتة: " . $tempPassword . "\n"
                    . "⚠️ يجب تغييرها من التطبيق عند أول دخول",
                // ⚠️ تنبيه أن الكلمة لن تظهر مرة أخرى
                "warning_ar"     =>
                    "⚠️ كلمة المرور تظهر هذه المرة فقط — "
                    . "لن تستطيع استرجاعها لاحقاً",
                // ⭐ توكن الجلسة (للتكامل فقط ولا يُعرض للموظف)
                "token"          => $userToken,
            ],

            // ===== ⭐ الخطوة التالية للتوجيه في اللوحة =====
            "next_step"    => "add_service_request",
            // ⭐ ترجمة الخطوة التالية
            "next_step_ar" => "أضف تفاصيل طلب الخدمة",

            // ===== سجل التنفيذ =====
            "created_by" => [
                // معرّف الموظف المنفّذ
                "admin_id"   => $adminId,
                // اسم الموظف المنفّذ
                "admin_name" => $currentAdmin['admin_full_name'] ?? null,
                // ⭐ دور الموظف مترجماً
                "role_ar"    => $currentAdmin['role_name_ar'] ?? null,
            ],
        ],
    ]);

// ============================================================
// ⭐⭐ الخطوة 9: معالجة أي خطأ والتراجع الكامل
// ============================================================
} catch (Exception $e) {

    // ⚠️ التراجع عن المعاملة إن كانت ما زالت مفتوحة
    // ⭐ نفحص أولاً لأن rollBack على معاملة مغلقة يرمي استثناء آخر
    if ($con->inTransaction()) {
        // إلغاء كل ما كُتب في قاعدة البيانات
        $con->rollBack();
    }

    // ⭐ تسجيل الخطأ في سجل PHP للتشخيص
    error_log("add_customer_account failed: " . $e->getMessage());

    // ⚠️ إرجاع رسالة الخطأ للموظف
    printFailure(
        "تعذّر إتمام العملية: " . $e->getMessage(),
        500
    );
    // إيقاف التنفيذ
    exit;
}
