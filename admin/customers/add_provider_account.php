    // ============================================================
    // ⭐⭐ الخطوة 17: إدخال الملف المهني
    // ============================================================
    // بناء مصفوفة البيانات بأسماء أعمدة الجدول حرفياً
    $profileData = [
        // ⭐ معرّف المستخدم (الجديد أو المربوط)
        "providers_users_id"              => $userId,
