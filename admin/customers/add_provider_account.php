        // المحافظة الحالية
        "providers_current_governorate"   => $governorate,
        // المنطقة الحالية
        "providers_current_area"          => $area,
        // اسم ملف الصورة الشخصية
        "providers_profile_image"         => $profileImageName,
        // اسم ملف البطاقة الأمامية
        "providers_id_card_front"         => $idFrontName,
        // اسم ملف البطاقة الخلفية
        "providers_id_card_back"          => $idBackName,
        // ⭐ الصحيفة الجنائية (null إن لم تُرفع)
        "providers_criminal_record_image" => $criminalName,
        // ⭐ إيصال المرافق (null إن لم يُرفع)
        // ⚠️ لاحظ اسم العمود الصحيح — وهو موضع الباگ في edit.php:132
        "providers_utility_receipt_image" => $utilityName,
        // ⭐⭐ 0 = في انتظار المراجعة دائماً
        // ⚠️ لا نضع 1 إطلاقاً حتى لو نفّذها المالك
        //    لأن التوثيق قرار مراجعة لا إدخال بيانات
        "providers_is_verified"           => 0,
        // التقييم الابتدائي صفر
        "providers_rating"                => 0.00,
        // ⭐ ملاحظة توضح أن الملف مُدخَل من الإدارة
        "providers_review_note"           => $reviewNote,
    ];

    // ⚠️ نمرر false لمنع الدالة من طباعة JSON لأننا نبني رداً مخصصاً
    $profileResult = insertData("professional_profiles", $profileData, false);

    // إذا فشل الإدخال نرمي استثناء ليتراجع catch عن كل شيء
    if ($profileResult <= 0) {
        // رمي استثناء يوضح فشل الحفظ
        throw new Exception("فشل حفظ الملف المهني في قاعدة البيانات");
    }

    // ⭐ قراءة معرّف الملف المهني الجديد
    $newProviderId = (int) $con->lastInsertId();

    // ============================================================
    // ⭐⭐ الخطوة 18: الالتزام بالمعاملة
    //
    // ⭐ كل شيء نجح، فنُثبّت التغييرات نهائياً
    //   وقبل هذا السطر لم يُكتب أي شيء في القاعدة بشكل نهائي
    // ============================================================
    // تثبيت كل التغييرات
    $con->commit();

    // ============================================================
    // ⭐ الخطوة 19: تسجيل الإجراء في سجل النشاط
    //
    // ⚠️ بعد commit لا قبله — فشل السجل لا يجوز أن يُفشل الإنشاء
    // ============================================================
    // تسجيل إجراء إنشاء الملف المهني
    logAdminActivity(
        // بيانات الموظف المنفّذ
        $currentAdmin,
        // ⭐ نوع الإجراء يوضح الوضع (إنشاء أم ربط)
        $isLinkMode ? 'link_provider_profile' : 'create_provider_account',
        // نوع الكيان
        'provider',
        // معرّف الملف المهني الجديد
        $newProviderId,
        // ⭐ التفاصيل التي نحتاجها في المراجعة لاحقاً
        [
            // معرّف المستخدم المرتبط
            "users_id"       => $userId,
            // اسم مقدم الخدمة
            "provider_name"  => $userFullName,
            // هاتفه
            "provider_phone" => $userPhone,
            // سنوات الخبرة
            "experience"     => $experience,
            // العمر
            "age"            => $age,
            // ⭐ هل رُفعت الصحيفة الجنائية؟
            "has_criminal"   => $criminalName !== null,
            // ⭐ هل رُفع إيصال المرافق؟
            "has_utility"    => $utilityName !== null,
            // ⭐ هل أُنشئ حساب جديد أم رُبط بموجود؟
            "account_mode"   => $accountMode,
            // ⚠️ لا نُسجّل كلمة المرور المؤقتة في السجل إطلاقاً
        ]
    );

    // ============================================================
    // ⭐ الخطوة 20: إرسال الرد النهائي
    //
    // ⚠️⚠️ لا نُرجع أسماء ملفات الصور ولا روابطها المباشرة إطلاقاً
    //   لأن البطاقة الشخصية مستند حساس جداً
    //   وعرضها يمرّ عبر admin/providers/secure_image.php وحده
    // ============================================================
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // ⭐ رسالة عربية تتغير حسب الوضع
        "message" => $isLinkMode
            ? "تم إنشاء الملف المهني وربطه بحساب " . $userFullName
            : "تم إنشاء حساب مقدم الخدمة وملفه المهني بنجاح",
        // بيانات النتيجة
        "data"    => [

            // ===== ⭐ بيانات الحساب =====
            "account" => [
                // ⭐ مفتاح الوضع للمنطق في فلاتر
                "mode"            => $accountMode,
                // ⭐ ترجمة الوضع للعرض
                "mode_ar"         => $isLinkMode
                                     ? 'رُبط بحساب موجود' : 'حساب جديد',
                // معرّف المستخدم
                "users_id"        => $userId,
                // الاسم الكامل
                "users_full_name" => $userFullName,
                // ⭐ الرقم بعد التوحيد (قد يختلف عمّا كتبه الموظف)
                "users_phone"     => $userPhone,
                // ⭐ النوع provider
                "users_type"      => "provider",
            ],

            // ===== ⭐⭐ بيانات الدخول (في وضع الإنشاء فقط) =====
            // ⚠️⚠️ كلمة المرور المؤقتة تُعرض في هذا الرد وحده
            //    فالمندوب يجب أن يُسلّمها الآن أو يُصوّر الشاشة
            "credentials" => $isLinkMode ? null : [
                // رقم الهاتف = اسم المستخدم في التطبيق
                "login_phone"     => $userPhone,
                // ⭐⭐ كلمة المرور المؤقتة (بها كابيتال ورمز)
                "temp_password"   => $tempPassword,
                // ⭐ تعليمات جاهزة يقرأها المندوب على مقدم الخدمة
                "instructions_ar" =>
                    "سلّم مقدم الخدمة هذه البيانات:\n"
                    . "• رقم الدخول: " . $userPhone . "\n"
                    . "• كلمة المرور المؤقتة: " . $tempPassword . "\n"
                    . "⚠️ يجب تغييرها من التطبيق عند أول دخول",
                // ⚠️ تنبيه أن الكلمة لن تظهر مرة أخرى
                "warning_ar"      =>
                    "⚠️ كلمة المرور تظهر هذه المرة فقط — "
                    . "لن تستطيع استرجاعها لاحقاً",
                // ⭐ توكن الجلسة (للتكامل لا للعرض)
                "token"           => $userToken,
            ],

            // ===== ⭐ بيانات الملف المهني =====
            "profile" => [
                // ⭐ معرّف الملف المهني
                "providers_id"    => $newProviderId,
                // معرّف المستخدم صاحب الملف
                "users_id"        => $userId,
                // سنوات الخبرة
                "experience"      => $experience,
                // العمر
                "age"             => $age,
                // النوع
                "gender"          => $gender,
                // الجنسية
                "nationality"     => $nationality,
                // ⭐ الموقع مجمّعاً جاهزاً للعرض
                "location_ar"     => $country . ' · ' . $governorate
                                     . ' · ' . $area,
                // العنوان التفصيلي
                "address"         => $address,
            ],

            // ===== ⭐ حالة المستندات =====
            "documents" => [
                // ⭐ الصور الثلاث الإجبارية مرفوعة دائماً
                "profile_image"     => true,
                // صورة البطاقة الأمامية
                "id_card_front"     => true,
