                "missing_ar"        => ($criminalName === null || $utilityName === null)
                    ? 'ينقص: '
                      . ($criminalName === null ? 'الصحيفة الجنائية' : '')
                      . ($criminalName === null && $utilityName === null ? ' و ' : '')
                      . ($utilityName === null ? 'إيصال المرافق' : '')
                      . ' (اختياريان — يمكن رفعهما لاحقاً)'
                    : null,
            ],

            // ===== ⭐⭐ حالة التوثيق =====
            "verification" => [
                // ⭐ صفر دائماً = في انتظار المراجعة
                "is_verified"      => 0,
                // ⭐ ترجمة الحالة
                "verification_ar"  => "في انتظار المراجعة",
                // ⭐ لون الشارة المقترح للواجهة
                "status_color"     => "warning",
                // ⭐ ملاحظة توضح أن الملف مُدخَل من الإدارة
                "review_note"      => $reviewNote,
                // ⭐⭐ تنبيه صريح للموظف بالخطوة الناقصة
                "notice_ar"        =>
                    "⚠️ الملف في انتظار المراجعة — "
                    . "اذهب لقسم مراجعة المزودين لتوثيقه، "
                    . "ولن تظهر خدماته للعملاء قبل التوثيق",
            ],

            // ===== ⭐ الخطوة التالية للتوجيه في اللوحة =====
            "next_step"    => "add_provider_services",
