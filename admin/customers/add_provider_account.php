<?php
// ============================================================
// ملف: admin/customers/add_provider_account.php
// الغرض: إنشاء حساب مقدم خدمة كامل من لوحة الإدارة
//        (users + professional_profiles) بلا أن يدخل التطبيق
// الطريقة: POST (multipart/form-data لأن فيه صور)
//
// ⭐⭐ يعمل بوضعين مثل add_company_account.php:
//   الوضع 1 (create): users_full_name + users_phone → حساب جديد
//   الوضع 2 (link)  : link_users_id → ملف مهني لحساب موجود
//
// ⭐ الصور الثلاث الإجبارية (المندوب يصوّرها بموبايله):
//   profile_image · id_card_front · id_card_back
//
// ⭐ والاختياريتان:
//   criminal_record_image · utility_receipt_image
//
// ⚠️⚠️ providers_is_verified = 0 دائماً
//   حتى لو نفّذها المالك — التوثيق قرار مراجعة لا إدخال
//   والطلب يظهر في شاشة مراجعة المزودين كأي طلب من التطبيق
//
// الصلاحية المطلوبة: providers.create
// ============================================================

// تضمين ملف الاتصال (مستويان للوراء لأن الملف داخل admin/customers)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من التوكن والصلاحية
//
// ⭐ providers.create يملكها: owner و manager و seller
//    ولا يملكها: support و accountant
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// ⭐ فرض صلاحية إضافة مقدم خدمة
requirePermission($currentAdmin, 'providers.create');

// معرّف الموظف المنفّذ مأخوذ من التوكن لا من الطلب
$adminId = (int) $currentAdmin['admin_id'];

// ============================================================
// الخطوة 2: استقبال بيانات الحساب
// ============================================================
// ⭐ معرّف حساب موجود للربط (فارغ = إنشاء حساب جديد)
$linkUserId    = filterRequest("link_users_id");
// الاسم الكامل لمقدم الخدمة - إجباري في وضع الإنشاء
$fullName      = trim(filterRequest("users_full_name"));
// رقم هاتفه - إجباري في وضع الإنشاء
$phone         = filterRequest("users_phone");
// كلمة مرور يكتبها الموظف - اختياري (نُولّدها إن لم يُرسلها)
$userPassword  = trim(filterRequest("users_password"));

// ============================================================
// الخطوة 3: استقبال بيانات الملف المهني
// ============================================================
// سنوات الخبرة - إجباري
$experience    = filterRequest("providers_experience");
// نبذة تعريفية - اختياري
$bio           = trim(filterRequest("providers_bio"));
// العمر - إجباري
$age           = filterRequest("providers_age");
// النوع (ذكر / أنثى) - إجباري
$gender        = trim(filterRequest("providers_gender"));
// الجنسية - إجباري
$nationality   = trim(filterRequest("providers_nationality"));
// الدولة الحالية - إجباري
$country       = trim(filterRequest("providers_current_country"));
// المحافظة الحالية - إجباري
$governorate   = trim(filterRequest("providers_current_governorate"));
// المنطقة الحالية - إجباري
$area          = trim(filterRequest("providers_current_area"));
// العنوان التفصيلي - إجباري
$address       = trim(filterRequest("providers_current_address"));

// ============================================================
// ⭐ الخطوة 4: تحديد وضع التشغيل
// ============================================================
// ⭐ الوضع = ربط إن أُرسل معرّف حساب موجود
$isLinkMode = ($linkUserId !== '' && (int)$linkUserId > 0);
// تحويل معرّف الربط لرقم صحيح
$linkUserId = (int) $linkUserId;

// ============================================================
// الخطوة 5: التحقق من الحقول النصية الإجبارية للملف المهني
// ============================================================
// إذا نقص أي حقل إجباري نوقف التنفيذ فوراً
if ($experience === '' || $age === '' || $gender === '' ||
    $nationality === '' || $country === '' || $governorate === '' ||
    $area === '' || $address === '') {
    // رسالة عربية توضح الحقول المطلوبة
    printFailure(
        "يرجى إدخال كل بيانات مقدم الخدمة الإجبارية: "
        . "الخبرة، العمر، النوع، الجنسية، الدولة، المحافظة، المنطقة، العنوان"
    );
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// ⭐ الخطوة 6: التحقق من الأرقام والقيم
// ============================================================
// تحويل سنوات الخبرة لرقم صحيح
$experience = (int) $experience;

// ⚠️ الخبرة بين 0 و 60 سنة (0 مسموح للمبتدئ)
if ($experience < 0 || $experience > 60) {
    // رسالة توضح النطاق المسموح
    printFailure("سنوات الخبرة يجب أن تكون بين 0 و 60");
    // إيقاف التنفيذ
    exit;
}

// تحويل العمر لرقم صحيح
$age = (int) $age;

// ⚠️ العمر بين 18 و 70 — لا نقبل عمالة أقل من 18 إطلاقاً
if ($age < 18 || $age > 70) {
    // رسالة توضح النطاق المسموح وسببه
    printFailure(
        "العمر يجب أن يكون بين 18 و 70 سنة — "
        . "لا يُقبل تشغيل من هم أقل من 18 عاماً"
    );
    // إيقاف التنفيذ
    exit;
}

// ⭐ قائمة قيم النوع المسموحة
// ⚠️ العمود varchar لا ENUM، لكن نُوحّد القيم حتى تعمل فلاتر البحث
$allowedGenders = ['ذكر', 'أنثى', 'male', 'female'];

// إذا كان النوع غير معروف نرفض الطلب
if (!in_array($gender, $allowedGenders, true)) {
    // رسالة توضح القيم المسموحة
    printFailure("النوع يجب أن يكون: ذكر أو أنثى");
    // إيقاف التنفيذ
    exit;
}

// ⚠️ العنوان لا يقل عن 5 أحرف ليكون مفيداً فعلاً
if (mb_strlen($address) < 5) {
    // رسالة توضح الحد الأدنى
    printFailure("العنوان التفصيلي يجب أن يكون 5 أحرف على الأقل");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// ⭐⭐ الخطوة 7: التحقق من وجود الصور الثلاث الإجبارية
//
// ⚠️ نفحصها قبل بدء المعاملة وقبل أي رفع
//   لأن رفع صورتين ثم كشف نقص الثالثة يعني حذفهما مرة أخرى
//   والمندوب على اتصال موبايل ضعيف يخسر ميجابايتات بلا داعٍ
// ============================================================
// ⭐ قائمة الحقول الإجبارية للصور
$requiredImages = [
    // الصورة الشخصية
    'profile_image'  => 'الصورة الشخصية',
    // صورة البطاقة الأمامية
    'id_card_front'  => 'صورة البطاقة (الوجه الأمامي)',
    // صورة البطاقة الخلفية
    'id_card_back'   => 'صورة البطاقة (الوجه الخلفي)',
];

// نمرّ على كل صورة إجبارية للتحقق من وجودها
foreach ($requiredImages as $field => $labelAr) {
    // ⚠️ نتحقق أن الملف أُرسل فعلاً وليس حقلاً فارغاً
    if (!isset($_FILES[$field]) ||
        $_FILES[$field]['error'] === UPLOAD_ERR_NO_FILE) {
        // رسالة توضح الصورة الناقصة بالاسم العربي
        printFailure("مطلوب رفع: " . $labelAr);
        // إيقاف التنفيذ
        exit;
    }
}

// ============================================================
// ⭐⭐ الخطوة 8: بدء المعاملة
//
// ⚠️⚠️ إلزامية لأننا نكتب في جدولين
//   نجاح users وفشل professional_profiles يعني حساب مزوّد
//   بلا ملف مهني، يحجز رقم الهاتف نهائياً بقيد UNIQUE
//   فلا يستطيع المندوب إعادة المحاولة إطلاقاً
//
// ⚠️ الجداول InnoDB فالمعاملات تعمل ✅
// ============================================================
// بدء المعاملة
$con->beginTransaction();

// ⭐ متغيّرات أسماء الملفات نحتاجها في catch لحذفها عند الفشل
$profileImageName = null;
$idFrontName      = null;
$idBackName       = null;
$criminalName     = null;
$utilityName      = null;

// ⚠️ نحيط كل عمليات الكتابة بـ try/catch لضمان التراجع عند أي خطأ
try {

    // ============================================================
    // ⭐ الخطوة 9: تجهيز حساب المستخدم (إنشاء أو ربط)
    // ============================================================
    // متغيّرات نتيجة الحساب
    $userId       = 0;
    $userFullName = '';
    $userPhone    = '';
    $tempPassword = null;
    $userToken    = null;
    // ⭐ يوضح للواجهة أي وضع نُفِّذ فعلاً
    $accountMode  = '';

    // ============================================================
    // ⭐ الوضع الأول: ربط الملف المهني بحساب موجود
    // ============================================================
    if ($isLinkMode) {
        // مفتاح الوضع للمنطق في فلاتر
        $accountMode = 'linked';

        // جلب الحساب الموجود للتحقق من صلاحيته
        $stmtUser = $con->prepare(
            "SELECT users_id, users_full_name, users_phone,
                    users_type, users_is_active
             FROM users WHERE users_id = ? LIMIT 1"
        );
        // تنفيذ الاستعلام بمعرّف الحساب المُرسل
        $stmtUser->execute([$linkUserId]);
        // جلب صف الحساب
        $user = $stmtUser->fetch(PDO::FETCH_ASSOC);

        // إذا لم يوجد الحساب نرفض الطلب
        if (!$user) {
            // إلغاء المعاملة قبل الخروج
            $con->rollBack();
            // رسالة توضح أن الحساب غير موجود
            printFailure("الحساب المطلوب ربطه غير موجود", 404);
            // إيقاف التنفيذ
            exit;
        }

        // ⚠️ لا نربط ملفاً مهنياً بحساب معطّل
        if ((int)$user['users_is_active'] !== 1) {
            // إلغاء المعاملة قبل الخروج
            $con->rollBack();
            // رسالة توضح أن الحساب معطّل
            printFailure(
                "هذا الحساب معطّل — فعّله أولاً قبل ربط ملف مهني به",
                403
            );
            // إيقاف التنفيذ
            exit;
        }

        // ============================================================
        // ⭐⭐ التحقق أن نوع الحساب provider
        //
        // ⚠️ complete_provider_profile/add.php يفرض هذا الشرط (السطر 54)
        //   فلو ربطنا ملفاً مهنياً بحساب client لتعطّل تعديله من التطبيق
        // ============================================================
        // نتحقق من نوع الحساب
        if ($user['users_type'] !== 'provider') {
            // إلغاء المعاملة قبل الخروج
            $con->rollBack();
            // ⭐ رسالة توضح الحل بدقة
            printFailure(
                "هذا الحساب نوعه (" . $user['users_type'] . ") "
                . "ولا يمكن ربط ملف مهني به — "
                . "يجب أن يكون نوعه provider",
                409,
                [
                    // معرّف الحساب
                    "users_id"   => (int) $user['users_id'],
                    // نوع الحساب الحالي
                    "users_type" => $user['users_type'],
                ]
            );
            // إيقاف التنفيذ
            exit;
        }

        // قراءة بيانات الحساب الموجود
        $userId       = (int) $user['users_id'];
        $userFullName = $user['users_full_name'];
        $userPhone    = $user['users_phone'];

    // ============================================================
    // ⭐⭐ الوضع الثاني: إنشاء حساب جديد بالكامل
    // ============================================================
    } else {
        // مفتاح الوضع للمنطق في فلاتر
        $accountMode = 'created';

        // ⚠️ التحقق من الحقلين الإجباريين لوضع الإنشاء
        if ($fullName === '' || $phone === '') {
            // إلغاء المعاملة قبل الخروج
            $con->rollBack();
            // رسالة توضح الحقول المطلوبة والبديل
            printFailure(
                "يرجى إدخال اسم مقدم الخدمة ورقم هاتفه، "
                . "أو أرسل link_users_id لربط الملف بحساب موجود"
            );
            // إيقاف التنفيذ
            exit;
        }

        // ⭐⭐ استدعاء الدالة المشتركة لإنشاء الحساب
        // ⚠️ لا تُدير الدالة المعاملة — نحن نُديرها هنا
        $accountResult = adminCreateUserAccount([
            // الاسم الكامل
            "full_name" => $fullName,
            // رقم الهاتف (تُوحّده الدالة داخلياً)
            "phone"     => $phone,
            // ⭐⭐ النوع provider وليس client
            "user_type" => "provider",
            // ⭐ نستخدم دولة ومنطقة الملف المهني نفسها للحساب
            "country"   => $country,
            // المنطقة
            "region"    => $area,
            // كلمة المرور إن كتبها الموظف
            "password"  => $userPassword,
            // ⭐ معرّف الموظف المنشئ للمساءلة
            "admin_id"  => $adminId,
        ]);

        // ⚠️ إن كان الرقم مسجّلاً بالفعل نُرجع بياناته ونتراجع
        if ($accountResult['status'] === 'exists') {
            // إلغاء المعاملة قبل الخروج
            $con->rollBack();
            // ⭐ رد 409 يحمل معرّف الحساب الموجود ليربط به المندوب
            printFailure(
                $accountResult['message']
                . " — أرسل link_users_id لربط الملف المهني بحسابه",
                409,
                // بيانات الحساب الموجود
                $accountResult['data']
            );
            // إيقاف التنفيذ
            exit;
        }

        // ⚠️ إن فشل الإنشاء لأي سبب آخر نتراجع ونُرجع الرسالة
        if ($accountResult['status'] !== 'success') {
            // إلغاء المعاملة قبل الخروج
            $con->rollBack();
            // رسالة الفشل القادمة من الدالة
            printFailure($accountResult['message']);
            // إيقاف التنفيذ
            exit;
        }

        // ⭐ قراءة بيانات الحساب الجديد
        $userId       = (int) $accountResult['data']['users_id'];
        $userFullName = $accountResult['data']['users_full_name'];
        $userPhone    = $accountResult['data']['users_phone'];
        // ⭐⭐ كلمة المرور المؤقتة — تُعرض مرة واحدة فقط
        $tempPassword = $accountResult['data']['temp_password'];
        // توكن جلسة المستخدم
        $userToken    = $accountResult['data']['token'];
    }

    // ============================================================
    // ⭐ الخطوة 10: التحقق من عدم وجود ملف مهني سابق
    //
    // ⚠️ إلزامي في الوضعين معاً
    //   لأن providers_users_id بلا قيد UNIQUE
    //   فبدون هذا الفحص يُنشئ كل ضغط ملفاً مكرَّراً لنفس الشخص
    // ============================================================
    // تجهيز استعلام البحث عن ملف مهني سابق
    $stmtExisting = $con->prepare(
        "SELECT providers_id, providers_is_verified
         FROM professional_profiles
         WHERE providers_users_id = ? LIMIT 1"
    );
    // تنفيذ الاستعلام بمعرّف المستخدم
    $stmtExisting->execute([$userId]);
    // جلب الصف إن وُجد
    $existingProfile = $stmtExisting->fetch(PDO::FETCH_ASSOC);

    // إذا وُجد ملف مهني نتراجع ونُرجع معرّفه
    if ($existingProfile) {
        // إلغاء المعاملة قبل الخروج
        $con->rollBack();
        // ⭐ رد 409 يحمل معرّف الملف الموجود
        printFailure(
            "هذا الحساب لديه ملف مهني بالفعل — "
            . "افتح صفحة المراجعة لتعديله",
            409,
            [
                // معرّف الملف المهني الموجود
                "providers_id"  => (int) $existingProfile['providers_id'],
                // معرّف المستخدم
                "users_id"      => $userId,
                // ⭐ حالة التوثيق الحالية
                "is_verified"   => (int) $existingProfile['providers_is_verified'],
                // ⭐ ترجمة حالة التوثيق
                "verification_ar" => match((int)$existingProfile['providers_is_verified']) {
                    0       => 'في انتظار المراجعة',
                    1       => 'موثق',
                    2       => 'مرفوض',
                    default => 'غير محدد',
                },
            ]
        );
        // إيقاف التنفيذ
        exit;
    }

    // ============================================================
    // ⭐ الخطوة 11: رفع الصورة الشخصية (إجباري)
    //
    // ⚠️ الصور ترتفع للقرص لا لقاعدة البيانات
    //    فالمعاملة لا تتراجع عنها — لذلك نحذفها يدوياً في catch
    // ============================================================
    // رفع الصورة الشخصية بدالتك الموحدة
    $profileImageName = imageUploadtwo(
        __DIR__ . "/../../upload/provider_profiles/",
        "profile_image"
    );

    // نتحقق من نجاح الرفع
    if (in_array($profileImageName,
                 ["fail", "empty", "extension_error", "size_error"], true)) {
        // ⚠️ نُفرّغ المتغيّر لأن الملف لم يُرفع فعلاً
        $profileImageName = null;
        // رمي استثناء ليعالجه catch ويتراجع عن المعاملة
        throw new Exception(
            "فشل رفع الصورة الشخصية، تأكد أن حجمها أقل من 10 ميجا"
        );
    }

    // ============================================================
    // الخطوة 12: رفع صورة البطاقة الأمامية (إجباري)
    // ============================================================
    // رفع صورة الوجه الأمامي للبطاقة
    $idFrontName = imageUploadtwo(
        __DIR__ . "/../../upload/id_cards/",
        "id_card_front"
    );

    // نتحقق من نجاح الرفع
    if (in_array($idFrontName,
                 ["fail", "empty", "extension_error", "size_error"], true)) {
        // نُفرّغ المتغيّر لأن الملف لم يُرفع فعلاً
        $idFrontName = null;
        // رمي استثناء (وcatch يحذف الصورة الشخصية)
        throw new Exception(
            "فشل رفع صورة البطاقة الأمامية، تأكد أن حجمها أقل من 10 ميجا"
        );
    }

    // ============================================================
    // الخطوة 13: رفع صورة البطاقة الخلفية (إجباري)
    // ============================================================
    // رفع صورة الوجه الخلفي للبطاقة
    $idBackName = imageUploadtwo(
        __DIR__ . "/../../upload/id_cards/",
        "id_card_back"
    );

    // نتحقق من نجاح الرفع
    if (in_array($idBackName,
                 ["fail", "empty", "extension_error", "size_error"], true)) {
        // نُفرّغ المتغيّر لأن الملف لم يُرفع فعلاً
        $idBackName = null;
        // رمي استثناء (وcatch يحذف الصورتين السابقتين)
        throw new Exception(
            "فشل رفع صورة البطاقة الخلفية، تأكد أن حجمها أقل من 10 ميجا"
        );
    }

    // ============================================================
    // ⭐ الخطوة 14: رفع الصحيفة الجنائية (اختياري)
    //
    // ⚠️ فشل رفعها لا يُوقف العملية إطلاقاً — نتجاهلها فقط
    //   لأنها اختيارية بقرارك، والمندوب في الشارع قد لا يملكها
    // ============================================================
    // نتحقق أن الملف أُرسل فعلاً
    if (isset($_FILES['criminal_record_image']) &&
        $_FILES['criminal_record_image']['error'] !== UPLOAD_ERR_NO_FILE) {

        // رفع الصحيفة الجنائية
        $criminalName = imageUploadtwo(
            __DIR__ . "/../../upload/criminal_records/",
            "criminal_record_image"
        );

        // ⚠️ عند الفشل نتجاهلها ولا نُوقف العملية
        if (in_array($criminalName,
                     ["fail", "empty", "extension_error", "size_error"], true)) {
            // نُفرّغ المتغيّر فتُحفظ NULL في العمود
            $criminalName = null;
        }
    }

    // ============================================================
    // ⭐ الخطوة 15: رفع إيصال المرافق (اختياري)
    // ============================================================
    // نتحقق أن الملف أُرسل فعلاً
    if (isset($_FILES['utility_receipt_image']) &&
        $_FILES['utility_receipt_image']['error'] !== UPLOAD_ERR_NO_FILE) {

        // رفع إيصال المرافق
        $utilityName = imageUploadtwo(
            __DIR__ . "/../../upload/utility_receipt/",
            "utility_receipt_image"
        );

