    // حذف الصورة الشخصية إن كانت قد رُفعت
    if ($profileImageName) {
        // حذف الملف من مجلده
        deleteFile(__DIR__ . "/../../upload/provider_profiles/", $profileImageName);
    }

    // حذف صورة البطاقة الأمامية إن كانت قد رُفعت
    if ($idFrontName) {
        // حذف الملف من مجلده
        deleteFile(__DIR__ . "/../../upload/id_cards/", $idFrontName);
    }

    // حذف صورة البطاقة الخلفية إن كانت قد رُفعت
    if ($idBackName) {
        // حذف الملف من مجلده
        deleteFile(__DIR__ . "/../../upload/id_cards/", $idBackName);
    }

    // حذف الصحيفة الجنائية إن كانت قد رُفعت
    if ($criminalName) {
        // حذف الملف من مجلده
        deleteFile(__DIR__ . "/../../upload/criminal_records/", $criminalName);
    }

    // حذف إيصال المرافق إن كان قد رُفع
    if ($utilityName) {
        // حذف الملف من مجلده
        deleteFile(__DIR__ . "/../../upload/utility_receipt/", $utilityName);
    }

    // ⭐ تسجيل الخطأ في سجل PHP للتشخيص
    error_log("add_provider_account failed: " . $e->getMessage());

    // ⚠️ إرجاع رسالة الخطأ للموظف
    printFailure("تعذّر إتمام العملية: " . $e->getMessage(), 500);
    // إيقاف التنفيذ
    exit;
}
