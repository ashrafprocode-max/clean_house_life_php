<?php
// ============================================================
// ملف: admin/customers/check_client_phone.php
// الغرض: البحث عن عميل مسجّل برقم هاتفه لعرض بطاقته
//        في التاب الثاني (العميل المسجّل) قبل إتمام الحجز
// الطريقة: POST
//
// ⭐⭐ الفرق عن check_phone.php:
//   check_phone.php يسأل "هل أستطيع إنشاء حساب/شركة بهذا الرقم؟"
//   وهذا الملف يسأل "أرني بطاقة العميل المسجّل بهذا الرقم"
//   فيُرجع صورة العميل وبياناته الكاملة لعرضها كبطاقة قابلة للضغط.
//
// الحقل الإجباري: phone
// الصلاحية المطلوبة: clients.view
// ============================================================

// تضمين ملف الاتصال (مستويان للوراء لأن الملف داخل admin/customers)
include "../../connect.php";

// ============================================================
// الخطوة 1: التحقق من توكن الإدارة والصلاحية
//
// ⭐ نطلب صلاحية العرض فقط لأن الفحص قراءة لا كتابة
//    وsupport يملكها فهي متاحة لأدوار القسم كلها
// ============================================================
// التحقق من التوكن وجلب بيانات الموظف مع صلاحياته
$currentAdmin = checkAdminToken();

// فرض صلاحية عرض العملاء
requirePermission($currentAdmin, 'clients.view');

// ============================================================
// الخطوة 2: استقبال رقم الهاتف وتوحيد صيغته
// ============================================================
// رقم الهاتف كما كتبه الموظف - إجباري
$rawPhone = filterRequest("phone");

// إذا لم يُرسل الرقم نوقف التنفيذ فوراً
if ($rawPhone === '') {
    // رسالة توضح الحقل المطلوب
    printFailure("الحقل phone مطلوب");
    // إيقاف التنفيذ
    exit;
}

// ⭐ توحيد صيغة الرقم قبل البحث
// ⚠️ إلزامي وإلا لم نجد 01055555555 عند البحث عن +201****5555
$phone = normalizePhoneNumber($rawPhone);

// ============================================================
// الخطوة 3: التحقق من صيغة الرقم بعد التوحيد
// ============================================================
// نتأكد أن الرقم أرقام فقط وطوله بين 10 و 15 خانة
if (!preg_match('/^[0-9]{10,15}$/', $phone)) {
    // رسالة توضح الصيغة المطلوبة مع الرقم بعد التوحيد
    printFailure(
        "رقم الهاتف غير صحيح — يجب أن يكون من 10 إلى 15 رقماً",
        400,
        [
            // ⭐ نُرجع الرقم بعد التوحيد ليرى الموظف ما فُهم من كتابته
            "normalized_phone" => $phone,
        ]
    );
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// ⭐ الخطوة 4: البحث عن الحساب مع ملفه الشخصي في استعلام واحد
//
// ⭐ LEFT JOIN لأن العميل قد يكون أنشأ الحساب ولم يُكمل ملفه
//    فالرقم يظل صالحاً للحجز ولو بلا صورة.
// ============================================================
// تجهيز استعلام يجمع حساب users مع ملف client_profiles
$stmt = $con->prepare(
    "SELECT
        -- ===== بيانات الحساب =====
        u.users_id,
        u.users_full_name,
        u.users_phone,
        u.users_type,
        u.users_is_active,
        u.users_approve,
        u.users_country,
        u.users_region,
        u.users_created_at,
        -- ⭐ هل أنشأه موظف أم سجّل نفسه؟
        u.users_created_by_admin,
        -- ⭐ اسم الموظف الذي أنشأ الحساب (إن وُجد)
        a.admin_full_name AS created_by_admin_name,
        -- ===== ⭐ بيانات ملف العميل إن وُجد =====
        cp.clients_id,
        cp.clients_profile_image,
        cp.clients_email,
        cp.clients_detailed_address,
        cp.clients_birth_date,
        cp.clients_nationality
     FROM users u
     -- ربط الموظف المنشئ (قد يكون NULL)
     LEFT JOIN admin_users a
            ON a.admin_id = u.users_created_by_admin
     -- ربط ملف العميل
     LEFT JOIN client_profiles cp
            ON cp.clients_users_id = u.users_id
     WHERE u.users_phone = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بالرقم الموحّد
$stmt->execute([$phone]);
// جلب الصف إن وُجد
$row = $stmt->fetch(PDO::FETCH_ASSOC);

// ============================================================
// ⭐ الحالة الأولى: الرقم غير مسجّل — يمكن إنشاء عميل جديد
// ============================================================
// إذا لم يوجد أي حساب بهذا الرقم
if (!$row) {
    // إرسال رد يوضح أن الرقم متاح
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // رسالة عربية جاهزة للعرض
        "message" => "لا يوجد عميل مسجّل بهذا الرقم — يمكنك إنشاء حساب جديد",
        // بيانات النتيجة
        "data"    => [
            // ⭐ المفتاح الذي تقرأه فلاتر لتحديد الخطوة التالية
            "state"            => "available",
            // ⭐ ترجمة الحالة جاهزة من PHP
            "state_ar"         => "غير مسجّل",
            // الرقم بعد التوحيد
            "normalized_phone" => $phone,
            // ⭐ هل يستطيع الموظف إنشاء حساب جديد؟
            "can_create"       => true,
            // لا بطاقة عميل
            "client"           => null,
        ],
    ]);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// ⭐ الخطوة 5: الرقم مسجّل — نفحص نوع الحساب
// ============================================================
// نوع الحساب المسجّل
$usersType = $row['users_type'];

// ============================================================
// ⭐ الحالة الثانية: الرقم مسجّل لكنه ليس حساب عميل
//
// ⚠️ مهم جداً: لا نُسمح بحجز خدمة لحساب مقدّم خدمة
//    لأن جدول الحجوزات يربط العميل بجدول users، ولو سمحنا
//    لاختلط الحسابان وصار الشخص يحجز من نفسه.
// ============================================================
if ($usersType !== 'client') {
    // إرسال رد يوضح أن الحساب ليس عميلاً
    echo json_encode([
        // حالة العملية
        "status"  => "success",
        // ⭐ رسالة توضح نوع الحساب الفعلي
        "message" => "هذا الرقم مسجّل كـ "
                     . ($usersType === 'provider' ? 'مقدّم خدمة' : $usersType)
                     . " وليس كعميل",
        // بيانات النتيجة
        "data"    => [
            // مفتاح الحالة للمنطق في فلاتر
            "state"            => "not_client",
            // ترجمة الحالة للعرض
            "state_ar"         => "حساب ليس عميلاً",
            // الرقم بعد التوحيد
            "normalized_phone" => $phone,
            // لا يمكن الإنشاء لأن الرقم محجوز
            "can_create"       => false,
            // ⭐ نُرجع نوع الحساب ليعرضه الموظف للموظف الآخر
            "users_type"       => $usersType,
            // لا بطاقة عميل
            "client"           => null,
        ],
    ]);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// ⭐ الخطوة 6: بناء رابط صورة العميل
//
// ⚠️ نرجع مستويين للوراء لأن الملف داخل admin/customers
//    وإلا لتكرر اسم المجلد في الرابط وأصبح 404
// ============================================================
// استخراج مسار جذر المشروع بالرجوع مستويين
$scriptDir = dirname(dirname(dirname($_SERVER['SCRIPT_NAME'])));

// بناء الرابط الكامل مع البروتوكول والمضيف
$baseUrl = (isset($_SERVER['HTTPS']) ? 'https' : 'http')
    . '://' . $_SERVER['HTTP_HOST']
    . ($scriptDir === '/' || $scriptDir === '\\' ? '' : $scriptDir);

// إزالة أي شرطة مائلة زائدة من النهاية
$baseUrl = rtrim($baseUrl, '/');

// ⭐ تنقية اسم الصورة من أي أسطر أو مسافات مسرَّبة
$imageName = trim(str_replace(["\n", "\r"], '', (string) $row['clients_profile_image']));

// بناء الرابط الكامل أو null إن لم توجد صورة
$profileImageUrl = $imageName !== ''
    ? $baseUrl . '/upload/clients/' . $imageName
    : null;

// ============================================================
// ⭐ الحالة الثالثة: عميل مسجّل — نُرجع بطاقته كاملة
// ============================================================
// إرسال بطاقة العميل
echo json_encode([
    // حالة العملية
    "status"  => "success",
    // رسالة عربية جاهزة للعرض
    "message" => "تم العثور على العميل: " . $row['users_full_name'],
    // بيانات النتيجة
    "data"    => [
        // مفتاح الحالة للمنطق في فلاتر
        "state"            => "is_client",
        // ترجمة الحالة للعرض
        "state_ar"         => "عميل مسجّل",
        // الرقم بعد التوحيد
        "normalized_phone" => $phone,
        // ⭐ لا حاجة لإنشاء حساب جديد
        "can_create"       => false,
        // ⭐ تحذير إن كان الحساب معطّلاً
        "warning"          => ((int) $row['users_is_active'] !== 1)
            ? "حساب العميل معطّل — فعّله من قسم العملاء قبل الحجز"
            : null,
        // ⭐⭐ بطاقة العميل
        "client" => [
            // معرّف المستخدم (يُمرَّر مع الحجز)
            "users_id"              => (int) $row['users_id'],
            // الاسم الكامل
            "users_full_name"       => $row['users_full_name'],
            // رقم الهاتف
            "users_phone"           => $row['users_phone'],
            // نوع الحساب (دائماً client هنا)
            "users_type"            => $row['users_type'],
            // هل الحساب مفعّل؟
            "users_is_active"       => (int) $row['users_is_active'],
            // هل تحقّق من رقمه بـ OTP؟
            "users_approve"         => (int) $row['users_approve'],
            // الدولة
            "users_country"         => $row['users_country'],
            // المنطقة
            "users_region"          => $row['users_region'],
            // تاريخ إنشاء الحساب
            "users_created_at"      => $row['users_created_at'],
            // ⭐ اسم الموظف الذي أنشأ الحساب إن وُجد
            "created_by_admin"      => $row['created_by_admin_name'],
            // ===== بيانات ملف العميل الاختياري =====
            // معرّف صف client_profiles (null إن لم يُكمل ملفه)
            "clients_id"            => $row['clients_id'] !== null
                ? (int) $row['clients_id']
                : null,
            // ⭐ رابط الصورة الشخصية الكامل
            "profile_image_url"     => $profileImageUrl,
            // البريد الإلكتروني
            "clients_email"         => $row['clients_email'],
            // العنوان التفصيلي
            "clients_detailed_address" => $row['clients_detailed_address'],
            // تاريخ الميلاد
            "clients_birth_date"    => $row['clients_birth_date'],
            // الجنسية
            "clients_nationality"   => $row['clients_nationality'],
        ],
    ],
]);
// إيقاف التنفيذ
exit;