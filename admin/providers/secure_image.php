<?php
// ============================================================
// ملف: admin/providers/secure_image.php
// الغرض: بوّابة آمنة لعرض مستندات مقدم الخدمة الحساسة
//        (البطاقة / الصحيفة الجنائية / إيصال المرافق)
//
// ⭐ لماذا نحتاج هذا الملف؟
//   مجلدات upload/id_cards و criminal_records و utility_receipt
//   محجوبة بـ .htaccess فلا يمكن فتح أي صورة برابط مباشر
//   وهذا الملف هو الطريق الوحيد لعرضها، وهو يتحقق من صلاحية
//   الإدارة أولاً ثم يقرأ الملف من القرص ويُرسله كصورة
//
// ⭐ لا نُمرّر اسم الملف في الرابط إطلاقاً
//   بل نُمرّر نوع المستند ومعرّف المستخدم، ونقرأ اسم الملف
//   من قاعدة البيانات — فلا يمكن التخمين ولا الوصول لملف آخر
//
// الحقول المطلوبة: type, providers_users_id
// أنواع المستندات: id_front / id_back / criminal / utility
// الطريقة: GET
// ============================================================

// ربط ملف الاتصال بقاعدة البيانات (مستويان للوراء)
include "../../connect.php";

// ⭐ حماية ملف الإدارة: يجب إرسال المفتاح السري
// ⚠️ لو أردت تعطيل الحماية مؤقتاً أثناء التطوير ضع // قبل السطر التالي
//checkAdminKey();
// ⭐ التحقق من توكن الإدارة وجلب بيانات الموظف الحالي
// أي موظف مسجّل دخوله (مدير أو خدمة عملاء) يستطيع القراءة
$currentAdmin = checkAdminToken();

// ============================================================
// الخطوة 1: استقبال البيانات
// ============================================================
// نوع المستند المطلوب عرضه
$type     = filterRequest("type");
// معرّف مقدم الخدمة صاحب المستند
$users_id = filterRequest("providers_users_id");

// ============================================================
// الخطوة 2: التحقق من الحقول الإجبارية
// ============================================================
// إذا نقص أي حقل نوقف التنفيذ
if (empty($type) || empty($users_id)) {
    // رسالة توضح الحقول المطلوبة
    printFailure("Required fields: type, providers_users_id");
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 3: خريطة أنواع المستندات
// تربط كل نوع بعموده في قاعدة البيانات ومجلده على القرص
// ⚠️ هذه الخريطة هي الحماية الأساسية: لا نقبل إلا هذه الأنواع
//    فلا يمكن لأحد تمرير مسار عشوائي لقراءة ملف من السيرفر
// ============================================================
$documentMap = [
    // البطاقة الأمامية
    'id_front' => [
        'column' => 'providers_id_card_front',
        'folder' => 'id_cards',
    ],
    // البطاقة الخلفية
    'id_back'  => [
        'column' => 'providers_id_card_back',
        'folder' => 'id_cards',
    ],
    // الصحيفة الجنائية
    'criminal' => [
        'column' => 'providers_criminal_record_image',
        'folder' => 'criminal_records',
    ],
    // إيصال المرافق
    'utility'  => [
        'column' => 'providers_utility_receipt_image',
        'folder' => 'utility_receipt',
    ],
];

// إذا كان النوع غير معروف نرفض الطلب
if (!isset($documentMap[$type])) {
    // رسالة توضح الأنواع المسموحة
    printFailure("type must be one of: " . implode(', ', array_keys($documentMap)));
    // إيقاف التنفيذ
    exit;
}

// قراءة اسم العمود والمجلد الخاصين بهذا النوع
$column = $documentMap[$type]['column'];
$folder = $documentMap[$type]['folder'];

// ============================================================
// الخطوة 4: قراءة اسم الملف من قاعدة البيانات
// ⚠️ اسم العمود يأتي من خريطتنا الثابتة وليس من المستخدم
//    لذلك دمجه في نص الاستعلام آمن تماماً هنا
// ============================================================
$stmt = $con->prepare(
    "SELECT $column AS file_name
     FROM professional_profiles
     WHERE providers_users_id = ?
     LIMIT 1"
);
// تنفيذ الاستعلام بتمرير معرّف المستخدم
$stmt->execute([$users_id]);
// جلب صف النتيجة
$row = $stmt->fetch(PDO::FETCH_ASSOC);

// إذا لم يوجد سجل أو لم يُرفع هذا المستند نرجع 404
if (!$row || empty($row['file_name'])) {
    // رسالة توضح أن المستند غير موجود
    printFailure("Document not found", 404);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 5: تنظيف اسم الملف من أي محاولة تسلّق للمجلدات
// basename تُزيل أي مسار مثل ../../ فلا يمكن قراءة ملف خارج المجلد
// ============================================================
// استخراج اسم الملف فقط بدون أي مسار
$fileName = basename($row['file_name']);

// بناء المسار الكامل للملف على القرص
$filePath = __DIR__ . "/../../upload/" . $folder . "/" . $fileName;

// ============================================================
// الخطوة 6: التحقق من وجود الملف فعلياً على القرص
// ============================================================
// قد يكون السجل موجوداً في قاعدة البيانات والملف محذوفاً
if (!file_exists($filePath) || !is_file($filePath)) {
    // رسالة توضح أن الملف مفقود من السيرفر
    printFailure("Document file is missing on the server", 404);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 7: تحديد نوع المحتوى (MIME type) حسب امتداد الملف
// ============================================================
// استخراج الامتداد وتحويله لحروف صغيرة
$extension = strtolower(pathinfo($fileName, PATHINFO_EXTENSION));

// خريطة الامتدادات المسموحة وأنواع محتواها
$mimeMap = [
    'jpg'  => 'image/jpeg',
    'jpeg' => 'image/jpeg',
    'png'  => 'image/png',
    'gif'  => 'image/gif',
    'webp' => 'image/webp',
    'pdf'  => 'application/pdf',
];

// إذا كان الامتداد غير مسموح نرفض العرض
if (!isset($mimeMap[$extension])) {
    // رسالة توضح أن نوع الملف غير مدعوم
    printFailure("Unsupported document type", 415);
    // إيقاف التنفيذ
    exit;
}

// ============================================================
// الخطوة 8: إرسال الملف كصورة
// ⚠️ نُلغي هيدر Content-Type: application/json الذي ضبطه connect.php
//    لأننا نُرسل صورة وليس JSON
// ============================================================
// إزالة أي هيدرات سابقة قد تُفسد الصورة
if (!headers_sent()) {
    // حذف هيدر نوع المحتوى الذي ضبطه connect.php
    header_remove('Content-Type');
}

// ضبط نوع المحتوى الصحيح للصورة
header('Content-Type: ' . $mimeMap[$extension]);
// إخبار المتصفح بحجم الملف
header('Content-Length: ' . filesize($filePath));
// عرض الملف داخل الصفحة وليس تنزيله
header('Content-Disposition: inline; filename="' . $fileName . '"');
// ⚠️ منع تخزين المستند الحساس في كاش المتصفح أو الوسائط
header('Cache-Control: private, no-store, no-cache, must-revalidate');
header('Pragma: no-cache');
// منع المتصفح من تخمين نوع المحتوى (حماية ضد XSS)
header('X-Content-Type-Options: nosniff');

// قراءة الملف من القرص وإرساله للمتصفح مباشرة
readfile($filePath);
// إيقاف التنفيذ فوراً حتى لا يُضاف أي محتوى بعد الصورة
exit;
?>